//go:build goexperiment.jsonv2

package integrationtests

import (
	jsonv1 "encoding/json"
	jsonv2 "encoding/json/v2"
	"strings"
	"testing"
)

// HookedStruct exercises the opt-in JSON interop hooks. Its presence in the
// test suite guarantees MarshalJSON/UnmarshalJSON are emitted and satisfy
// the stdlib (v1 and v2) interfaces at compile time.
//
//ggen:generate marshal unmarshal
type HookedStruct struct {
	Name string `json:"name" ggen:"required,minlen=1,maxlen=20"`
	N    int    `json:"n" ggen:"gte=0,lte=100"`
}

// Compile-time interface satisfaction. If any of these assertions fail to
// compile, the corresponding hook was not emitted. ggen only emits the
// []byte-based MarshalJSON / UnmarshalJSON hooks — the streaming jsontext
// variants (MarshalerTo / UnmarshalerFrom) were removed along with the
// jsontext-backed decode path.
var (
	_ jsonv1.Marshaler = HookedStruct{}
	_ jsonv2.Marshaler = HookedStruct{}

	_ jsonv1.Unmarshaler = (*HookedStruct)(nil)
	_ jsonv2.Unmarshaler = (*HookedStruct)(nil)
)

// TestHookedValidationPropagates verifies that validation errors generated by
// the hooks correctly dispatch to our code and the error is not swallowed.
//
//ggen:generate are surfaced through both jsonv1.Unmarshal and jsonv2.Unmarshal, i.e.
func TestHookedValidationPropagates(t *testing.T) {
	// N out of range (lte=100) — violates generated validation.
	bad := []byte(`{"name":"ok","n":200}`)

	// jsonv1 path
	{
		var got HookedStruct
		err := jsonv1.Unmarshal(bad, &got)
		if err == nil {
			t.Fatal("v1 unmarshal: expected validation error, got nil")
		}
		if !strings.Contains(err.Error(), "exceeds maximum") {
			t.Errorf("v1 error = %q, want to contain 'exceeds maximum'", err.Error())
		}
	}

	// jsonv2 path
	{
		var got HookedStruct
		err := jsonv2.Unmarshal(bad, &got)
		if err == nil {
			t.Fatal("v2 unmarshal: expected validation error, got nil")
		}
		if !strings.Contains(err.Error(), "exceeds maximum") {
			t.Errorf("v2 error = %q, want to contain 'exceeds maximum'", err.Error())
		}
	}
}

// TestHookedRoundtrip confirms valid data round-trips cleanly through both
// stdlib entry points via the generated hooks.
func TestHookedRoundtrip(t *testing.T) {
	in := HookedStruct{Name: "ok", N: 42}

	for _, tc := range []struct {
		name      string
		marshal   func(any) ([]byte, error)
		unmarshal func([]byte, any) error
	}{
		{"jsonv1", jsonv1.Marshal, jsonv1.Unmarshal},
		{"jsonv2",
			func(v any) ([]byte, error) { return jsonv2.Marshal(v) },
			func(b []byte, v any) error { return jsonv2.Unmarshal(b, v) }},
	} {
		t.Run(tc.name, func(t *testing.T) {
			out, err := tc.marshal(in)
			if err != nil {
				t.Fatalf("marshal: %v", err)
			}
			var got HookedStruct
			if err := tc.unmarshal(out, &got); err != nil {
				t.Fatalf("unmarshal: %v", err)
			}
			if got != in {
				t.Errorf("roundtrip: got %+v want %+v", got, in)
			}
		})
	}
}
