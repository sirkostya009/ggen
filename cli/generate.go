// streamUnknownKey is the stream-scanner counterpart of unknownKey.
// `key` is an alias into the stream buffer (Stream.KeyView is
// zero-copy on the no-escape happy path). ConsumeColon shifts the
// buffer and invalidates the alias, so any value that survives past
// that shift — stored map keys, retained errors — must hold an owned
// copy, captured BEFORE ConsumeColon runs. The immediate-return
// branch is safe to read the alias directly since the function exits
// before any subsequent Stream call.
func streamUnknownKey(s StructInfo, posVar string) string {
	_ = posVar
	if inline := s.InlineField(); inline.Inline {
		// Set the field marker once ownKey has been cloned — the alias
		// from KeyView is unsafe across compaction inside the value
		// decode.
		chk := streamErrCheck("ownKey")
		prelude := fmt.Sprintf(`ownKey := strings.Clone(key)
err = s.ConsumeColon()
%[3]sif result.%[1]s == nil { result.%[1]s = make(%[2]s) }
`, inline.GoName, inline.GoType, chk)
		switch inline.ElemKind {
		case KindAny:
			anyFn := "s.Any"
			if s.UseNumber {
				anyFn = "s.AnyNumber"
			}
			return prelude + fmt.Sprintf(`result.%[1]s[ownKey], err = %[2]s()
%[3]s`, inline.GoName, anyFn, chk)
		case KindString:
			return prelude + fmt.Sprintf(`result.%[1]s[ownKey], err = s.String()
%[2]s`, inline.GoName, chk)
		case KindStruct:
			if isGenerated(inline.ElemType) {
				return prelude + fmt.Sprintf(`var _iv %[1]s
_iv, err = _iv.DecodeFromStream(s)
%[3]sresult.%[2]s[ownKey] = _iv
`, inline.ElemType, inline.GoName, nestedDecodeErrCheck("ownKey", s.MultiErr, false))
			}
		}
		return prelude + fmt.Sprintf(`start := s.Pos
prevPin := s.Shift
s.Shift = false
err = s.SkipValue()
s.Shift = prevPin
%[3]svar _iv %[1]s
if err = json.Unmarshal(s.Bytes()[start:s.Pos], &_iv); err != nil { return result, decode.NewParseErr(ownKey, s.Pos, err) }
result.%[2]s[ownKey] = _iv
`, inline.ElemType, inline.GoName, chk)
	}
	if s.IgnoreUnknown {
		chk := streamErrCheck("strings.Clone(key)")
		return fmt.Sprintf(`err = s.ConsumeColon()
%[1]serr = s.SkipValue()
%[1]s`, chk)
	}
	if s.MultiErr {
		chk := streamErrCheck("strings.Clone(key)")
		return fmt.Sprintf(`errs = append(errs, &validation.UnknownKeyError{Path: []string{strings.Clone(key)}})
err = s.ConsumeColon()
%[1]serr = s.SkipValue()
%[1]s`, chk)
	}
	return "return result, &validation.UnknownKeyError{Path: []string{strings.Clone(key)}}\n"
}

func renderStreamStringTag(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	_ = posVar // stream-path uses s.Pos directly
	field := fieldLit(f)
	chk := streamErrCheck(field)
	// Brace-less — see renderStringTag.
	b.WriteString("var sv string\n")
	b.WriteString("sv, err = s.KeyView()\n")
	b.WriteString(chk)
	switch f.Kind {
	case KindBool:
		fmt.Fprintf(b, `switch sv {
case "true": %[1]s = true
case "false": %[1]s = false
default: return result, decode.NewParseErr(%[2]s, s.Pos, scan.ErrBadBool)
}
`, ref, field)
	case KindFloat32, KindFloat64:
		b.WriteString("f, err := strconv.ParseFloat(sv, 64)\n" + chk)
		if f.Kind == KindFloat32 {
			fmt.Fprintf(b, "%s = float32(f)\n", ref)
		} else {
			fmt.Fprintf(b, "%s = f\n", ref)
		}
	case KindUint, KindUint8, KindUint16, KindUint32, KindUint64:
		b.WriteString("u, err := strconv.ParseUint(sv, 10, 64)\n" + chk)
		if f.Kind == KindUint64 {
			fmt.Fprintf(b, "%s = u\n", ref)
		} else {
			fmt.Fprintf(b, "%s = %s(u)\n", ref, f.GoType)
		}
	case KindInt, KindInt8, KindInt16, KindInt32, KindInt64:
		b.WriteString("n, err := strconv.ParseInt(sv, 10, 64)\n" + chk)
		if f.Kind == KindInt64 {
			fmt.Fprintf(b, "%s = n\n", ref)
		} else {
			fmt.Fprintf(b, "%s = %s(n)\n", ref, f.GoType)
		}
	case KindString:
		fmt.Fprintf(b, "%s = string(sv)\n", ref)
	}
}

func renderStreamField(f FieldInfo, ref, posVar string) string {
	// See renderField — `,string` on bool is a no-op to match jsonv2.
	if f.String && f.Kind != KindBool {
		var out bytes.Buffer
		renderStreamStringTag(&out, f, ref, posVar)
		if !f.NoValidate {
			validateAndModStream(&out, f, ref)
		}
		return out.String()
	}
	b := getSmall()
	defer putSmall(b)
	field := fieldLit(f)
	chk := streamErrCheck(field)
	if f.Pointer {
		// See the bytes-path comment: custom `@Func` rules want the pointer;
		// built-ins want the deref'd leaf. Partition both lists.
		builtinV, customV := partitionCustomValidation(f.Validation)
		builtinM, customM := partitionCustomMods(f.Mods)
		rm := streamReadMore(field, "0", false)
		rmKi := strings.Replace(rm, "if s.Pos >=", "if s.Pos+ki >=", 1)
		// Decode-into-receiver, any pointer depth — see renderField. null →
		// nil outer; otherwise parse the leaf into temp `v` FIRST (no mutation
		// on parse failure), then the assign cascade reuses the non-nil prefix
		// of the chain and allocates only the nil tail. Mergeable leaf seeded
		// from the carried-in value.
		depth, leafType := pointerDepth(f.GoType)
		leaf := f
		leaf.Pointer = false
		leaf.PointeeType = ""
		leaf.GoType = leafType
		leaf.Kind = resolveKind(leafType)
		leaf.Validation = builtinV
		leaf.Mods = builtinM
		leaf.AtDispatch = false
		leaf.TargetNil = false
		// Widened numeric leaf: scan into a wide temp (drops the stream
		// path's separate widening var) and cast at the assign (`new(int(v))`).
		scanType, valExpr := leafType, "v"
		if wide, wideKind, cast := widenedLeafCast(leaf.Kind, leafType); wide != "" {
			leaf.Kind, leaf.GoType, scanType, valExpr = wideKind, wide, wide, cast+"(v)"
		}
		// At dispatch level the null branch breaks straight to the comma
		// handling — the non-null decode stays at case-body level.
		flat := nullBreakOK(f)
		fmt.Fprintf(b, `%[2]sif s.Bytes()[s.Pos] == 'n' {
	for ki := 1; ki < 4; ki++ {
		%[3]sif s.Bytes()[s.Pos+ki] != "null"[ki] { return result, decode.NewParseErr(%[4]s, s.Pos, scan.ErrBadLiteral) }
	}
	s.Pos += 4
	%[1]s = nil
`, ref, rm, rmKi, field)
		if flat {
			b.WriteString("break\n}\n")
		} else {
			b.WriteString("} else {\n")
		}
		fmt.Fprintf(b, "var v %s\n", scanType)
		if !f.TargetNil {
			emitPointerSeed(b, ref, depth, leaf.Kind)
		}
		b.WriteString(renderStreamField(leaf, "v", posVar))
		if f.TargetNil {
			// Target was declared `var x *T` just above by the caller —
			// known nil, no chain to reuse: straight new-chain assign.
			fmt.Fprintf(b, "%s = %s\n", ref, newChain(valExpr, depth))
		} else {
			emitPointerAssign(b, ref, depth, valExpr)
		}
		if !flat {
			b.WriteString("}\n")
		}
		if !f.NoValidate && (len(customV) > 0 || len(customM) > 0) {
			outer := f
			outer.Validation = customV
			outer.Mods = customM
			validateAndModStream(b, outer, ref)
		}
		return b.String()
	}
	primScan := func(method string) {
		fmt.Fprintf(b, `%[1]s, err = s.%[2]s()
%[3]s`, ref, method, chk)
	}
	widenedScan := func(wideType, wideVar, method, castTo string) {
		fmt.Fprintf(b, `var %[1]s %[2]s
%[1]s, err = s.%[3]s()
%[6]s%[4]s = %[5]s(%[1]s)
`, wideVar, wideType, method, ref, castTo, chk)
	}
	switch f.Kind {
	case KindString:
		primScan("String")
	case KindBool:
		primScan("Bool")
	case KindInt, KindInt8, KindInt16, KindInt32:
		widenedScan("int64", "iv", "Int64", f.GoType)
	case KindInt64:
		primScan("Int64")
	case KindUint, KindUint8, KindUint16, KindUint32:
		widenedScan("uint64", "uv", "Uint64", f.GoType)
	case KindUint64:
		primScan("Uint64")
	case KindFloat32:
		widenedScan("float64", "fv", "Float64", "float32")
	case KindFloat64:
		primScan("Float64")
	case KindStruct:
		if isGenerated(f.GoType) {
			fmt.Fprintf(b, `%[1]s, err = %[1]s.DecodeFromStream(s)
%[2]s`, ref, nestedDecodeErrCheck(fieldLit(f), f.MultiErr, false))
		} else {
			b.WriteString(renderCrossPkgStructStreamDecode(f, ref, posVar))
		}
	case KindSlice:
		renderStreamSlice(b, f, ref, posVar)
	case KindArray:
		emitStreamSliceRead(b, f, ref, posVar, 0)
	case KindMap:
		renderStreamMap(b, f, ref, posVar)
	case KindBytes:
		renderStreamBytes(b, f, ref, posVar)
	case KindTime:
		renderStreamTime(b, f, ref, posVar)
	case KindDuration:
		renderStreamDuration(b, f, ref, posVar)
	case KindNetIP:
		renderStreamNetIP(b, f, ref, posVar)
	case KindNetipAddr:
		renderStreamNetipAddr(b, f, ref, posVar)
	case KindNetipPrefix:
		renderStreamNetipPrefix(b, f, ref, posVar)
	case KindRawJSON:
		renderStreamRawJSON(b, f, ref, posVar)
	case KindURL:
		renderStreamURL(b, f, ref, posVar)
	case KindBigInt:
		renderStreamBigInt(b, f, ref, posVar)
	case KindBigFloat:
		renderStreamBigFloat(b, f, ref, posVar)
	case KindBigRat:
		renderStreamBigRat(b, f, ref, posVar)
	case KindSQLNull:
		renderStreamSQLNull(b, f, ref, posVar)
	case KindAny:
		renderStreamAny(b, f, ref, posVar)
	default:
		fmt.Fprintf(b, `err = s.SkipValue()
%s`, chk)
	}
	if !f.NoValidate {
		validateAndModStream(b, f, ref)
	}
	return b.String()
}

