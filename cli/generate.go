// renderCrossPkgStructDecode emits the decode body for a cross-package /
// unannotated struct field. When f.Iface is resolved (packages-aware
// loader gave us full type info), branches directly to the appropriate
// method based on the type's actual interface implementations — zero
// runtime probes. Without resolution (AST-only mode), falls through to
// the runtime-probe cascade so the generator still produces correct code.
func renderCrossPkgStructDecode(f FieldInfo, ref, posVar string) string {
	if f.Iface.Resolved {
		switch {
		case f.Iface.ByteDecoder:
			// Type was generated by ggen in another package — call
			// DecodeFrom directly. The new signature takes `data[i:]`
			// and returns bytes consumed; advance posVar by that count.
			return fmt.Sprintf(`var _n int
%[1]s, _n, err = %[1]s.DecodeFrom(data[%[2]s:])
%[2]s += _n
%[3]s`, ref, posVar, nestedDecodeErrCheck(fieldLit(f), f.MultiErr, true))

		case f.Iface.JSONUnmarshaler:
			chk := bytesErrCheck(fieldLit(f), posVar)
			return fmt.Sprintf(`start := %[1]s
%[1]s, err = scan.SkipValue(data, start)
%[3]serr = %[2]s.UnmarshalJSON(data[start:%[1]s])
%[3]s`, posVar, ref, chk)

		case f.Iface.TextUnmarshaler:
			chk := bytesErrCheck(fieldLit(f), posVar)
			return fmt.Sprintf(`var ts string
ts, %[1]s, err = scan.String(data, %[1]s)
%[3]serr = %[2]s.UnmarshalText(unsafe.Slice(unsafe.StringData(ts), len(ts)))
%[3]s`, posVar, ref, chk)

		default:
			chk := bytesErrCheck(fieldLit(f), posVar)
			return fmt.Sprintf(`start := %[1]s
%[1]s, err = scan.SkipValue(data, start)
%[3]serr = json.Unmarshal(data[start:%[1]s], &%[2]s)
%[3]s`, posVar, ref, chk)
		}
	}
	chk := bytesErrCheck(fieldLit(f), posVar)
	return fmt.Sprintf(`start := %[1]s
%[1]s, err = scan.SkipValue(data, start)
%[3]serr = json.Unmarshal(data[start:%[1]s], &%[2]s)
%[3]s`, posVar, ref, chk)
}

// renderCrossPkgStructAppend is the marshal counterpart for cross-package
// struct fields. Resolved → static branch on what the type implements.
// Unresolved → runtime cascade.
func renderCrossPkgStructAppend(f FieldInfo, ref string) string {
	// Field-suffixed temp — fields emit at function scope, so two cross-pkg
	// fields in one struct would collide on a shared name.
	tmp := "b" + strings.ReplaceAll(f.GoName, ".", "")
	if f.Iface.Resolved {
		switch {
		case f.Iface.AppendJSON:
			// Same shape as in-pass branch — direct AppendJSON call.
			return fmt.Sprintf("if dst, err = %s.AppendJSON(dst); err != nil { return dst, err }\n", ref)

		case f.Iface.JSONMarshaler:
			return fmt.Sprintf(`var %[1]s []byte
%[1]s, err = %[2]s.MarshalJSON()
if err != nil { return dst, err }
dst = append(dst, %[1]s...)
`, tmp, ref)

		case f.Iface.TextAppender:
			// Direct AppendText is preferred over MarshalText: no fresh
			// []byte alloc, no intermediate string. Go 1.24+ encoding.TextAppender.
			return fmt.Sprintf(`dst = append(dst, '"')
if dst, err = %s.AppendText(dst); err != nil { return dst, err }
dst = append(dst, '"')
`, ref)

		case f.Iface.TextMarshaler:
			return fmt.Sprintf(`var %[1]s []byte
%[1]s, err = %[2]s.MarshalText()
if err != nil { return dst, err }
dst = append(dst, '"')
dst = %[3]s(dst, encode.BytesToString(%[1]s))
`, tmp, ref, appendStrFn(f.HTMLEscape))

		default:
			return fmt.Sprintf(`var %[1]s []byte
%[1]s, err = json.Marshal(%[2]s)
if err != nil { return dst, err }
dst = append(dst, %[1]s...)
`, tmp, ref)
		}
	}
	// Unresolved (AST-only) — plain encoding/json fallback.
	return fmt.Sprintf(`var %[1]s []byte
%[1]s, err = json.Marshal(%[2]s)
if err != nil { return dst, err }
dst = append(dst, %[1]s...)
`, tmp, ref)
}

// renderCrossPkgStructStreamDecode is the streaming counterpart of
// renderCrossPkgStructDecode. Same static-vs-runtime branching.
func renderCrossPkgStructStreamDecode(f FieldInfo, ref, posVar string) string {
	_ = posVar
	chk := streamErrCheck(fieldLit(f))
	if f.Iface.Resolved {
		switch {
		case f.Iface.StreamDecoder:
			return fmt.Sprintf(`%[1]s, err = %[1]s.DecodeFromStream(s)
%[2]s`, ref, nestedDecodeErrCheck(fieldLit(f), f.MultiErr, false))

		case f.Iface.JSONUnmarshaler:
			return fmt.Sprintf(`start := s.Pos
prevPin := s.Shift
s.Shift = false
err = s.SkipValue()
s.Shift = prevPin
%[2]serr = %[1]s.UnmarshalJSON(s.Bytes()[start:s.Pos])
%[2]s`, ref, chk)

		case f.Iface.TextUnmarshaler:
			// StringView: UnmarshalText must not retain its arg (encoding
			// contract), and the bytes path already passes an aliased slice
			// here — see Stream.StringView.
			return fmt.Sprintf(`var ts string
ts, err = s.StringView()
%[2]serr = %[1]s.UnmarshalText(unsafe.Slice(unsafe.StringData(ts), len(ts)))
%[2]s`, ref, chk)

		default:
			return fmt.Sprintf(`start := s.Pos
prevPin := s.Shift
s.Shift = false
err = s.SkipValue()
s.Shift = prevPin
%[2]serr = json.Unmarshal(s.Bytes()[start:s.Pos], &%[1]s)
%[2]s`, ref, chk)
		}
	}
	// Unresolved (AST-only) — plain encoding/json fallback.
	return fmt.Sprintf(`start := s.Pos
prevPin := s.Shift
s.Shift = false
err = s.SkipValue()
s.Shift = prevPin
%[2]serr = json.Unmarshal(s.Bytes()[start:s.Pos], &%[1]s)
%[2]s`, ref, chk)
}

// renderRawJSON aliases data[start:end] into the field — zero copy.
// Works for both json.RawMessage and jsontext.Value because both have
// underlying type []byte.
func renderRawJSON(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	chk := bytesErrCheck(fieldLit(f), posVar)
	fmt.Fprintf(b, `start := %[1]s
%[1]s, err = scan.SkipValue(data, start)
%[3]s%[2]s = data[start:%[1]s]
`, posVar, ref, chk)
}

// renderURL parses a JSON string via url.Parse. The dereference is
// safe because Parse returns a non-nil *URL on success.
func renderURL(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	field := fieldLit(f)
	b.WriteString("var s string\n")
	inlineScanString(b, posVar, "s", posVar, field)
	fmt.Fprintf(b, `var u *url.URL
u, err = url.Parse(s)
if err != nil { return result, %[2]s, decode.NewParseErr(%[3]s, %[2]s, err) }
%[1]s = *u
`, ref, posVar, field)
}

// renderBigInt reads a bare JSON number, hands the raw bytes to
// big.Int.SetString. The number can be arbitrarily long — no overflow.
// The literal is aliased through unsafe.String — SetString reads it left
// to right and copies the digits into its own internal storage, so the
// alias is dead by the time data could be mutated.
func renderBigInt(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	field := fieldLit(f)
	fmt.Fprintf(b, `start := %[1]s
%[1]s, err = scan.SkipValue(data, start)
if err != nil { return result, %[1]s, decode.NewParseErr(%[3]s, %[1]s, err) }
if _, ok := (&%[2]s).SetString(unsafe.String(unsafe.SliceData(data[start:]), %[1]s-start), 10); !ok {
	return result, %[1]s, decode.NewParseErr(%[3]s, %[1]s, scan.ErrBadNumber)
}
`, posVar, ref, field)
}

// renderBigFloat reads a JSON-string-wrapped numeric literal into big.Float
// at the default precision. Wrapping matches jsonv2's wire format for
// big.Float; bare numbers are not accepted (use big.Int or float64 for those).
func renderBigFloat(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	field := fieldLit(f)
	b.WriteString("var s string\n")
	inlineScanString(b, posVar, "s", posVar, field)
	fmt.Fprintf(b, `if _, _, err := (&%[1]s).Parse(s, 10); err != nil {
	return result, %[2]s, decode.NewParseErr(%[3]s, %[2]s, err)
}
`, ref, posVar, field)
}

// renderBigRat reads a JSON string of the form "num" or "num/denom"
// and feeds it to big.Rat.SetString. Lossless — fractions stay exact.
func renderBigRat(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	field := fieldLit(f)
	b.WriteString("var s string\n")
	inlineScanString(b, posVar, "s", posVar, field)
	fmt.Fprintf(b, `if _, ok := (&%[1]s).SetString(s); !ok {
	return result, %[2]s, decode.NewParseErr(%[3]s, %[2]s, scan.ErrBadNumber)
}
`, ref, posVar, field)
}

// renderSQLNull emits decode for a database/sql.NullX field. Probes for
// `null` first; on a value, parses with the inner-kind primitive and sets
// Valid=true. The outer-scope local is `nv` (null-inner-value) — chosen
// to avoid collisions with the `v` that the time/string sub-renderers
// declare internally.
func renderSQLNull(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	spec, ok := SQLNullSpec(f.GoType)
	if !ok {
		return
	}
	field := fieldLit(f)
	var inner bytes.Buffer
	switch spec.Inner {
	case KindString:
		inner.WriteString("var nv string\n")
		inlineScanString(&inner, posVar, "nv", posVar, field)
	case KindBool:
		inner.WriteString("var nv bool\n")
		fmt.Fprintf(&inner, "nv, %[1]s, err = scan.Bool(data, %[1]s)\n", posVar)
		fmt.Fprintf(&inner, "if err != nil { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, err) }\n", posVar, field)
	case KindInt64:
		inner.WriteString("var nv int64\n")
		inlineScanInt64(&inner, posVar, "nv", "", field)
	case KindInt32, KindInt16:
		fmt.Fprintf(&inner, "var nv %s\n", spec.Type)
		inlineScanInt64(&inner, posVar, "nv", spec.Type, field)
	case KindUint8:
		fmt.Fprintf(&inner, "var nv %s\n", spec.Type)
		inlineScanUint64(&inner, posVar, "nv", spec.Type, field)
	case KindFloat64:
		inner.WriteString("var nv float64\n")
		fmt.Fprintf(&inner, "nv, %[1]s, err = scan.Float64(data, %[1]s)\n", posVar)
		fmt.Fprintf(&inner, "if err != nil { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, err) }\n", posVar, field)
	case KindTime:
		tf := FieldInfo{JSONName: f.JSONName, Format: f.Format}
		inner.WriteString("var nv time.Time\n")
		renderTime(&inner, tf, "nv", posVar)
	}
	fmt.Fprintf(b, `if %s+4 <= len(data) && data[%s] == 'n' && data[%s+1] == 'u' && data[%s+2] == 'l' && data[%s+3] == 'l' {
	%s = sql.%s{}
	%s += 4
} else {
	%s
	%s = sql.%s{%s: nv, Valid: true}
}
`, posVar, posVar, posVar, posVar, posVar,
		ref, sqlTypeName(f.GoType), posVar,
		inner.String(),
		ref, sqlTypeName(f.GoType), spec.Field)
}

// sqlTypeName returns the bare type name from a `sql.NullX` qualified name.
func sqlTypeName(goType string) string {
	if i := strings.IndexByte(goType, '.'); i >= 0 {
		return goType[i+1:]
	}
	return goType
}

// renderAny captures the raw JSON span and hands it to encoding/json,
// which decodes into Go's reflective any (map/slice/string/float64/bool/nil).
// Slow path on purpose — a hand-rolled any decoder is a separate project.
func renderAny(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	fn := "scan.Any"
	if f.UseNumber {
		fn = "scan.AnyNumber"
	}
	chk := bytesErrCheck(fieldLit(f), posVar)
	fmt.Fprintf(b, `%[1]s, %[2]s, err = %[3]s(data, %[2]s)
%[4]s`, ref, posVar, fn, chk)
}

// needsSeen reports whether a seen<Field> bool is required for f inside
// struct s. The flag is always tracked except for inline catch-all maps:
//   - default mode uses it as a duplicate-key guard (error on second hit).
//   - AllowDups mode uses it to skip subsequent occurrences (first-wins
//     semantics — the first key-value pair is parsed, later ones are
//     advanced past via scan.SkipValue without being decoded).
//   - validation mode uses it for the required-field post-loop check.
//
// Inline fields don't take this path; they're absorbed into the catch-all
// map regardless of how many times their JSON key appears.
func needsSeen(f FieldInfo) bool {
	return !f.Inline
}

// seenBitmaskThreshold is the field count above which the codegen swaps
// per-field `bool` locals for a packed bitmask. Bools are simpler and
// fit in registers for narrow structs; for wide structs, the cumulative
// stack frame (1 byte/field) and cache pressure dominate, and a single
// uint64 (or array thereof for >64 fields) wins.
const seenBitmaskThreshold = 32

// useSeenBitmask reports whether struct s should use the packed-bitmask
// shape for its seen-tracking instead of per-field bools.
func useSeenBitmask(s StructInfo) bool {
	if len(s.Fields) <= seenBitmaskThreshold {
		return false
	}
	for _, f := range s.Fields {
		if !f.Inline && needsSeen(f) {
			return true
		}
	}
	return false
}

// seenBitIndex assigns a stable bit index to f based on its position in
// s.Fields. Inline fields are skipped (they don't need seen tracking) but
// still occupy an index — small waste, simpler addressing.
func seenBitIndex(s StructInfo, f FieldInfo) int {
	for i, ff := range s.Fields {
		if ff.GoName == f.GoName {
			return i
		}
	}
	return -1
}

func seenWordCount(s StructInfo) int {
	return (len(s.Fields) + 63) / 64
}

// seenDecl emits the declaration line(s) for the bitmask, or the empty
// string when bools-mode is in use (caller emits per-field bools).
func seenDecl(s StructInfo) string {
	if !useSeenBitmask(s) {
		return ""
	}
	if seenWordCount(s) == 1 {
		return "var seen uint64\n"
	}
	return fmt.Sprintf("var seen [%d]uint64\n", seenWordCount(s))
}

// seenAccess returns the read expression for f's seen bit. In bool mode
// it's the local `seen<GoName>`; in bitmask mode it's `seen & (1<<N)
// != 0` (or the array-indexed form for >64 fields).
func seenAccess(s StructInfo, f FieldInfo) string {
	if !useSeenBitmask(s) {
		return "seen" + f.GoName
	}
	bit := seenBitIndex(s, f)
	if seenWordCount(s) == 1 {
		return fmt.Sprintf("seen&(1<<%d) != 0", bit)
	}
	return fmt.Sprintf("seen[%d]&(1<<%d) != 0", bit/64, bit%64)
}

// seenNotAccess is the negated counterpart of seenAccess — true when the
// bit is unset.
func seenNotAccess(s StructInfo, f FieldInfo) string {
	if !useSeenBitmask(s) {
		return "!seen" + f.GoName
	}
	bit := seenBitIndex(s, f)
	if seenWordCount(s) == 1 {
		return fmt.Sprintf("seen&(1<<%d) == 0", bit)
	}
	return fmt.Sprintf("seen[%d]&(1<<%d) == 0", bit/64, bit%64)
}

// seenSet emits a statement that marks f's seen bit. Trailing newline
// is intentional so callers can concatenate freely.
func seenSet(s StructInfo, f FieldInfo) string {
	if !useSeenBitmask(s) {
		return "seen" + f.GoName + " = true\n"
	}
	bit := seenBitIndex(s, f)
	if seenWordCount(s) == 1 {
		return fmt.Sprintf("seen |= 1<<%d\n", bit)
	}
	return fmt.Sprintf("seen[%d] |= 1<<%d\n", bit/64, bit%64)
}

// unknownKey emits code for the default branch of the key
// switch. Three modes, in precedence order:
//  1. Struct has an inline catch-all map field — absorb the unknown key/value.
//  2. s.IgnoreUnknown — SkipValue and continue.
//  3. Default — return a validation.Error{UnknownKey}.
//
// `key` must already be populated by inlineScanString. The bytes-path
// `key` is aliased into the caller's data slice and stays valid for the
// duration of the function, so it can be embedded directly as the field
// expression in decode.NewParseErr calls (no clone needed).
func unknownKey(s StructInfo, posVar string) string {
	chk := bytesErrCheck("key", posVar)
	if inline := s.InlineField(); inline.Inline {
		initMap := fmt.Sprintf("if result.%s == nil { result.%s = make(%s) }\n",
			inline.GoName, inline.GoName, inline.GoType)
		switch inline.ElemKind {
		case KindAny:
			anyFn := "scan.Any"
			if s.UseNumber {
				anyFn = "scan.AnyNumber"
			}
			return initMap + fmt.Sprintf(`result.%[1]s[key], %[2]s, err = %[3]s(data, %[2]s)
%[4]s`, inline.GoName, posVar, anyFn, chk)
		case KindString:
			return initMap + fmt.Sprintf(`result.%[2]s[key], %[1]s, err = scan.String(data, %[1]s)
%[3]s`, posVar, inline.GoName, chk)
		case KindStruct:
			if isGenerated(inline.ElemType) {
				return initMap + fmt.Sprintf(`var _iv %[1]s
var _in int
_iv, _in, err = _iv.DecodeFrom(data[%[2]s:])
%[2]s += _in
%[4]sresult.%[3]s[key] = _iv
`, inline.ElemType, posVar, inline.GoName, nestedDecodeErrCheck("key", s.MultiErr, true))
			}
		}
		return initMap + fmt.Sprintf(`_vstart := %[1]s
%[1]s, err = scan.SkipValue(data, %[1]s)
%[4]svar _iv %[2]s
if err = json.Unmarshal(data[_vstart:%[1]s], &_iv); err != nil { return result, %[1]s, decode.NewParseErr(key, %[1]s, err) }
result.%[3]s[key] = _iv
`, posVar, inline.ElemType, inline.GoName, chk)
	}
	if s.IgnoreUnknown {
		return fmt.Sprintf(`%[1]s, err = scan.SkipValue(data, %[1]s)
%[2]s`, posVar, chk)
	}
	if s.MultiErr {
		return fmt.Sprintf(`errs = append(errs, &validation.UnknownKeyError{Path: []string{key}})
%[1]s, err = scan.SkipValue(data, %[1]s)
%[2]s`, posVar, chk)
	}
	return "return result, i, &validation.UnknownKeyError{Path: []string{key}}\n"
}

// validateAndMod emits mods + validation for a field inline in the decoder
// body. The 3-tuple return shape `(T, int, error)` is requested via posVar="i"
// since validation runs mid-stream where the decoder needs to thread the
// cursor through every return. Skipped entirely when f.NoValidate.
func validateAndMod(b *bytes.Buffer, f FieldInfo, ref string) {
	if len(f.Mods) > 0 {
		renderMods(b, f.Mods, ref, f.GoType, f.Kind)
	}
	if len(f.Validation) > 0 {
		renderValidationOn(b, f.Validation, ref, f.JSONName, f.Kind, f.MultiErr, "i")
	}
}

// validateAndModStream is the stream-path counterpart of validateAndMod.
// Emits 2-tuple `return result, err` shape (Stream owns s.Pos).
func validateAndModStream(b *bytes.Buffer, f FieldInfo, ref string) {
	if len(f.Mods) > 0 {
		renderStreamMods(b, f.Mods, ref, f.GoType, f.Kind)
	}
	if len(f.Validation) > 0 {
		renderValidationOn(b, f.Validation, ref, f.JSONName, f.Kind, f.MultiErr, "")
	}
}

// renderField emits the body of a single case: read the value via scan
// helpers, assign into ref, advance pos (`posVar`) to the byte after the
// parsed value. Appends mods + validation unless the struct is novalidate.
// renderStringTag handles json:",string" — reads a quoted JSON string
// and parses its textual contents via strconv into the field's numeric /
// bool type.
func renderStringTag(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	field := fieldLit(f)
	// Brace-less: `sv` / `u` / `n` / `f` land in the caller's scope (case
	// body or pointer-leaf block) — one `,string` field per scope, no
	// collisions. The `:=` parse shadows the function-level err; checked
	// immediately.
	b.WriteString("var sv string\n")
	inlineScanString(b, posVar, "sv", posVar, field)
	errCheck := fmt.Sprintf("if err != nil { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, err) }\n", posVar, field)
	switch f.Kind {
	case KindBool:
		fmt.Fprintf(b, `switch sv {
case "true": %[1]s = true
case "false": %[1]s = false
default: return result, %[2]s, decode.NewParseErr(%[3]s, %[2]s, scan.ErrBadBool)
}
`, ref, posVar, field)
	case KindFloat32, KindFloat64:
		b.WriteString("f, err := strconv.ParseFloat(sv, 64)\n" + errCheck)
		if f.Kind == KindFloat32 {
			fmt.Fprintf(b, "%s = float32(f)\n", ref)
		} else {
			fmt.Fprintf(b, "%s = f\n", ref)
		}
	case KindUint, KindUint8, KindUint16, KindUint32, KindUint64:
		b.WriteString("u, err := strconv.ParseUint(sv, 10, 64)\n" + errCheck)
		if f.Kind == KindUint64 {
			fmt.Fprintf(b, "%s = u\n", ref)
		} else {
			fmt.Fprintf(b, "%s = %s(u)\n", ref, f.GoType)
		}
	case KindInt, KindInt8, KindInt16, KindInt32, KindInt64:
		b.WriteString("n, err := strconv.ParseInt(sv, 10, 64)\n" + errCheck)
		if f.Kind == KindInt64 {
			fmt.Fprintf(b, "%s = n\n", ref)
		} else {
			fmt.Fprintf(b, "%s = %s(n)\n", ref, f.GoType)
		}
	case KindString:
		fmt.Fprintf(b, "%s = sv\n", ref)
	}
}

// pointerDepth counts the leading `*` of a pointer field's GoType and
// returns (depth, leafType). depth==1 is a plain `*T`; depth>=2 is a
// multi-level pointer (`**T`, `***T`, …) whose leaf is the type left after
// stripping every `*`.
func pointerDepth(goType string) (int, string) {
	depth := 0
	for len(goType) > 0 && goType[0] == '*' {
		depth++
		goType = goType[1:]
	}
	return depth, goType
}

// elemPtrType returns the full Go type of a slice/array/map element
// including every pointer level, plus the total pointer depth. The parse
// layer unwraps ONE `*` into ElemPointer for slices/arrays (and alias
// containers); map values and nested-container peels keep all their
// stars on ElemType. depth==0 means the element is not a pointer.
func elemPtrType(f FieldInfo) (string, int) {
	et := f.ElemType
	if f.ElemPointer {
		et = "*" + et
	}
	depth, _ := pointerDepth(et)
	return et, depth
}

// elemPtrField synthesizes the FieldInfo a pointer-typed element decodes
// through — the same parse-first cascade scalar pointer fields use
// (renderField / renderStreamField / renderAppendValue / sizeContrib all
// dispatch on Pointer+GoType). Elem-level rules ride along so built-ins
// run on the deref'd leaf and `@Func` customs on the pointer itself.
// jsonName picks the validation-path suffix ("x[]" for elems, "x.value"
// for map values).
func elemPtrField(f FieldInfo, jsonName string) FieldInfo {
	et, _ := elemPtrType(f)
	_, leafType := pointerDepth(et)
	pf := FieldInfo{
		GoType:      et,
		Pointer:     true,
		PointeeType: et[1:],
		Kind:        resolveKind(leafType),
		JSONName:    jsonName,
		Format:      f.Format,
		HTMLEscape:  f.HTMLEscape,
		MultiErr:    f.MultiErr,
		NoValidate:  f.NoValidate,
		AllowDups:   f.AllowDups,
		UseNumber:   f.UseNumber,
		Validation:  f.ElemValidation,
		Mods:        f.ElemMods,
		Iface:       f.ElemIface,
	}
	// A container leaf (`[]**[]int`, `map[string]**[2]T`, …) needs its own
	// Elem* populated — the parse layer only fills these for the outermost
	// container.
	switch pf.Kind {
	case KindSlice, KindArray:
		pf.ArrayLen = arrayLenFromType(leafType)
		elem, kind, _ := stripOneContainer(leafType)
		if strings.HasPrefix(elem, "*") {
			pf.ElemPointer = true
			elem = elem[1:]
			kind = resolveKind(elem)
		}
		pf.ElemType, pf.ElemKind = elem, kind
		if kind == KindArray {
			pf.ElemArrayLen = arrayLenFromType(elem)
		}
	case KindMap:
		pf.ElemType = strings.TrimPrefix(leafType, "map[string]")
		pf.ElemKind = resolveKind(pf.ElemType)
	}
	return pf
}

// derefStr returns ref dereferenced k times, parenthesized:
// derefStr("x",0)=="x", derefStr("x",1)=="(*x)", derefStr("x",2)=="(*(*x))".
func derefStr(ref string, k int) string {
	for ; k > 0; k-- {
		ref = "(*" + ref + ")"
	}
	return ref
}

// newChain returns `new(new(…expr))` with n `new(` calls — wraps expr in n
// pointer levels via the Go 1.26 `new(expr)` form. n==1 → `new(expr)`.
func newChain(expr string, n int) string {
	return strings.Repeat("new(", n) + expr + strings.Repeat(")", n)
}

// widenedLeafCast maps a narrow numeric leaf kind to the wide type its scanner
// naturally produces (`int64`/`uint64`/`float64`) plus the cast back to the
// leaf type. For these the pointer decode scans into a wide temp `v` and casts
// at the `new(…)`/assign site (`new(int(v))`) — no separate width-conversion
// variable. Returns ("", 0, "") for kinds that need no widening (the temp is
// already the leaf type, assigned as-is).
func widenedLeafCast(k TypeKind, leafGoType string) (wideType string, wideKind TypeKind, cast string) {
	switch k {
	case KindInt, KindInt8, KindInt16, KindInt32:
		return "int64", KindInt64, leafGoType
	case KindUint, KindUint8, KindUint16, KindUint32:
		return "uint64", KindUint64, leafGoType
	case KindFloat32:
		return "float64", KindFloat64, leafGoType
	}
	return "", 0, ""
}

// leafMerges reports whether a pointer leaf of this kind benefits from being
// seeded with the receiver's carried-in value before decode (struct fields
// persist across omission; slice/map backing is reused). Primitives just
// overwrite, so seeding them is pointless.
func leafMerges(k TypeKind) bool {
	switch k {
	case KindStruct, KindSlice, KindArray, KindMap:
		return true
	}
	return false
}

// nullBreakOK reports whether a field's `null` branch can `break` out of the
// key-dispatch switch instead of nesting the whole value decode in an else.
// Requires the emit site to sit directly inside the dispatch switch
// (AtDispatch) and no post-value field rules — a break would skip the
// validateAndMod / custom @Func calls that follow the value block.
func nullBreakOK(f FieldInfo) bool {
	return f.AtDispatch && (f.NoValidate || (len(f.Validation) == 0 && len(f.Mods) == 0))
}

// emitPointerSeed copies the receiver's existing leaf into the decode temp
// `v` when the whole pointer chain is already allocated — so a mergeable leaf
// merges against its carried-in value. No-op for non-mergeable leaves.
func emitPointerSeed(b *bytes.Buffer, ref string, depth int, leafKind TypeKind) {
	if !leafMerges(leafKind) {
		return
	}
	conds := make([]string, depth)
	for k := 0; k < depth; k++ {
		conds[k] = derefStr(ref, k) + " != nil"
	}
	fmt.Fprintf(b, "if %s {\nv = %s\n}\n", strings.Join(conds, " && "), derefStr(ref, depth))
}

// emitPointerAssign writes the post-parse assign cascade for a depth-level
// pointer field: the leaf value has already been decoded into temp `v`
// (so a parse failure returned WITHOUT touching the receiver — no allocation
// for a value that never landed). `valExpr` is the value written at the leaf —
// `v`, or a width cast like `int(v)` for a widened numeric leaf. REUSE the
// non-nil prefix of the chain, allocating `new(new(…valExpr))` only from the
// first nil level down; the final else writes straight into a fully-allocated
// chain. depth==1 is the plain single-pointer merge.
func emitPointerAssign(b *bytes.Buffer, ref string, depth int, valExpr string) {
	for k := 0; k < depth; k++ {
		dk := derefStr(ref, k)
		kw := "if"
		if k > 0 {
			kw = "} else if"
		}
		fmt.Fprintf(b, "%s %s == nil {\n%s = %s\n", kw, dk, dk, newChain(valExpr, depth-k))
	}
	fmt.Fprintf(b, "} else {\n%s = %s\n}\n", derefStr(ref, depth), valExpr)
}

func renderField(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	// Pointer FIRST: a pointer-to-T field with json:",string" needs to
	// decode into the pointee's T and then take its address. Running the
	// string-tag branch with f.GoType="*T" emits the broken
	// `result.X = *T(n)`. The pointer block recurses with inner.GoType=T,
	// inner.String preserved — the string-tag branch then runs on the
	// inner-of-T type and assigns to the stack-local `v`.
	if f.Pointer {
		// Custom `@Func` rules apply to the field's exact type — `*T` /
		// `**T` for pointer fields. Built-in rules (gte, minlen, …) operate
		// on the deref'd leaf, since they're typed against the underlying
		// kind. Partition here, run @-rules on `ref` (the pointer) AFTER the
		// if/else.
		builtinV, customV := partitionCustomValidation(f.Validation)
		builtinM, customM := partitionCustomMods(f.Mods)
		// Decode-into-receiver, any pointer depth. JSON `null` → nil outer
		// (drops a pre-existing chain, stdlib merge parity). Otherwise decode
		// the leaf into a temp `v` FIRST — a parse failure returns before any
		// mutation, so we never allocate a chain for a value that never
		// landed. On success the assign cascade REUSES the non-nil prefix of
		// the receiver's chain, allocating `new(new(…))` only from the first
		// nil level down. A mergeable leaf is seeded from the carried-in value
		// so it still merges. No reflective encoding/json fallback at any depth.
		depth, leafType := pointerDepth(f.GoType)
		leaf := f
		leaf.Pointer = false
		leaf.PointeeType = ""
		leaf.GoType = leafType
		leaf.Kind = resolveKind(leafType)
		leaf.Validation = builtinV
		leaf.Mods = builtinM
		leaf.AtDispatch = false
		leaf.TargetNil = false
		// Widened numeric leaf: scan into the wide type and cast at the assign
		// site (`new(int(v))` / `new(int(n))`) rather than carrying a separate
		// conversion var. castFn is the cast back to the narrow leaf type.
		scanType, castFn := leafType, ""
		if wide, wideKind, cast := widenedLeafCast(leaf.Kind, leafType); wide != "" {
			leaf.Kind, leaf.GoType, scanType, castFn = wideKind, wide, wide, cast
		}
		// At dispatch level the null branch breaks straight to the comma
		// handling — the non-null decode stays at case-body level instead of
		// nesting inside an else.
		flat := nullBreakOK(f)
		inlineNullPeek(b, posVar)
		fmt.Fprintf(b, "%s = nil\n", ref)
		if flat {
			b.WriteString("break\n}\n")
		} else {
			b.WriteString("} else {\n")
		}
		// Fast path: the inline int/uint scanner already materializes `n`, so
		// a leaf with no built-in mods/validation skips the temp entirely —
		// the assign cascade runs in-block straight off `n`.
		if (leaf.Kind == KindInt64 || leaf.Kind == KindUint64) && len(builtinV) == 0 && len(builtinM) == 0 {
			valExpr := "n"
			if castFn != "" {
				valExpr = castFn + "(n)"
			}
			var cascade bytes.Buffer
			if f.TargetNil {
				fmt.Fprintf(&cascade, "%s = %s\n", ref, newChain(valExpr, depth))
			} else {
				emitPointerAssign(&cascade, ref, depth, valExpr)
			}
			stmt := strings.TrimRight(cascade.String(), "\n")
			if leaf.Kind == KindInt64 {
				inlineScanInt64Stmt(b, posVar, fieldLit(f), stmt)
			} else {
				inlineScanUint64Stmt(b, posVar, fieldLit(f), stmt)
			}
		} else {
			valExpr := "v"
			if castFn != "" {
				valExpr = castFn + "(v)"
			}
			fmt.Fprintf(b, "var v %s\n", scanType)
			if !f.TargetNil {
				emitPointerSeed(b, ref, depth, leaf.Kind)
			}
			renderField(b, leaf, "v", posVar)
			if f.TargetNil {
				// Target was declared `var x *T` just above by the caller —
				// known nil, no chain to reuse: straight new-chain assign.
				fmt.Fprintf(b, "%s = %s\n", ref, newChain(valExpr, depth))
			} else {
				emitPointerAssign(b, ref, depth, valExpr)
			}
		}
		if !flat {
			b.WriteString("}\n")
		}
		if !f.NoValidate && (len(customV) > 0 || len(customM) > 0) {
			outer := f
			outer.Validation = customV
			outer.Mods = customM
			validateAndMod(b, outer, ref)
		}
		return
	}
	// jsonv2 dropped `,string` for bool; ggen follows. Fall through to
	// the normal bool decode path so the wire stays bare `true`/`false`.
	if f.String && f.Kind != KindBool {
		renderStringTag(b, f, ref, posVar)
		if !f.NoValidate {
			validateAndMod(b, f, ref)
		}
		return
	}
	field := fieldLit(f)
	switch f.Kind {
	case KindString:
		inlineScanString(b, posVar, ref, posVar, field)
	case KindBool:
		fmt.Fprintf(b, "%[1]s, %[2]s, err = scan.Bool(data, %[2]s)\n", ref, posVar)
		fmt.Fprintf(b, "if err != nil { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, err) }\n", posVar, field)
	case KindInt, KindInt8, KindInt16, KindInt32:
		inlineScanInt64(b, posVar, ref, f.GoType, field)
	case KindInt64:
		inlineScanInt64(b, posVar, ref, "", field)
	case KindUint, KindUint8, KindUint16, KindUint32:
		inlineScanUint64(b, posVar, ref, f.GoType, field)
	case KindUint64:
		inlineScanUint64(b, posVar, ref, "", field)
	case KindFloat32:
		fmt.Fprintf(b, `var fv float64
fv, %[1]s, err = scan.Float64(data, %[1]s)
if err != nil { return result, %[1]s, decode.NewParseErr(%[3]s, %[1]s, err) }
%[2]s = float32(fv)
`, posVar, ref, field)
	case KindFloat64:
		fmt.Fprintf(b, `%[1]s, %[2]s, err = scan.Float64(data, %[2]s)
if err != nil { return result, %[2]s, decode.NewParseErr(%[3]s, %[2]s, err) }
`, ref, posVar, field)
	case KindStruct:
		if isGenerated(f.GoType) {
			// Receiver is the existing field — value-receiver method
			// reads the field's current value (zero on fresh decode) and
			// returns a fresh value we write back into the field. New
			// DecodeFrom signature takes data[i:] and returns bytes
			// consumed; we advance posVar by that count.
			fmt.Fprintf(b, `var _n int
%[1]s, _n, err = %[1]s.DecodeFrom(data[%[2]s:])
%[2]s += _n
%[3]s`, ref, posVar, nestedDecodeErrCheck(fieldLit(f), f.MultiErr, true))
		} else {
			b.WriteString(renderCrossPkgStructDecode(f, ref, posVar))
		}
	case KindSlice:
		renderSlice(b, f, ref, posVar)
	case KindArray:
		emitByteArrayRead(b, f, ref, posVar, 0)
	case KindMap:
		renderMap(b, f, ref, posVar)
	case KindBytes:
		renderBytes(b, f, ref, posVar)
	case KindTime:
		renderTime(b, f, ref, posVar)
	case KindDuration:
		renderDuration(b, f, ref, posVar)
	case KindNetIP:
		renderNetIP(b, f, ref, posVar)
	case KindNetipAddr:
		renderNetipAddr(b, f, ref, posVar)
	case KindNetipPrefix:
		renderNetipPrefix(b, f, ref, posVar)
	case KindRawJSON:
		renderRawJSON(b, f, ref, posVar)
	case KindURL:
		renderURL(b, f, ref, posVar)
	case KindBigInt:
		renderBigInt(b, f, ref, posVar)
	case KindBigFloat:
		renderBigFloat(b, f, ref, posVar)
	case KindBigRat:
		renderBigRat(b, f, ref, posVar)
	case KindSQLNull:
		renderSQLNull(b, f, ref, posVar)
	case KindAny:
		renderAny(b, f, ref, posVar)
	default:
		fmt.Fprintf(b, `k, err := scan.SkipValue(data, %[1]s)
%[2]s%[1]s = k
`, posVar, bytesErrCheck(fieldLit(f), posVar))
	}
	// Post-decode: mods then validation. The `seen<GoName>` bool is set
	// by the caller (renderDispatch emits it), not here.
	if !f.NoValidate {
		validateAndMod(b, f, ref)
	}
}

// renderSlice is the depth-0 entry point into the recursive slice emitter.
// See emitByteSliceRead for the bulk of the work.
func renderSlice(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	emitByteSliceRead(b, f, ref, posVar, 0)
}

// peelSliceField returns the FieldInfo describing one level down for a
// slice-of-slice or slice-of-array element. Mod / validation rules shift up
// by one level (InnerValidation[0] → ElemValidation, etc.). The outer
// container's kind (slice or array) is inferred from f.ElemKind at the
// parent call — this helper is invoked after the parent confirms ElemKind
// is either KindSlice or KindArray.
func peelSliceField(f FieldInfo) FieldInfo {
	innerGoType := f.ElemType
	innerElem, innerKind, innerLen := stripOneContainer(innerGoType)
	// Mirror the parse layer: one leading `*` on the peeled element type
	// unwraps into ElemPointer (slab fast path / pointer cascade); any
	// remaining stars stay on ElemType for the multi-level route.
	innerPointer := false
	if strings.HasPrefix(innerElem, "*") {
		innerPointer = true
		innerElem = innerElem[1:]
		innerKind = resolveKind(innerElem)
		if innerKind == KindArray {
			innerLen = arrayLenFromType(innerElem)
		}
	}
	inner := FieldInfo{
		GoType:      innerGoType,
		Kind:        f.ElemKind, // KindSlice or KindArray — the layer we're now inside
		ArrayLen:    f.ElemArrayLen,
		ElemPointer: innerPointer,
		ElemType:    innerElem,
		ElemKind:    innerKind,
		JSONName:    f.JSONName + "[]",
		MultiErr:    f.MultiErr,
		NoValidate:  f.NoValidate,
		AllowDups:   f.AllowDups,
		// HintLen=-1 means "unset" — preallocCap then falls through to
		// len/minlen/kind-based default. Without this the zero-value 0
		// reads as "user opt-out (no prealloc)" and the inner slice gets
		// cap=0, forcing the 1→2→4→8 growth chain on every nested row.
		HintLen: -1,
	}
	if innerKind == KindArray {
		inner.ElemArrayLen = innerLen
	}
	if len(f.InnerValidation) > 0 {
		inner.ElemValidation = f.InnerValidation[0]
		if len(f.InnerValidation) > 1 {
			inner.InnerValidation = f.InnerValidation[1:]
		}
	}
	if len(f.InnerMods) > 0 {
		inner.ElemMods = f.InnerMods[0]
		if len(f.InnerMods) > 1 {
			inner.InnerMods = f.InnerMods[1:]
		}
	}
	return inner
}

// stripOneContainer peels off one layer of container (slice `[]` or array
// `[N]`) from a Go type string, returning the element type, its kind, and
// N (0 for slices / non-containers).
func stripOneContainer(typ string) (inner string, kind TypeKind, length int) {
	if strings.HasPrefix(typ, "[]") {
		inner = typ[2:]
		return inner, resolveKind(inner), 0
	}
	if len(typ) > 2 && typ[0] == '[' {
		if end := strings.IndexByte(typ, ']'); end > 1 {
			if n, err := strconv.Atoi(typ[1:end]); err == nil {
				inner = typ[end+1:]
				return inner, resolveKind(inner), n
			}
		}
	}
	return typ, resolveKind(typ), 0
}

// emitByteArrayRead is a thin wrapper around emitByteSliceRead for top-level
// [N]T fields. The shared emitter picks the array path based on f.Kind.
func emitByteArrayRead(b *bytes.Buffer, f FieldInfo, dst, posVar string, depth int) {
	emitByteSliceRead(b, f, dst, posVar, depth)
}

// emitByteSliceRead emits a JSON array reader against `data` into `dst`,
// advancing the caller's position variable `posVar`. Handles both slices
// (f.Kind == KindSlice) and fixed-length arrays (f.Kind == KindArray):
//   - slices: pre-sized via preallocCap, appended to
//   - arrays: strict tuple semantics — the JSON array must have exactly
//     f.ArrayLen elements or the decode errors with validation.Error{Len}
//
// All locals carry the `depth` suffix (k0, ev0 at the outermost call; k1,
// ev1 one level in; …) so nested arrays/slices don't collide on names.
func emitByteSliceRead(b *bytes.Buffer, f FieldInfo, dst, posVar string, depth int) {
	isArray := f.Kind == KindArray
	arrayN := f.ArrayLen
	// Multi-level pointer element (`[]**T`, `[N]***T`, …): no slab — each
	// element runs the same parse-first cascade scalar pointer fields use
	// (renderField's Pointer branch: null peek, leaf temp, new(…) chain).
	// Depth-1 `[]*T` keeps the slab fast path.
	_, elemDepth := elemPtrType(f)
	mptr := elemDepth >= 2
	// kvar threads through the caller's position variable directly — no
	// separate `kN := posVar` alias. The whole nest of slice/array decoders
	// shares one position counter (typically `j` at the top level), each
	// inner level advancing it past the bytes it consumed. Only the data
	// locals (`evN`, `idxN`, `slabN`) keep depth suffixes.
	// No wrapper block: every local is depth-suffixed (`idxN`, `slabN`) or
	// lives inside the element loop, so nothing here needs its own scope.
	kvar := posVar
	evvar := fmt.Sprintf("ev%d", depth)
	ivar := fmt.Sprintf("idx%d", depth)
	inlineSkipWS(b, kvar)
	// `null` → nil out the slice and consume the literal. Arrays don't
	// accept null (no nil array values in Go); they still error on
	// non-`[` input. At dispatch level the null branch breaks straight to
	// the comma handling instead of nesting the array read in an else; a
	// nested slot whose parent already consumed the null (NullDone) skips
	// the peek entirely.
	flat := !isArray && nullBreakOK(f)
	if !isArray && !f.NullDone {
		inlineNullPeek(b, kvar)
		fmt.Fprintf(b, "%s = nil\n", dst)
		if flat {
			b.WriteString("break\n}\n")
		} else {
			b.WriteString("} else {\n")
		}
	}
	fmt.Fprintf(b, "if %s >= len(data) || data[%s] != '[' { return result, i, scan.ErrBadArray }\n", kvar, kvar)
	fmt.Fprintf(b, "%s++\n", kvar)
	inlineSkipWS(b, kvar)
	slabVar := fmt.Sprintf("slab%d", depth)
	if isArray {
		fmt.Fprintf(b, "var %s int\n", ivar)
		// For arrays of pointers, allocate the slab as an exact-sized
		// heap slice. `[N]E` would land on the stack, then `&slab[i]`
		// at the assignment site forces the whole array to escape — net
		// is still a heap alloc, but copied via the stack frame first.
		// `make([]E, N)` skips the stack hop and avoids the cache-line
		// thrash for large E.
		if f.ElemPointer && !mptr {
			fmt.Fprintf(b, "%s := make([]%s, %d)\n", slabVar, f.ElemType, arrayN)
		}
	} else {
		sCap, slCap := preallocCap(f)
		if f.ElemPointer && !mptr {
			fmt.Fprintf(b, "var %s []%s\n", slabVar, f.ElemType)
		}
		// dst is decode-into-receiver: either nil (fresh) or already [:0]'d
		// at the top of DecodeFrom (existing backing kept for reuse). Only
		// allocate when nil; otherwise the [:0]'d slice serves as the
		// append target and re-uses the caller's backing array.
		fmt.Fprintf(b, "if %s < len(data) && data[%s] == ']' {\n", kvar, kvar)
		fmt.Fprintf(b, "if %s == nil { %s = %s{} }\n", dst, dst, f.GoType)
		fmt.Fprintf(b, "} else {\n")
		if sCap > 0 {
			fmt.Fprintf(b, "if %s == nil { %s = make(%s, 0, %d) }\n", dst, dst, f.GoType, sCap)
		} else {
			fmt.Fprintf(b, "if %s == nil { %s = %s{} }\n", dst, dst, f.GoType)
		}
		if f.ElemPointer && !mptr {
			fmt.Fprintf(b, "%s = make([]%s, 0, %d)\n", slabVar, f.ElemType, slCap)
		}
		fmt.Fprintf(b, "}\n")
	}
	// Every elem kind decodes IN PLACE into the destination slot — no
	// `var ev0 T` temporary. The slot is:
	//   - [N]*T (slab+array):  `slab[ivar]`
	//   - [N]T  (dst+array):   `dst[ivar]`
	//   - []*T  (slab+slice):  pre-grow slab `append(slab, T{})`,
	//                          target `slab[len-1]`
	//   - []T   (dst+slice):   pre-grow dst   `append(dst, T{})`,
	//                          target `dst[len-1]`
	// `var err error` is hoisted once above the loop for the struct
	// case (byte path has no outer err scope); container recursion has
	// its own err handling.
	directStruct := f.ElemKind == KindStruct && isGenerated(f.ElemType)
	_ = evvar // legacy depth-suffixed name no longer used at this scope
	// err is now hoisted at the DecodeFrom function-body level (renderDecode);
	// no local declaration needed here.
	fmt.Fprintf(b, "for %s < len(data) && data[%s] != ']' {\n", kvar, kvar)
	if isArray {
		// Strict tuple: reject when the JSON array has more elements than
		// the Go [N]T can hold.
		fmt.Fprintf(b, "if %s >= %d { return result, i, %s }\n",
			ivar, arrayN,
			arrayLenErr(f.JSONName, arrayN, ivar))
	}
	if f.ElemPointer && !mptr {
		// `null` element → nil pointer. Skip the parse + slab work.
		// (Multi-level elements skip this — the pointer cascade carries
		// its own null peek.)
		inlineNullPeek(b, kvar)
		if isArray {
			fmt.Fprintf(b, "%s[%s] = nil\n", dst, ivar)
			fmt.Fprintf(b, "%s++\n", ivar)
		} else {
			fmt.Fprintf(b, "%s = append(%s, nil)\n", dst, dst)
		}
		inlineSkipWS(b, kvar)
		fmt.Fprintf(b, "if %s < len(data) && data[%s] == ',' { %s++; ", kvar, kvar, kvar)
		inlineSkipWS(b, kvar)
		emitNoCloseAfterComma(b, kvar, ']')
		b.WriteString("continue }\nbreak\n}\n")
	}
	// Compute the in-place target. For slice cases we pre-grow the
	// slice/slab here so the slot exists before scan writes into it.
	var target string
	switch {
	case isArray && mptr:
		target = fmt.Sprintf("%s[%s]", dst, ivar)
	case mptr:
		// Pointer cascade assigns the chain head into the slot directly;
		// pre-grow with nil.
		fmt.Fprintf(b, "%s = append(%s, nil)\n", dst, dst)
		target = fmt.Sprintf("%s[len(%s)-1]", dst, dst)
	case isArray && f.ElemPointer:
		target = fmt.Sprintf("%s[%s]", slabVar, ivar)
	case isArray:
		target = fmt.Sprintf("%s[%s]", dst, ivar)
	case f.ElemPointer:
		// Pointer slab holds the pointee type (e.g. []Addr for []*Addr);
		// pre-grow with the pointee's zero value.
		fmt.Fprintf(b, "%s = append(%s, %s)\n", slabVar, slabVar, zeroLit(f.ElemType, f.ElemKind))
		target = fmt.Sprintf("%s[len(%s)-1]", slabVar, slabVar)
	default:
		fmt.Fprintf(b, "%s = append(%s, %s)\n", dst, dst, zeroLit(f.ElemType, f.ElemKind))
		target = fmt.Sprintf("%s[len(%s)-1]", dst, dst)
	}
	field := fieldLit(f)
	errCheck := fmt.Sprintf("if err != nil { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, err) }\n", kvar, field)
	if mptr {
		// Elem rules ride inside the cascade (built-ins on the leaf temp);
		// no slab, no post-decode mods/validation here. Slice slots are
		// pre-grown with nil (append above) — no chain to seed or reuse;
		// array slots carry the receiver's element, so they keep the cascade.
		pf := elemPtrField(f, f.JSONName+"[]")
		pf.TargetNil = !isArray
		renderField(b, pf, target, kvar)
	} else {
		switch f.ElemKind {
		case KindString:
			inlineScanString(b, kvar, target, kvar, field)
		case KindBool:
			fmt.Fprintf(b, "%s, %s, err = scan.Bool(data, %s)\n", target, kvar, kvar)
			b.WriteString(errCheck)
		case KindInt, KindInt8, KindInt16, KindInt32, KindInt64:
			castFn := ""
			if f.ElemType != "int64" {
				castFn = f.ElemType
			}
			inlineScanInt64(b, kvar, target, castFn, field)
		case KindUint, KindUint8, KindUint16, KindUint32, KindUint64:
			castFn := ""
			if f.ElemType != "uint64" {
				castFn = f.ElemType
			}
			inlineScanUint64(b, kvar, target, castFn, field)
		case KindFloat32, KindFloat64:
			if f.ElemKind == KindFloat64 {
				fmt.Fprintf(b, "%s, %s, err = scan.Float64(data, %s)\n", target, kvar, kvar)
				b.WriteString(errCheck)
			} else {
				b.WriteString("var fv float64\n")
				fmt.Fprintf(b, "fv, %s, err = scan.Float64(data, %s)\n", kvar, kvar)
				b.WriteString(errCheck)
				fmt.Fprintf(b, "%s = float32(fv)\n", target)
			}
		case KindStruct:
			if directStruct {
				// DecodeFrom now takes data[i:] and returns bytes consumed.
				fmt.Fprintf(b, `var _n int
%[1]s, _n, err = %[1]s.DecodeFrom(data[%[2]s:])
%[2]s += _n
`, target, kvar)
				b.WriteString(nestedDecodeErrCheck(fieldLit(f), f.MultiErr, true))
			} else {
				fmt.Fprintf(b, "%s, err = scan.SkipValue(data, %s)\n", kvar, kvar)
				b.WriteString(bytesErrCheck(fieldLit(f), kvar))
			}
		case KindSlice, KindArray:
			// Nested container — recurse, peeling one outer [] / [N] off.
			// The recursive emit writes into target (the slot itself).
			inner := peelSliceField(f)
			if inner.Kind == KindSlice && len(f.ElemMods) == 0 {
				// `null` elem → nil slot, handled HERE (mirrors the []*T
				// nil-elem fast path) so the inner emitter's body isn't
				// nested in an else. Slice slots are pre-grown nil; array
				// slots carry the receiver's element and need the explicit
				// nil. Elem rules still run against the nil slot — same
				// emit as the post-decode call below.
				inlineNullPeek(b, kvar)
				if isArray {
					fmt.Fprintf(b, "%s = nil\n", target)
				}
				if len(f.ElemValidation) > 0 {
					renderValidationOn(b, f.ElemValidation, target, f.JSONName+"[]", f.ElemKind, f.MultiErr, "i")
				}
				if isArray {
					fmt.Fprintf(b, "%s++\n", ivar)
				}
				inlineSkipWS(b, kvar)
				fmt.Fprintf(b, "if %s < len(data) && data[%s] == ',' { %s++; ", kvar, kvar, kvar)
				inlineSkipWS(b, kvar)
				emitNoCloseAfterComma(b, kvar, ']')
				b.WriteString("continue }\nbreak\n}\n")
				inner.NullDone = true
			}
			emitByteSliceRead(b, inner, target, kvar, depth+1)
		}
		if len(f.ElemMods) > 0 {
			renderMods(b, f.ElemMods, target, f.ElemType, f.ElemKind)
		}
		if len(f.ElemValidation) > 0 {
			renderValidationOn(b, f.ElemValidation, target, f.JSONName+"[]", f.ElemKind, f.MultiErr, "i")
		}
	}
	switch {
	case isArray && f.ElemPointer && !mptr:
		// Slab slot already decoded in-place; publish its address.
		fmt.Fprintf(b, "%s[%s] = &%s[%s]\n", dst, ivar, slabVar, ivar)
		fmt.Fprintf(b, "%s++\n", ivar)
	case isArray:
		// dst[ivar] already decoded in-place (slot decode or pointer cascade).
		fmt.Fprintf(b, "%s++\n", ivar)
	case f.ElemPointer && !mptr:
		// Slab tail decoded in-place via append+index above; publish addr.
		fmt.Fprintf(b, "%s = append(%s, &%s[len(%s)-1])\n", dst, dst, slabVar, slabVar)
	default:
		// dst tail already decoded in-place via append+index above.
	}
	inlineSkipWS(b, kvar)
	fmt.Fprintf(b, "if %s < len(data) && data[%s] == ',' { %s++; ", kvar, kvar, kvar)
	inlineSkipWS(b, kvar)
	emitNoCloseAfterComma(b, kvar, ']')
	b.WriteString("continue }\n")
	b.WriteString("break\n")
	b.WriteString("}\n")
	fmt.Fprintf(b, "if %s >= len(data) || data[%s] != ']' { return result, i, scan.ErrBadArray }\n", kvar, kvar)
	if isArray {
		fmt.Fprintf(b, "if %s != %d { return result, i, %s }\n",
			ivar, arrayN,
			arrayLenErr(f.JSONName, arrayN, ivar))
	}
	// kvar == posVar (no alias); just step past the closing `]`.
	fmt.Fprintf(b, "%s++\n", posVar)
	if !isArray && !flat && !f.NullDone {
		b.WriteString("}\n") // close else (null-check)
	}
}

// renderStreamDecode emits the streaming counterpart of renderDecode.
// Uses scan.Stream methods which pull more bytes on demand. Buffer backing
// array is fixed-capacity and never reallocates — zero-copy string aliases
// stay valid for the lifetime of the Stream.
func renderStreamDecode(b *bytes.Buffer, s StructInfo) {
	// Named-result return slot — see DecodeFrom above.
	fmt.Fprintf(b, "func (recv %s) DecodeFromStream(s *scan.Stream) (result %s, err error) {\n", s.Name, s.Name)
	b.WriteString("result = recv\n")
	if s.IsAlias {
		renderAliasStreamDecode(b, s)
		b.WriteString("}\n\n")
		return
	}
	renderStreamDecodeStruct(b, s)
	b.WriteString("}\n\n")
}

func renderStreamDecodeStruct(b *bytes.Buffer, s StructInfo) {
	emitReceiverReset(b, s)
	if s.MultiErr {
		b.WriteString("var errs validation.Errors\n")
	}
	if useSeenBitmask(s) {
		b.WriteString(seenDecl(s))
	} else {
		for _, f := range s.Fields {
			if f.Inline {
				continue
			}
			if needsSeen(f) {
				fmt.Fprintf(b, "seen%s := false\n", f.GoName)
			}
		}
	}
	var pl bytes.Buffer
	renderStreamPostLoop(&pl, s)
	plStr := pl.String()
	// Dispatch happens IMMEDIATELY after KeyView so the alias is still
	// valid when the switch compares it against constants. Each case
	// body opens with s.ConsumeColon — that's where the buffer may
	// compact (via SkipSpace's internal shift) and where the alias
	// dies. Cases that capture key (inline catch-all, UnknownKeyError
	// in multierr/immediate-return paths) must clone BEFORE
	// ConsumeColon.
	chk := streamErrCheck(`""`)
	rmore := `if s.Pos >= len(s.Bytes()) { if err = s.ReadMore(s.Pos); err != nil { return result, decode.NewParseErr("", s.Pos, err) }; s.Pos = 0 }
`
	badObj := `return result, decode.NewParseErr("", s.Pos, scan.ErrBadObject)`
	fmt.Fprintf(b, `err = s.ObjectOpen()
%[1]serr = s.SkipSpace()
%[1]s%[5]sif s.Bytes()[s.Pos] == '}' {
s.Pos++
%[2]sreturn result, nil
}
for {
	var key string
	key, err = s.KeyView()
	%[1]s%[3]s
	err = s.SkipSpace()
	%[1]s%[5]sc := s.Bytes()[s.Pos]
	if c == ',' {
		s.Pos++
		err = s.SkipSpace()
		%[1]scontinue
	}
	if c == '}' {
		s.Pos++
%[2]s		return result, nil
	}
	%[4]s
}`, chk, plStr, renderStreamDispatch(s), badObj, rmore)
}

func renderStreamDispatch(s StructInfo) string {
	// Each known-key case opens with s.ConsumeColon — the alias is no
	// longer needed past this point, so the shift it triggers is safe.
	emitField := func(b *bytes.Buffer, f FieldInfo, parse string) {
		field := fieldLit(f)
		chk := streamErrCheck(field)
		fmt.Fprintf(b, "err = s.ConsumeColon()\n%s", chk)
		if f.Inline || !needsSeen(f) {
			b.WriteString(parse)
			return
		}
		set := seenSet(s, f)
		seen := seenAccess(s, f)
		if s.AllowDups {
			fmt.Fprintf(b, `if %[1]s {
	err = s.SkipValue()
	%[4]s} else {
	%[2]s%[3]s
}
`, seen, set, parse, chk)
			return
		}
		if s.MultiErr {
			fmt.Fprintf(b, `if %[1]s {
	errs = append(errs, &validation.DuplicateKeyError{Path: []string{%[2]q}})
	err = s.SkipValue()
	%[5]s} else {
	%[3]s%[4]s
}
`, seen, f.JSONName, set, parse, chk)
			return
		}
		fmt.Fprintf(b, `if %s { return result, &validation.DuplicateKeyError{Path: []string{%q}} }
%s%s`, seen, f.JSONName, set, parse)
	}

	b := getSmall()
	defer putSmall(b)
	b.WriteString("switch key {\n")
	for _, f := range s.Fields {
		if f.Inline {
			continue
		}
		f.AtDispatch = true
		fmt.Fprintf(b, "case %q:\n", f.JSONName)
		emitField(b, f, renderStreamField(f, "result."+f.GoName, "s.Pos"))
	}
	b.WriteString("default:\n")
	b.WriteString(streamUnknownKey(s, "s.Pos"))
	b.WriteString("}\n")
	return b.String()
}

// renderStreamMap emits map decode for the stream path.
// err comes from the function-body scope (ObjectOpen at the top of the
// regular DecodeFromStream, or the synthetic decl in
// renderAliasContainerDecode for alias containers). `null` -> leave nil
// and consume the literal. Empty `{}` -> non-nil empty; else fresh
// make(). Map keys must be detached copies (the map holds the string
// header; the buffer can be overwritten on next ReadMore), so we use
// s.String which copies.
func renderStreamMap(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	field := fieldLit(f)
	chk := streamErrCheck(field)
	rm := streamReadMore(field, "0", false)
	rmKi := strings.Replace(rm, "if s.Pos >=", "if s.Pos+ki >=", 1)
	badLit := fmt.Sprintf("return result, decode.NewParseErr(%s, s.Pos, scan.ErrBadLiteral)", field)
	badObj := fmt.Sprintf("return result, decode.NewParseErr(%s, s.Pos, scan.ErrBadObject)", field)
	makeExpr := fmt.Sprintf("make(%s)", f.GoType)
	if cap := mapPreallocCap(f); cap > 0 {
		makeExpr = fmt.Sprintf("make(%s, %d)", f.GoType, cap)
	}
	// At dispatch level the null branch breaks straight to the comma
	// handling instead of nesting the whole object read in an else.
	// No wrapper block: `mk` / `mv` / `mn` all live inside the element loop.
	flat := nullBreakOK(f)
	fmt.Fprintf(b, `err = s.SkipSpace()
%[3]s%[4]sif s.Bytes()[s.Pos] == 'n' {
	for ki := 1; ki < 4; ki++ {
		%[5]sif s.Bytes()[s.Pos+ki] != "null"[ki] { %[2]s }
	}
	s.Pos += 4
	%[1]s = nil
`, ref, badLit, chk, rm, rmKi)
	if flat {
		b.WriteString("break\n}\n")
	} else {
		b.WriteString("} else {\n")
	}
	fmt.Fprintf(b, `	err = s.ObjectOpen()
	%[4]serr = s.SkipSpace()
	%[4]s%[6]sif s.Bytes()[s.Pos] == '}' {
		if %[1]s == nil { %[1]s = %[2]s{} }
	} else {
		if %[1]s == nil { %[1]s = %[3]s }
	}
	for s.Bytes()[s.Pos] != '}' {
		var mk string
		mk, err = s.String()
		%[4]s`, ref, f.GoType, makeExpr, chk, badLit, rm)
	keyValidateAndModStream(b, f, "mk")
	fmt.Fprintf(b, `		err = s.SkipSpace()
		%[1]s%[3]sif s.Bytes()[s.Pos] != ':' { %[2]s }
		s.Pos++
		err = s.SkipSpace()
		%[1]s`, chk, badObj, rm)
	_ = posVar

	mapTarget := fmt.Sprintf("%s[mk]", ref)
	if _, eDepth := elemPtrType(f); eDepth > 0 {
		// Pointer value (any depth) — same cascade as the bytes path,
		// decoded straight into the map slot (TargetNil keeps the emit
		// assignment-only, so the unaddressable index is fine).
		pf := elemPtrField(f, f.JSONName+".value")
		pf.TargetNil = true
		b.WriteString(renderStreamField(pf, mapTarget, posVar))
		fmt.Fprintf(b, `		err = s.SkipSpace()
		%[1]s%[3]sif s.Bytes()[s.Pos] == ',' { s.Pos++; err = s.SkipSpace(); %[1]s%[4]scontinue }
		break
	}
	if s.Bytes()[s.Pos] != '}' { %[2]s }
	s.Pos++
`, chk, badObj, rm, streamNoCloseAfterComma(field, '}'))
		if !flat {
			b.WriteString("}\n") // close else (null-check)
		}
		return
	}
	switch f.ElemKind {
	case KindString:
		fmt.Fprintf(b, `%s, err = s.String()
%s`, mapTarget, chk)
	case KindBool:
		fmt.Fprintf(b, `%s, err = s.Bool()
%s`, mapTarget, chk)
	case KindInt, KindInt8, KindInt16, KindInt32, KindInt64:
		if f.ElemType == "int64" {
			fmt.Fprintf(b, `%s, err = s.Int64()
%s`, mapTarget, chk)
		} else {
			fmt.Fprintf(b, `var iv int64
iv, err = s.Int64()
%[3]s%[1]s = %[2]s(iv)
`, mapTarget, f.ElemType, chk)
		}
	case KindUint, KindUint8, KindUint16, KindUint32, KindUint64:
		if f.ElemType == "uint64" {
			fmt.Fprintf(b, `%s, err = s.Uint64()
%s`, mapTarget, chk)
		} else {
			fmt.Fprintf(b, `var uv uint64
uv, err = s.Uint64()
%[3]s%[1]s = %[2]s(uv)
`, mapTarget, f.ElemType, chk)
		}
	case KindFloat32, KindFloat64:
		if f.ElemKind == KindFloat64 {
			fmt.Fprintf(b, `%s, err = s.Float64()
%s`, mapTarget, chk)
		} else {
			fmt.Fprintf(b, `var fv float64
fv, err = s.Float64()
%[2]s%[1]s = float32(fv)
`, mapTarget, chk)
		}
	case KindStruct:
		if isGenerated(f.ElemType) {
			fmt.Fprintf(b, `var mv %s
mv, err = mv.DecodeFromStream(s)
%s%s = mv
`, f.ElemType, nestedDecodeErrCheck(fieldLit(f), f.MultiErr, false), mapTarget)
		} else {
			fmt.Fprintf(b, `start := s.Pos
prevPin := s.Shift
s.Shift = false
err = s.SkipValue()
s.Shift = prevPin
%[3]svar mv %[1]s
if err := json.Unmarshal(s.Bytes()[start:s.Pos], &mv); err != nil { return result, decode.NewParseErr(%[4]s, s.Pos, err) }
%[2]s = mv
`, f.ElemType, mapTarget, chk, field)
		}
	default:
		fmt.Fprintf(b, `err = s.SkipValue()
%s`, chk)
	}
	if len(f.ElemMods) > 0 {
		renderStreamMods(b, f.ElemMods, mapTarget, f.ElemType, f.ElemKind)
	}
	if len(f.ElemValidation) > 0 {
		renderValidationOn(b, f.ElemValidation, mapTarget, f.JSONName+".value", f.ElemKind, f.MultiErr, "")
	}
	fmt.Fprintf(b, `		err = s.SkipSpace()
		%[1]s%[3]sif s.Bytes()[s.Pos] == ',' { s.Pos++; err = s.SkipSpace(); %[1]s%[4]scontinue }
		break
	}
	if s.Bytes()[s.Pos] != '}' { %[2]s }
	s.Pos++
`, chk, badObj, rm, streamNoCloseAfterComma(field, '}'))
	if !flat {
		b.WriteString("}\n") // close else (null-check)
	}
}

// streamErrCheck returns the canonical `if err != nil { return ... }` tail
// emitted after a stream-side scan call. The field literal is embedded
// directly so no post-pass wrap is needed.
func streamErrCheck(field string) string {
	return fmt.Sprintf("if err != nil { return result, decode.NewParseErr(%s, s.Pos, err) }\n", field)
}

// bytesErrCheck is the bytes-path equivalent of streamErrCheck, with the
// 3-tuple `return result, pos, err` shape.
func bytesErrCheck(field, posVar string) string {
	return fmt.Sprintf("if err != nil { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, err) }\n", posVar, field)
}

// streamReadMore emits the canonical "buffer exhausted? pull more"
// guard for the stream path. keep controls compaction (`0` = grow
// without shift; `s.Pos` = discard consumed prefix); resetPos appends
// `s.Pos = 0` after a non-zero keep. The err is wrapped with field at
// emit time — no post-pass.
func streamReadMore(field, keep string, resetPos bool) string {
	reset := ""
	if resetPos {
		reset = "; s.Pos = 0"
	}
	return fmt.Sprintf("if s.Pos >= len(s.Bytes()) { if err = s.ReadMore(%s); err != nil { return result, decode.NewParseErr(%s, s.Pos, err) }%s }\n", keep, field, reset)
}

// nestedDecodeErrCheck emits the `if err != nil { … }` tail after a
// nested DecodeFrom / DecodeFromStream call. The outer field literal
// is woven into the decode.NewParseErr wrap so the inner *ParseError's
// Field path gets prepended (chaining "addr" + inner "street" →
// "addr.street").
//
// In multierr mode any validation failure (single leaf or aggregate)
// is merged into the outer's flat slice via Errors.Append, which
// prepends the outer field name onto every leaf's Path. Only true
// parse errors return early.
//
// bytesPath=true emits the 3-tuple `return result, pos, …` shape;
// false emits the 2-tuple stream shape.
func nestedDecodeErrCheck(field string, multierr, bytesPath bool) string {
	wrap := fmt.Sprintf("decode.NewParseErr(%s, s.Pos, err)", field)
	ret := fmt.Sprintf("return result, %s", wrap)
	if bytesPath {
		wrap = fmt.Sprintf("decode.NewParseErr(%s, i, err)", field)
		ret = fmt.Sprintf("return result, i, %s", wrap)
	}
	if !multierr {
		return fmt.Sprintf("if err != nil { %s }\n", ret)
	}
	return fmt.Sprintf(`if err != nil {
	if verr, ok := err.(validation.Error); ok {
		errs.Append(%[1]s, verr)
	} else {
		%[2]s
	}
}
`, field, ret)
}

