// oneofRegistry collects unique allowed-string sets emitted as
// package-level frozen slices, so OneOfError construction never
// allocates the slice itself. Reset at the start of each Generate call.
var oneofRegistry struct {
	names map[string]string // joined "a|b|c" → var name
	decls []string
}

func resetOneofRegistry() {
	oneofRegistry.names = map[string]string{}
	oneofRegistry.decls = nil
}

func registerOneOf(parts []string) string {
	key := strings.Join(parts, "\x00")
	if name, ok := oneofRegistry.names[key]; ok {
		return name
	}
	name := fmt.Sprintf("ggenOneof%d", len(oneofRegistry.names))
	oneofRegistry.names[key] = name
	quoted := make([]string, len(parts))
	for i, p := range parts {
		quoted[i] = strconv.Quote(p)
	}
	oneofRegistry.decls = append(oneofRegistry.decls,
		fmt.Sprintf("var %s = []string{%s}", name, strings.Join(quoted, ", ")))
	return name
}

// renderValidationOn emits Go source for validation checks against the
// variable named by ref. jsonName appears in error messages; kind selects
// type-appropriate comparisons; multiErr switches the failure action from
// early return to `errs = append(errs, ...)`. posVar controls the return
// shape: "" emits the top-level 2-tuple `return result, err`; any other
// value emits the 3-tuple `return result, <posVar>, err` used by mid-
// stream callers (slice/map element readers).
func renderValidationOn(b *bytes.Buffer, rules []ValidationRule, ref, jsonName string, kind TypeKind, multiErr bool, posVar string) {
	// onErr wraps a `&validation.XError{...}` literal into the appropriate
	// failure action: append to the flat `errs` slice in multierr mode,
	// or an early return otherwise. The leaf carries its own
	// root-relative Path; nested struct decodes prepend their outer
	// segment via [validation.Append] when bubbling up.
	onErr := func(errExpr string) string {
		if multiErr {
			return "errs = append(errs, " + errExpr + ")"
		}
		if posVar == "" {
			return "return result, " + errExpr
		}
		return "return result, " + posVar + ", " + errExpr
	}

	// vstr is the source expression for the offending Value field of a
	// pattern/length error. For string-typed refs it's just `ref`. For
	// numeric refs that need to be cast to string for the error (none of
	// today's patterns), this would adapt — currently a no-op pass-through.

	for _, v := range rules {
		switch v.Name {
		case "required", "optional":
			// required handled separately; optional is a no-op marker

		case "notempty":
			fmt.Fprintf(b, "if len(%s) == 0 {\n\t%s\n}\n", ref,
				onErr(fmt.Sprintf("&validation.NotEmptyError{Path: []string{%q}}", jsonName)))

		case "len":
			fmt.Fprintf(b, "if len(%s) != %s {\n\t%s\n}\n", ref, v.Value,
				onErr(fmt.Sprintf("&validation.LenError{Path: []string{%q}, Want: %s, Got: len(%s)}", jsonName, v.Value, ref)))
		case "minlen":
			fmt.Fprintf(b, "if len(%s) < %s {\n\t%s\n}\n", ref, v.Value,
				onErr(fmt.Sprintf("&validation.MinLenError{Path: []string{%q}, Limit: %s, Got: len(%s)}", jsonName, v.Value, ref)))
		case "maxlen":
			fmt.Fprintf(b, "if len(%s) > %s {\n\t%s\n}\n", ref, v.Value,
				onErr(fmt.Sprintf("&validation.MaxLenError{Path: []string{%q}, Limit: %s, Got: len(%s)}", jsonName, v.Value, ref)))

		case "runes":
			fmt.Fprintf(b, "if utf8.RuneCountInString(%s) != %s {\n\t%s\n}\n", ref, v.Value,
				onErr(fmt.Sprintf("&validation.RunesError{Path: []string{%q}, Want: %s, Got: utf8.RuneCountInString(%s)}", jsonName, v.Value, ref)))
		case "minrunes":
			fmt.Fprintf(b, "if utf8.RuneCountInString(%s) < %s {\n\t%s\n}\n", ref, v.Value,
				onErr(fmt.Sprintf("&validation.MinRunesError{Path: []string{%q}, Limit: %s, Got: utf8.RuneCountInString(%s)}", jsonName, v.Value, ref)))
		case "maxrunes":
			fmt.Fprintf(b, "if utf8.RuneCountInString(%s) > %s {\n\t%s\n}\n", ref, v.Value,
				onErr(fmt.Sprintf("&validation.MaxRunesError{Path: []string{%q}, Limit: %s, Got: utf8.RuneCountInString(%s)}", jsonName, v.Value, ref)))

		case "gt":
			fmt.Fprintf(b, "if %s <= %s {\n\t%s\n}\n", ref, v.Value,
				onErr(fmt.Sprintf("&validation.GTError{Path: []string{%q}, Limit: %s, Value: %s}", jsonName, v.Value, ref)))
		case "gte":
			fmt.Fprintf(b, "if %s < %s {\n\t%s\n}\n", ref, v.Value,
				onErr(fmt.Sprintf("&validation.GTEError{Path: []string{%q}, Limit: %s, Value: %s}", jsonName, v.Value, ref)))
		case "lt":
			fmt.Fprintf(b, "if %s >= %s {\n\t%s\n}\n", ref, v.Value,
				onErr(fmt.Sprintf("&validation.LTError{Path: []string{%q}, Limit: %s, Value: %s}", jsonName, v.Value, ref)))
		case "lte":
			fmt.Fprintf(b, "if %s > %s {\n\t%s\n}\n", ref, v.Value,
				onErr(fmt.Sprintf("&validation.LTEError{Path: []string{%q}, Limit: %s, Value: %s}", jsonName, v.Value, ref)))

		case "eq":
			if kind == KindString {
				fmt.Fprintf(b, "if %s != %q {\n\t%s\n}\n",
					ref, v.Value,
					onErr(fmt.Sprintf("&validation.EqError{Path: []string{%q}, Want: %q, Value: %s}", jsonName, v.Value, ref)))
			} else if isNumeric(kind) {
				fmt.Fprintf(b, "if %s != %s {\n\t%s\n}\n",
					ref, v.Value,
					onErr(fmt.Sprintf("&validation.EqError{Path: []string{%q}, Want: %s, Value: %s}", jsonName, v.Value, ref)))
			}
		case "neq":
			if kind == KindString {
				fmt.Fprintf(b, "if %s == %q {\n\t%s\n}\n",
					ref, v.Value,
					onErr(fmt.Sprintf("&validation.NeqError{Path: []string{%q}, Want: %q, Value: %s}", jsonName, v.Value, ref)))
			} else if isNumeric(kind) {
				fmt.Fprintf(b, "if %s == %s {\n\t%s\n}\n",
					ref, v.Value,
					onErr(fmt.Sprintf("&validation.NeqError{Path: []string{%q}, Want: %s, Value: %s}", jsonName, v.Value, ref)))
			}

		case "oneof":
			cases := renderOneofCases(kind, v.Value)
			parts := strings.Split(v.Value, "|")
			varName := registerOneOf(parts)
			fmt.Fprintf(b, "switch %s {\ncase %s:\ndefault:\n\t%s\n}\n",
				ref, cases,
				onErr(fmt.Sprintf("&validation.OneOfError{Path: []string{%q}, Allowed: %s, Value: %s}", jsonName, varName, ref)))

		case "email":
			fmt.Fprintf(b, "if !decode.IsEmail(%s) {\n\t%s\n}\n", ref,
				onErr(fmt.Sprintf("&validation.EmailError{Path: []string{%q}, Value: %s}", jsonName, ref)))
		case "url":
			fmt.Fprintf(b, "if !decode.IsURL(%s) {\n\t%s\n}\n", ref,
				onErr(fmt.Sprintf("&validation.URLError{Path: []string{%q}, Value: %s}", jsonName, ref)))

		case "ascii":
			fmt.Fprintf(b, "if !decode.IsASCII(%s) {\n\t%s\n}\n", ref,
				onErr(fmt.Sprintf("&validation.ASCIIError{Path: []string{%q}, Value: %s}", jsonName, ref)))
		case "printable":
			fmt.Fprintf(b, "if !decode.IsPrintable(%s) {\n\t%s\n}\n", ref,
				onErr(fmt.Sprintf("&validation.PrintableError{Path: []string{%q}, Value: %s}", jsonName, ref)))
		case "alphanum":
			fmt.Fprintf(b, "if !decode.IsAlphanum(%s) {\n\t%s\n}\n", ref,
				onErr(fmt.Sprintf("&validation.AlphanumError{Path: []string{%q}, Value: %s}", jsonName, ref)))
		case "numeric":
			fmt.Fprintf(b, "if !decode.IsNumeric(%s) {\n\t%s\n}\n", ref,
				onErr(fmt.Sprintf("&validation.NumericError{Path: []string{%q}, Value: %s}", jsonName, ref)))
		case "lower":
			fmt.Fprintf(b, "if !decode.IsLower(%s) {\n\t%s\n}\n", ref,
				onErr(fmt.Sprintf("&validation.LowerError{Path: []string{%q}, Value: %s}", jsonName, ref)))
		case "upper":
			fmt.Fprintf(b, "if !decode.IsUpper(%s) {\n\t%s\n}\n", ref,
				onErr(fmt.Sprintf("&validation.UpperError{Path: []string{%q}, Value: %s}", jsonName, ref)))
		case "hexadecimal":
			fmt.Fprintf(b, "if !decode.IsHex(%s) {\n\t%s\n}\n", ref,
				onErr(fmt.Sprintf("&validation.HexadecimalError{Path: []string{%q}, Value: %s}", jsonName, ref)))

		case "starts":
			fmt.Fprintf(b, "if !strings.HasPrefix(%s, %q) {\n\t%s\n}\n",
				ref, v.Value,
				onErr(fmt.Sprintf("&validation.StartsError{Path: []string{%q}, Want: %q, Value: %s}", jsonName, v.Value, ref)))
		case "ends":
			fmt.Fprintf(b, "if !strings.HasSuffix(%s, %q) {\n\t%s\n}\n",
				ref, v.Value,
				onErr(fmt.Sprintf("&validation.EndsError{Path: []string{%q}, Want: %q, Value: %s}", jsonName, v.Value, ref)))
		case "contains":
			fmt.Fprintf(b, "if !strings.Contains(%s, %q) {\n\t%s\n}\n",
				ref, v.Value,
				onErr(fmt.Sprintf("&validation.ContainsError{Path: []string{%q}, Want: %q, Value: %s}", jsonName, v.Value, ref)))

		case "multiple":
			fmt.Fprintf(b, "if %s %% %s != 0 {\n\t%s\n}\n", ref, v.Value,
				onErr(fmt.Sprintf("&validation.MultipleError{Path: []string{%q}, Of: %s, Value: %s}", jsonName, v.Value, ref)))

		default:
			// `@FuncName` (or `@pkg.FuncName`) — user-defined validator
			// resolved at parse time. Direct call into the user's function;
			// non-nil return wraps as validation.CustomError.
			if v.Custom {
				call := v.FuncName
				if v.PkgName != "" {
					call = v.PkgName + "." + v.FuncName
				}
				fmt.Fprintf(b, "if err := %s(%s); err != nil {\n\t%s\n}\n",
					call, ref,
					onErr(fmt.Sprintf("&validation.CustomError{Path: []string{%q}, Name: %q, Cause: err}", jsonName, v.Name)))
			}
			// Unknown non-custom names are silently ignored — keeps the
			// parser tolerant of forward-compatible rule additions.
		}
	}
}

func renderOneofCases(kind TypeKind, raw string) string {
	parts := strings.Split(raw, "|")
	out := make([]string, len(parts))
	for i, p := range parts {
		if kind == KindString {
			out[i] = strconv.Quote(p)
		} else {
			out[i] = p
		}
	}
	return strings.Join(out, ", ")
}

// renderAppendJSON emits the body of an AppendJSON method: a series of
// append/helper calls that emit the struct as JSON into dst.
// fieldIsConditional reports whether the field's marshal emission depends on
// a runtime check (omitempty/omitzero). Fields without skip conditions are
// always emitted.
func fieldIsConditional(f FieldInfo) bool {
	if f.Inline {
		return true
	}
	if !f.OmitEmpty && !f.OmitZero {
		return false
	}
	return fieldSkipExpr(f, "s."+f.GoName) != ""
}

// fieldSkipExpr returns a Go boolean expression that evaluates to true when
// the field should be EMITTED. Empty string means "always emit".
func fieldSkipExpr(f FieldInfo, ref string) string {
	// omitempty: skip if JSON-empty (null, "", [], {}).
	// omitzero: skip if Go zero value.
	var emitConds []string
	if f.OmitEmpty {
		if f.Pointer {
			emitConds = append(emitConds, fmt.Sprintf("%s != nil", ref))
		} else {
			switch f.Kind {
			case KindString:
				emitConds = append(emitConds, fmt.Sprintf("%s != \"\"", ref))
			case KindSlice, KindMap:
				emitConds = append(emitConds, fmt.Sprintf("len(%s) > 0", ref))
			case KindRawJSON:
				// Underlying []byte; nil/empty → skip. Strict v2 also
				// considers literal `null`/`[]`/`{}` content JSON-empty;
				// we don't peek into the bytes — nil/len-0 is the bound.
				emitConds = append(emitConds, fmt.Sprintf("len(%s) > 0", ref))
			case KindAny:
				emitConds = append(emitConds, fmt.Sprintf("%s != nil", ref))
			case KindSQLNull:
				// jsonv2: NullX.MarshalJSON returns `null` when !Valid,
				// which is JSON-empty → omit. Match by emitting only when Valid.
				emitConds = append(emitConds, fmt.Sprintf("%s.Valid", ref))
			case KindBigInt, KindBigFloat, KindBigRat:
				// jsonv2: big.X.MarshalJSON of zero returns `"0"` (or `"0/1"`
				// for Rat) which is JSON-empty (zero number). Skip the zero.
				emitConds = append(emitConds, fmt.Sprintf("%s.Sign() != 0", ref))
			}
		}
	}
	if f.OmitZero {
		if f.Pointer {
			emitConds = append(emitConds, fmt.Sprintf("%s != nil", ref))
		} else {
			switch f.Kind {
			case KindString:
				emitConds = append(emitConds, fmt.Sprintf("%s != \"\"", ref))
			case KindBool:
				emitConds = append(emitConds, ref)
			case KindInt, KindInt8, KindInt16, KindInt32, KindInt64,
				KindUint, KindUint8, KindUint16, KindUint32, KindUint64,
				KindFloat32, KindFloat64:
				emitConds = append(emitConds, fmt.Sprintf("%s != 0", ref))
			case KindSlice, KindBytes, KindMap, KindRawJSON:
				// jsonv2 omitzero: Go-zero of a slice/map is nil, not empty.
				// `make([]T, 0)` is non-nil and must be emitted.
				emitConds = append(emitConds, fmt.Sprintf("%s != nil", ref))
			case KindStruct:
				emitConds = append(emitConds, fmt.Sprintf("%s != (%s{})", ref, f.GoType))
			case KindTime:
				emitConds = append(emitConds, fmt.Sprintf("!%s.IsZero()", ref))
			case KindDuration:
				emitConds = append(emitConds, fmt.Sprintf("%s != 0", ref))
			case KindNetIP:
				emitConds = append(emitConds, fmt.Sprintf("%s != nil", ref))
			case KindNetipAddr, KindNetipPrefix:
				emitConds = append(emitConds, fmt.Sprintf("%s.IsValid()", ref))
			case KindAny:
				emitConds = append(emitConds, fmt.Sprintf("%s != nil", ref))
			case KindSQLNull:
				// Go-zero for sql.NullX is the all-fields-zero literal,
				// which is comparable (Valid: false, X: zero).
				emitConds = append(emitConds, fmt.Sprintf("%s != (%s{})", ref, f.GoType))
			case KindURL:
				// url.URL is a comparable struct.
				emitConds = append(emitConds, fmt.Sprintf("%s != (%s{})", ref, f.GoType))
			case KindBigInt, KindBigFloat, KindBigRat:
				// big.Int/Float/Rat have unexported slices, not comparable.
				// Sign() returns 0 for the zero value — cheap and reliable.
				emitConds = append(emitConds, fmt.Sprintf("%s.Sign() != 0", ref))
			case KindArray:
				// [N]T comparable when element kind is comparable. Use the
				// type literal for the all-zero comparison.
				emitConds = append(emitConds, fmt.Sprintf("%s != (%s{})", ref, f.GoType))
			}
		}
	}
	if len(emitConds) == 0 {
		return ""
	}
	// Join with && (if any skip rule says skip, skip).
	return strings.Join(slices.Compact(emitConds), " && ")
}

func renderAppendJSON(b *bytes.Buffer, s StructInfo) {
	fmt.Fprintf(b, "func (s %s) AppendJSON(dst []byte) ([]byte, error) {\n", s.Name)
	if s.IsAlias {
		renderAliasAppendJSON(b, s)
		b.WriteString("}\n\n")
		return
	}
	// coalesceConstAppends operates on the assembled body string — fold
	// adjacent constant-byte appends post-emit, then ship the result
	// into the caller's builder.
	var body bytes.Buffer
	renderAppendJSONBody(&body, s)
	b.WriteString(coalesceConstAppends(body.String()))
	b.WriteString("}\n\n")
}

// coalesceConstAppends merges adjacent constant-bytes append lines into a
// single append. Recognizes both `dst = append(dst, ...)` and the
// terminating `return append(dst, ...), nil` form, so the trailing `}` of
// a struct gets folded into the prior `]`/`}` etc.
//
// Single-byte payloads emit as `'X'` (char literal); multi-byte as
// `"…"...` (string spread). The compiler treats them identically but
// char-literal form is more idiomatic for one byte.
func coalesceConstAppends(src string) string {
	lines := strings.Split(src, "\n")
	var out []string
	var pending []byte
	var indent string
	flushAs := func(prefix, suffix string) {
		if len(pending) == 0 {
			return
		}
		out = append(out, indent+prefix+formatAppendArgs(pending)+suffix)
		pending = nil
	}
	flush := func() { flushAs("dst = append(dst, ", ")") }
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if bs, ok := parseConstAppend(trimmed); ok {
			if len(pending) == 0 {
				indent = line[:len(line)-len(trimmed)]
			}
			pending = append(pending, bs...)
			continue
		}
		if bs, ok := parseConstReturnAppend(trimmed); ok {
			if len(pending) == 0 {
				indent = line[:len(line)-len(trimmed)]
			}
			pending = append(pending, bs...)
			flushAs("return append(dst, ", "), nil")
			continue
		}
		flush()
		out = append(out, line)
	}
	flush()
	return strings.Join(out, "\n")
}

// formatAppendArgs renders the bytes as the `args` of an append call.
// Single byte → char literal; multi-byte → string spread.
func formatAppendArgs(p []byte) string {
	if len(p) == 1 {
		return strconv.QuoteRune(rune(p[0]))
	}
	return fmt.Sprintf("%q...", string(p))
}

// parseConstAppend recognizes `dst = append(dst, X)` where X is one of
// `"…"...`, `'a'`, or `'a', 'b', …` (all compile-time constant bytes).
// Returns the literal bytes; anything non-constant returns false.
func parseConstAppend(line string) ([]byte, bool) {
	const prefix = "dst = append(dst,"
	if !strings.HasPrefix(line, prefix) || !strings.HasSuffix(line, ")") {
		return nil, false
	}
	return parseConstAppendArgs(line[len(prefix) : len(line)-1])
}

// parseConstReturnAppend is the trailing-return variant: matches
// `return append(dst, X), nil` and extracts X's bytes if constant.
func parseConstReturnAppend(line string) ([]byte, bool) {
	const prefix = "return append(dst,"
	const suffix = "), nil"
	if !strings.HasPrefix(line, prefix) || !strings.HasSuffix(line, suffix) {
		return nil, false
	}
	return parseConstAppendArgs(line[len(prefix) : len(line)-len(suffix)])
}

func parseConstAppendArgs(args string) ([]byte, bool) {
	rest := strings.TrimSpace(args)
	if before, ok := strings.CutSuffix(rest, "..."); ok {
		s := strings.TrimSpace(before)
		if !strings.HasPrefix(s, `"`) {
			return nil, false
		}
		unq, err := strconv.Unquote(s)
		if err != nil {
			return nil, false
		}
		return []byte(unq), true
	}
	// `'a', 'b', '\n'` — split by `,` is wrong when the literal IS a
	// comma. Walk char literals manually, respecting `\X` escapes.
	var out []byte
	for len(rest) > 0 {
		if rest[0] != '\'' {
			return nil, false
		}
		i := 1
		for i < len(rest) {
			if rest[i] == '\\' {
				i += 2
				continue
			}
			if rest[i] == '\'' {
				break
			}
			i++
		}
		if i >= len(rest) {
			return nil, false
		}
		unq, err := strconv.Unquote(rest[:i+1])
		if err != nil || len(unq) != 1 {
			return nil, false
		}
		out = append(out, unq[0])
		rest = strings.TrimSpace(rest[i+1:])
		if len(rest) == 0 {
			break
		}
		if rest[0] != ',' {
			return nil, false
		}
		rest = strings.TrimSpace(rest[1:])
	}
	return out, true
}

func renderAppendJSONBody(b *bytes.Buffer, s StructInfo) {
	if len(s.Fields) == 0 {
		b.WriteString("return append(dst, '{', '}'), nil")
		return
	}

	// `var err error` is declared up front so emitters can do
	// `dst, err = X.AppendJSON(dst); if err != nil { return dst, err }`
	// without having to redeclare per call site. Marked with `_ = err` if
	// no fallible call ends up using it (e.g. struct of pure primitives).
	b.WriteString("var err error\n_ = err\n")

	// Detect if any field is conditional; if none, use the path that
	// hard-codes `{` into the first field's prefix and commas before the rest.
	anyConditional := slices.ContainsFunc(s.Fields, fieldIsConditional)

	if !anyConditional {
		for i, f := range s.Fields {
			prefix := `,"` + f.JSONName + `":`
			if i == 0 {
				prefix = `{"` + f.JSONName + `":`
			}
			ref := "s." + f.GoName
			if newPrefix, code, ok := foldLeadingQuote(f, ref, prefix); ok {
				fmt.Fprintf(b, "dst = append(dst, %q...)\n", newPrefix)
				b.WriteString(code)
			} else {
				fmt.Fprintf(b, "dst = append(dst, %q...)\n", prefix)
				renderAppendValue(b, f, ref)
			}
		}
		b.WriteString("return append(dst, '}'), nil")
		return
	}

	// Conditional path: track emissions via len(dst) vs start.
	b.WriteString("dst = append(dst, '{')\nstart := len(dst)\n")
	for _, f := range s.Fields {
		ref := "s." + f.GoName
		if f.Inline {
			valEmit := inlineValueEmit(f)
			fmt.Fprintf(b, `for k, v := range %[1]s {
if len(dst) > start { dst = append(dst, ',') }
dst = append(dst, '"')
dst = %[2]s(dst, k)
dst = append(dst, ':')
%[3]s}
`, ref, appendStrFn(f.HTMLEscape), valEmit)
			continue
		}
		emit := fieldSkipExpr(f, ref)
		// For pointer fields the emit predicate is the nil check, so the
		// guard we're inside already proves non-nil. Peel one pointer level
		// off before renderAppendValue so it doesn't emit a dead
		// `if ref == nil { null }` rung inside the `if ref != nil { ... }`.
		av, aref := f, ref
		if emit != "" && f.Pointer {
			av.GoType = strings.TrimPrefix(av.GoType, "*")
			av.Pointer = strings.HasPrefix(av.GoType, "*")
			av.PointeeType = strings.TrimPrefix(av.GoType, "*")
			if !av.Pointer {
				av.PointeeType = ""
			}
			aref = "(*" + ref + ")"
		}
		if emit != "" {
			fmt.Fprintf(b, "if %s {\n", emit)
		}
		b.WriteString("if len(dst) > start { dst = append(dst, ',') }\n")
		prefix := `"` + f.JSONName + `":`
		if newPrefix, code, ok := foldLeadingQuote(av, aref, prefix); ok {
			fmt.Fprintf(b, "dst = append(dst, %q...)\n", newPrefix)
			b.WriteString(code)
		} else {
			fmt.Fprintf(b, "dst = append(dst, %q...)\n", prefix)
			renderAppendValue(b, av, aref)
		}
		if emit != "" {
			b.WriteString("}\n")
		}
	}
	b.WriteString("return append(dst, '}'), nil")
}

// inlineValueEmit returns the inline-catch-all marshal code for one map
// entry's value, assuming the loop variable is `v`. Specializes a couple of
// elem kinds to skip the `any` boxing AppendAny does; everything else
// (including cross-pkg structs, slices/maps as values, native types)
// goes through AppendAny's reflection path.
func inlineValueEmit(f FieldInfo) string {
	switch f.ElemKind {
	case KindString:
		return fmt.Sprintf("dst = append(dst, '\"')\ndst = %s(dst, v)\n", appendStrFn(f.HTMLEscape))
	case KindStruct:
		if isGenerated(f.ElemType) {
			return "if dst, err = v.AppendJSON(dst); err != nil { return dst, err }\n"
		}
	case KindRawJSON:
		// jsontext.Value / json.RawMessage: passthrough.
		return "dst = append(dst, v...)\n"
	}
	if f.ElemType == "jsontext.Value" {
		return "dst = append(dst, v...)\n"
	}
	return fmt.Sprintf("if dst, err = %s(dst, v); err != nil { return dst, err }\n", appendAnyFn(f.HTMLEscape))
}

func renderAppendValue(b *bytes.Buffer, f FieldInfo, ref string) {
	if f.Pointer {
		// A nil at any level of the chain emits `null`; only a fully-allocated
		// chain reaches the leaf. One flat `else if` ladder (one rung per
		// pointer level, matching stdlib's intermediate-nil → `null`) rather
		// than a nested staircase. No json.Marshal fallback at any depth.
		depth, leafType := pointerDepth(f.GoType)
		leaf := f
		leaf.Pointer = false
		leaf.PointeeType = ""
		leaf.GoType = leafType
		leaf.Kind = resolveKind(leafType)
		for k := range depth {
			kw := "if"
			if k > 0 {
				kw = "} else if"
			}
			fmt.Fprintf(b, "%s %s == nil {\n\tdst = append(dst, 'n', 'u', 'l', 'l')\n", kw, derefStr(ref, k))
		}
		b.WriteString("} else {\n\t")
		renderAppendValue(b, leaf, derefStr(ref, depth))
		b.WriteString("}\n")
		return
	}
	if f.String {
		switch f.Kind {
		case KindBool:
			// jsonv2 dropped `,string` for bool — wire shape stays bare
			// `true`/`false`. Fall through to the default emit below for
			// stdcompat with encoding/json/v2.
		case KindInt, KindInt8, KindInt16, KindInt32:
			fmt.Fprintf(b, "dst = append(dst, '\"')\ndst = strconv.AppendInt(dst, int64(%s), 10)\ndst = append(dst, '\"')\n", ref)
			return
		case KindInt64:
			fmt.Fprintf(b, "dst = append(dst, '\"')\ndst = strconv.AppendInt(dst, %s, 10)\ndst = append(dst, '\"')\n", ref)
			return
		case KindUint, KindUint8, KindUint16, KindUint32:
			fmt.Fprintf(b, "dst = append(dst, '\"')\ndst = strconv.AppendUint(dst, uint64(%s), 10)\ndst = append(dst, '\"')\n", ref)
			return
		case KindUint64:
			fmt.Fprintf(b, "dst = append(dst, '\"')\ndst = strconv.AppendUint(dst, %s, 10)\ndst = append(dst, '\"')\n", ref)
			return
		case KindFloat32:
			fmt.Fprintf(b, "dst = append(dst, '\"')\nif dst, err = encode.AppendFloat(dst, float64(%s), 32); err != nil { return dst, err }\ndst = append(dst, '\"')\n", ref)
			return
		case KindFloat64:
			fmt.Fprintf(b, "dst = append(dst, '\"')\nif dst, err = encode.AppendFloat(dst, %s, 64); err != nil { return dst, err }\ndst = append(dst, '\"')\n", ref)
			return
		}
		// unknown/invalid combo — fall through to default
	}
	switch f.Kind {
	case KindString:
		fmt.Fprintf(b, "dst = append(dst, '\"')\ndst =%s(dst, %s)\n", appendStrFn(f.HTMLEscape), ref)
	case KindBool:
		fmt.Fprintf(b, "dst = strconv.AppendBool(dst, %s)\n", ref)
	case KindInt, KindInt8, KindInt16, KindInt32:
		fmt.Fprintf(b, "dst = strconv.AppendInt(dst, int64(%s), 10)\n", ref)
	case KindInt64:
		fmt.Fprintf(b, "dst = strconv.AppendInt(dst, %s, 10)\n", ref)
	case KindUint, KindUint8, KindUint16, KindUint32:
		fmt.Fprintf(b, "dst = strconv.AppendUint(dst, uint64(%s), 10)\n", ref)
	case KindUint64:
		fmt.Fprintf(b, "dst = strconv.AppendUint(dst, %s, 10)\n", ref)
	case KindFloat32:
		fmt.Fprintf(b, "if dst, err = encode.AppendFloat(dst, float64(%s), 32); err != nil { return dst, err }\n", ref)
	case KindFloat64:
		fmt.Fprintf(b, "if dst, err = encode.AppendFloat(dst, %s, 64); err != nil { return dst, err }\n", ref)
	case KindStruct:
		if isGenerated(f.GoType) {
			fmt.Fprintf(b, "if dst, err = %s.AppendJSON(dst); err != nil { return dst, err }\n", ref)
		} else {
			b.WriteString(renderCrossPkgStructAppend(f, ref))
		}
	case KindSlice, KindArray:
		renderAppendSlice(b, f, ref)
	case KindMap:
		renderAppendMap(b, f, ref)
	case KindBytes:
		renderAppendBytes(b, f, ref)
	case KindTime:
		renderAppendTime(b, f, ref)
	case KindDuration:
		renderAppendDuration(b, f, ref)
	case KindNetIP, KindNetipAddr, KindNetipPrefix:
		// All three implement encoding.TextAppender (Go 1.24+). One
		// uniform emit path — same as the cross-pkg TextAppender branch.
		fmt.Fprintf(b, `dst = append(dst, '"')
if dst, err = %s.AppendText(dst); err != nil { return dst, err }
dst = append(dst, '"')
`, ref)
	case KindRawJSON:
		// Emit raw bytes verbatim (or "null" if empty/nil).
		fmt.Fprintf(b, `if len(%s) == 0 {
	dst = append(dst, 'n', 'u', 'l', 'l')
} else {
	dst = append(dst, %s...)
}
`, ref, ref)
	case KindURL:
		fmt.Fprintf(b, "dst = append(dst, '\"')\ndst = encode.AppendURL(dst, %s)\ndst = append(dst, '\"')\n", ref)
	case KindBigInt:
		// big.Int.Append takes (buf, base) and appends in place — no alloc.
		fmt.Fprintf(b, "dst = (&%s).Append(dst, 10)\n", ref)
	case KindBigFloat:
		// big.Float as JSON string — matches jsonv2's expected wire format.
		// big.Float.Append: (buf, format byte, prec int).
		fmt.Fprintf(b, "dst = append(dst, '\"')\ndst = (&%s).Append(dst, 'g', -1)\ndst = append(dst, '\"')\n", ref)
	case KindBigRat:
		// Rat is JSON-stringified ("num/denom" or just "n" when whole).
		// AppendText cuts ~3 allocs vs %s(dst, (&r).RatString()) — same
		// wire shape (collapses to integer when IsInt()), but writes
		// straight into dst instead of materializing a fresh string.
		fmt.Fprintf(b, "dst = append(dst, '\"')\nif dst, err = (&%s).AppendText(dst); err != nil { return dst, err }\ndst = append(dst, '\"')\n", ref)
	case KindSQLNull:
		spec, ok := SQLNullSpec(f.GoType)
		if !ok {
			return
		}
		// Build the inner-value emit for the .X field — reuse renderAppendValue
		// with a synthetic FieldInfo whose Kind is the inner kind.
		innerField := FieldInfo{Kind: spec.Inner, GoType: spec.Type, Format: f.Format}
		fmt.Fprintf(b, "if !%s.Valid {\n\tdst = append(dst, 'n', 'u', 'l', 'l')\n} else {\n\t", ref)
		renderAppendValue(b, innerField, ref+"."+spec.Field)
		b.WriteString("}\n")
	case KindAny:
		// AppendAny type-switches on common runtime types (primitives,
		// []any, map[string]any) before falling back to encoding/json.
		fmt.Fprintf(b, "if dst, err = %s(dst, %s); err != nil { return dst, err }\n", appendAnyFn(f.HTMLEscape), ref)
	}
}

// renderAppendBytes emits marshal code for a []byte field based on format.
// Inlines the stdlib AppendEncode call between quote bytes — the
// previously-helper-wrapped versions saved no work over the inlined form.
func renderAppendBytes(b *bytes.Buffer, f FieldInfo, ref string) {
	// nil []byte → null (stdlib v1 parity; decode accepts null → nil).
	fmt.Fprintf(b, "if %s == nil {\ndst = append(dst, \"null\"...)\n} else {\n", ref)
	renderAppendBytesValue(b, f, ref)
	b.WriteString("}\n")
}

func renderAppendBytesValue(b *bytes.Buffer, f FieldInfo, ref string) {
	switch f.Format {
	case "", "base64":
		fmt.Fprintf(b, "dst = append(dst, '\"')\ndst =base64.StdEncoding.AppendEncode(dst, %s)\ndst =append(dst, '\"')\n", ref)
	case "base64url":
		fmt.Fprintf(b, "dst = append(dst, '\"')\ndst =base64.URLEncoding.AppendEncode(dst, %s)\ndst =append(dst, '\"')\n", ref)
	case "base32":
		fmt.Fprintf(b, "dst = append(dst, '\"')\ndst =base32.StdEncoding.AppendEncode(dst, %s)\ndst =append(dst, '\"')\n", ref)
	case "base32hex":
		fmt.Fprintf(b, "dst = append(dst, '\"')\ndst =base32.HexEncoding.AppendEncode(dst, %s)\ndst =append(dst, '\"')\n", ref)
	case "base16", "hex":
		fmt.Fprintf(b, "dst = append(dst, '\"')\ndst =hex.AppendEncode(dst, %s)\ndst =append(dst, '\"')\n", ref)
	case "array":
		fmt.Fprintf(b, `dst = append(dst, '[')
for i, b := range %s {
	if i > 0 { dst = append(dst, ',') }
	dst = strconv.AppendUint(dst, uint64(b), 10)
}
dst = append(dst, ']')
`, ref)
	default:
		// Unknown format: fall back to base64.
		fmt.Fprintf(b, "dst = append(dst, '\"')\ndst =base64.StdEncoding.AppendEncode(dst, %s)\ndst =append(dst, '\"')\n", ref)
	}
}

// timeLayoutExpr returns the Go expression for a format value on a time.Time
// field (e.g. "RFC3339" → time.RFC3339, 'custom' → "custom" literal). It also
// returns whether the format targets a numeric encoding (unix family).
// timeFormatSize returns the JSONSize byte budget for a `time.Time`
// field with the given `format:` option, including surrounding quotes
// (or none for numeric `unix*` variants). Unknown / custom layouts
// fall back to `len(format) + 6` — output length tracks the layout
// string closely (literal text passes through verbatim) with a small
// slack for `_2` style space-pads and timezone offset width.
func timeFormatSize(format string) int {
	switch format {
	case "unix":
		// Worst case: sign + 10-digit unix seconds + `.` + 9-digit
		// nanos = 21 chars. Plus a small slack for the float
		// formatter's exponent path if it ever kicks in (it doesn't
		// at 'f' format, but be defensive).
		return 24
	case "unixmilli", "unixmicro", "unixnano":
		return sizeInt // int64 digits, no quotes
	case "", "RFC3339Nano":
		return 35 + 2
	case "RFC3339":
		return 25 + 2
	case "ANSIC":
		return 24 + 2
	case "UnixDate":
		// "MST" → up to 5-char offset when zone has no name.
		return 30 + 2
	case "RubyDate":
		return 30 + 2
	case "RFC822":
		// "MST" → up to 5-char offset when zone has no name.
		return 21 + 2
	case "RFC822Z":
		return 21 + 2
	case "RFC850":
		// "MST" → up to 5-char offset when zone has no name.
		return 32 + 2
	case "RFC1123":
		// "MST" → up to 5-char offset when zone has no name.
		return 31 + 2
	case "RFC1123Z":
		return 31 + 2
	case "Kitchen":
		return 7 + 2
	case "Stamp":
		return 15 + 2
	case "StampMilli":
		return 19 + 2
	case "StampMicro":
		return 22 + 2
	case "StampNano":
		return 25 + 2
	case "DateTime":
		return 19 + 2
	case "DateOnly":
		return 10 + 2
	case "TimeOnly":
		return 8 + 2
	case "Layout":
		return 26 + 2
	}
	return len(format) + 6
}

// durationFormatSize returns the JSONSize byte budget for a
// `time.Duration` field. Numeric formats (sec/milli/micro/nano) emit
// an int with no quotes; the default `units` format renders as a
// quoted "NhNmNs" string capped at ~25 chars + quotes.
func durationFormatSize(format string) int {
	switch format {
	case "sec", "milli", "micro", "nano":
		return sizeInt
	}
	return 25 + 2 // "<NhNmNs>" worst case
}

func timeLayoutExpr(format string) (layout string, numeric string) {
	switch format {
	case "":
		return "time.RFC3339Nano", ""
	case "unix":
		return "", "Unix"
	case "unixmilli":
		return "", "UnixMilli"
	case "unixmicro":
		return "", "UnixMicro"
	case "unixnano":
		return "", "UnixNano"
	}
	// Recognized time-package constant names.
	switch format {
	case "Layout", "ANSIC", "UnixDate", "RubyDate",
		"RFC822", "RFC822Z", "RFC850", "RFC1123", "RFC1123Z",
		"RFC3339", "RFC3339Nano", "Kitchen",
		"Stamp", "StampMilli", "StampMicro", "StampNano",
		"DateTime", "DateOnly", "TimeOnly":
		return "time." + format, ""
	}
	// Custom layout — emit as a string literal.
	return strconv.Quote(format), ""
}

func renderAppendTime(b *bytes.Buffer, f FieldInfo, ref string) {
	layout, numeric := timeLayoutExpr(f.Format)
	if numeric != "" {
		// `format:unix` is the seconds unit — sub-second nanos must
		// emit as a fractional decimal to match jsonv2's wire format
		// (jsonv2 emits e.g. `1778762096.789` when nanos != 0).
		// `unixmilli`/`unixmicro`/`unixnano` work at integer granularity
		// of their respective units, so plain AppendInt is correct.
		if numeric == "Unix" {
			fmt.Fprintf(b, "dst = strconv.AppendFloat(dst, float64(%s.UnixNano())/1e9, 'f', -1, 64)\n", ref)
			return
		}
		fmt.Fprintf(b, "dst = strconv.AppendInt(dst, %s.%s(), 10)\n", ref, numeric)
		return
	}
	fmt.Fprintf(b, "dst = append(dst, '\"')\ndst = %s.AppendFormat(dst, %s)\ndst = append(dst, '\"')\n", ref, layout)
}

func renderAppendDuration(b *bytes.Buffer, f FieldInfo, ref string) {
	switch f.Format {
	case "sec":
		// encode.AppendFloat for the stdlib 'f'/'e' format selection —
		// 'g' flips to scientific at |sec| >= 1e6. Seconds() is always
		// finite, so the error arm is dead but keeps the emit uniform.
		fmt.Fprintf(b, "if dst, err = encode.AppendFloat(dst, %s.Seconds(), 64); err != nil { return dst, err }\n", ref)
	case "milli":
		fmt.Fprintf(b, "dst = strconv.AppendInt(dst, %s.Milliseconds(), 10)\n", ref)
	case "micro":
		fmt.Fprintf(b, "dst = strconv.AppendInt(dst, %s.Microseconds(), 10)\n", ref)
	case "nano":
		fmt.Fprintf(b, "dst = strconv.AppendInt(dst, %s.Nanoseconds(), 10)\n", ref)
	case "units":
		fmt.Fprintf(b, "dst = append(dst, '\"')\ndst =%s(dst, %s.String())\n", appendStrFn(f.HTMLEscape), ref)
	default:
		// jsonv2 requires an explicit format for Duration; fall back to units string.
		fmt.Fprintf(b, "dst = %s(dst, %s.String())\n", appendStrFn(f.HTMLEscape), ref)
	}
}

// structHasAppendFormatTime reports whether any field of s emits via
// time.Time.AppendFormat (i.e. a non-numeric time format). Used by
// renderSize to reserve the 64-byte headroom Go's stdlib AppendFormat
// requires via its internal slices.Grow call.
func structHasAppendFormatTime(s StructInfo) bool {
	for _, f := range s.Fields {
		if f.Kind != KindTime {
			continue
		}
		_, numeric := timeLayoutExpr(f.Format)
		if numeric == "" {
			return true
		}
	}
	return false
}

// renderSize emits the body of a JSONSize method: sums the exact (or
// worst-case) byte count needed to serialize the struct as JSON. Per-field
// contributions split into a compile-time constant (folded into the
// initial `size := N`) and runtime code (loops, len(), recursive calls).
// Two passes over the field list — first to total the constant, then to
// emit runtime adds — would re-invoke sizeContrib redundantly, so we
// collect runtime additions into a sibling builder during the constant
// pass and flush them after the `size := N` line is written.
func renderSize(b *bytes.Buffer, s StructInfo) {
	fmt.Fprintf(b, "func (s %s) JSONSize() int {\n", s.Name)
	if s.IsAlias {
		b.WriteString(renderAliasSize(s))
		b.WriteString("}\n\n")
		return
	}
	// Fixed overhead: braces + per-field key bytes + separating commas.
	// omitempty/omitzero fields move their key+value contribution out
	// of the constant and into a runtime `if <emit> { size += ... }`
	// guard, so a zero-valued OmitStruct doesn't reserve room for
	// fields that won't ship.
	fixed := 2 // { and }
	// time.AppendFormat internally calls slices.Grow(b, max(layout, 64))
	// per invocation. Without 64-byte headroom at every call site the
	// runtime doubles the backing array — defeating the single-alloc
	// Marshal contract. Reserve one shared 64-byte tail at struct level
	// for any non-numeric time-format field; subsequent AppendFormat
	// calls in the same Marshal benefit from the same slack since their
	// actual content writes consume less than 64 bytes each.
	if structHasAppendFormatTime(s) {
		fixed += 64
	}
	named := 0
	var runtime bytes.Buffer
	for _, f := range s.Fields {
		if f.Inline {
			// Inline catch-all: name/colon/comma budgeted per-entry
			// in sizeMapContrib. No fixed key bytes here.
			ref := "s." + f.GoName
			_, code := sizeContrib(f, ref)
			runtime.WriteString(code)
			continue
		}
		ref := "s." + f.GoName
		emit := fieldSkipExpr(f, ref)
		// For pointer fields whose emit predicate is the nil check,
		// the outer guard already proves non-nil. Pass the
		// dereferenced inner to sizeContrib so it doesn't emit a
		// redundant `if ref == nil { 4 } else { ... }` inside the
		// `if ref != nil { ... }` we're already in.
		sizeField, sizeRef := f, ref
		if emit != "" && f.Pointer {
			sizeField.Pointer = false
			if f.PointeeType != "" {
				sizeField.GoType = f.PointeeType
			}
			sizeRef = "(*" + ref + ")"
		}
		n, code := sizeContrib(sizeField, sizeRef)
		if emit == "" {
			fixed += len(f.JSONName) + 3 // "name":
			if named > 0 {
				fixed++ // comma
			}
			named++
			fixed += n
			runtime.WriteString(code)
			continue
		}
		// Omit-eligible field: pessimistic worst-case includes a
		// leading comma (cheaper than threading "is this the first
		// emitted field" through the runtime guard).
		fmt.Fprintf(&runtime, "if %s {\nsize += %d\n", emit, len(f.JSONName)+4+n)
		runtime.WriteString(code)
		runtime.WriteString("}\n")
	}
	fmt.Fprintf(b, "size := %d\n", fixed)
	// b is *bytes.Buffer — WriteTo's err can't be non-nil here.
	_, _ = runtime.WriteTo(b)
	b.WriteString("return size\n}\n\n")
}

// appendStrFn returns the encode-pkg helper to call for emitting a JSON
// string body + closing `"`. Default is the raw, jsonv2-shaped variant
// that emits `<`, `>`, `&` literally; when the field's parent struct
// opts in via the `htmlescape` annotation / `-htmlescape` flag, codegen
// switches to the HTML-safe escaper that matches stdlib `encoding/json` v1.
//
// The CALLER must have written the opening `"` already — folded into a
// constant prefix at struct-field top level, or explicitly via
// `dst = append(dst, '"')` at slice/map/standalone sites.
func appendStrFn(htmlEscape bool) string {
	if htmlEscape {
		return "encode.AppendString"
	}
	return "encode.AppendStringNoHTML"
}

// emitNoCloseAfterComma emits the bytes-path strict-grammar guard inside an
// element loop's comma branch: a comma promises another element, so the
// container close (or EOF) right after it is invalid JSON — stdlib v1/v2
// parity. The plain sentinel return picks up its field wrap from the
// parse-error post-pass.
func emitNoCloseAfterComma(b *bytes.Buffer, posVar string, close byte) {
	sentinel := "scan.ErrBadArray"
	if close == '}' {
		sentinel = "scan.ErrBadObject"
	}
	fmt.Fprintf(b, "if %[1]s >= len(data) || data[%[1]s] == '%[2]c' { return result, i, %[3]s }\n", posVar, close, sentinel)
}

// streamNoCloseAfterComma is emitNoCloseAfterComma's stream twin. The
// `s.Pos >= len(...)` half also catches EOF right after the comma —
// SkipSpace returns nil at EOF with Pos == len(buf), and the element
// loop's top would index out of range (panic) without it.
func streamNoCloseAfterComma(field string, close byte) string {
	sentinel := "scan.ErrBadArray"
	if close == '}' {
		sentinel = "scan.ErrBadObject"
	}
	return fmt.Sprintf("if s.Pos >= len(s.Bytes()) || s.Bytes()[s.Pos] == '%c' { return result, decode.NewParseErr(%s, s.Pos, %s) }\n", close, field, sentinel)
}

// appendAnyFn mirrors appendStrFn for `any` values — htmlescape structs
// route their any-walk through the HTML-safe variant so nested strings
// escape consistently with sibling string fields.
func appendAnyFn(htmlEscape bool) string {
	if htmlEscape {
		return "encode.AppendAnyHTML"
	}
	return "encode.AppendAny"
}

// foldLeadingQuote checks whether the given field's value emit begins
// with a JSON `"` byte. If so, it returns the prefix with `"` appended
// and the value-emit code with the opening quote elided. Caller can
// emit `prefix + code` instead of `oldPrefix + standardValueEmit` to
// save one byte-append op per field.
func foldLeadingQuote(f FieldInfo, ref, prefix string) (newPrefix, code string, ok bool) {
	if f.Pointer {
		return prefix, "", false // pointer may emit "null"
	}
	switch f.Kind {
	case KindString:
		return prefix + `"`, fmt.Sprintf("dst = %s(dst, %s)\n", appendStrFn(f.HTMLEscape), ref), true
	case KindNetIP, KindNetipAddr, KindNetipPrefix:
		return prefix + `"`, fmt.Sprintf(`if dst, err = %s.AppendText(dst); err != nil { return dst, err }
dst = append(dst, '"')
`, ref), true
	case KindBytes:
		// No fold: a nil []byte emits `null` (no opening quote).
	case KindURL:
		// encode.AppendURL replicates url.URL.String semantics with
		// byte-append — zero alloc (the stdlib AppendBinary internally
		// calls String, which builds a strings.Builder buffer).
		// URL output never contains `"` or `\` (both percent-encoded),
		// so safe to drop between JSON quotes without escaping.
		return prefix + `"`, fmt.Sprintf("dst = encode.AppendURL(dst, %s)\ndst = append(dst, '\"')\n", ref), true
	case KindBigRat:
		return prefix + `"`, fmt.Sprintf("if dst, err = (&%s).AppendText(dst); err != nil { return dst, err }\ndst = append(dst, '\"')\n", ref), true
	case KindBigFloat:
		return prefix + `"`, fmt.Sprintf("dst = (&%s).Append(dst, 'g', -1)\ndst = append(dst, '\"')\n", ref), true
	}
	return prefix, "", false
}

// Worst-case byte budgets for primitive encodings.
const (
	sizeBool    = 5  // "false"
	sizeInt     = 20 // "-9223372036854775808"
	sizeUint    = 20 // "18446744073709551615"
	sizeFloat   = 25 // IEEE-754 shortest round-trip, 'f' form: sign + "0." + 5 zeros + 17 digits
	sizeStrMult = 2  // 2× covers short escapes (\n, \", \\, …). Control
	// chars expand to \uXXXX (6×) but are rejected by the decoder (RFC 8259),
	// so they can't survive a round-trip — the 2× bound is tight for legal
	// JSON. Marshal of non-RFC-compliant user input still overshoots but
	// users get the one-time realloc only on pathological input.
	sizeStrMultHTML = 6 // htmlescape opt-in expands <, >, & to \uXXXX (6×).
	sizeStrPad      = 2 // surrounding quotes
)

// strMult returns the per-byte string size multiplier for the given
// HTML-escape mode. Used by every site that needs a string size budget
// (top-level field, slice/array element, map value, etc.).
func strMult(htmlEscape bool) int {
	if htmlEscape {
		return sizeStrMultHTML
	}
	return sizeStrMult
}

// sizeContrib returns (constN, runtimeCode) — the constant byte count
// known at codegen time, and the runtime statements that compute the
// variable contribution. constN is folded into the initial `size := N`
// at the top level; runtimeCode is emitted as-is.
func sizeContrib(f FieldInfo, ref string) (int, string) {
	if f.Pointer {
		// A nil at any level of the chain budgets `null` (4 bytes); only a
		// fully-allocated chain reaches the leaf. Emit one flat `else if`
		// ladder (one rung per pointer level) rather than nesting, so a
		// `***T` reads as a chain of guards, not a staircase.
		depth, leafType := pointerDepth(f.GoType)
		leaf := f
		leaf.Pointer = false
		leaf.PointeeType = ""
		leaf.GoType = leafType
		leaf.Kind = resolveKind(leafType)
		leafN, leafCode := sizeContrib(leaf, derefStr(ref, depth))
		b := getSmall()
		defer putSmall(b)
		for k := range depth {
			kw := "if"
			if k > 0 {
				kw = " else if"
			}
			fmt.Fprintf(b, "%s %s == nil { size += 4 }", kw, derefStr(ref, k))
		}
		b.WriteString(" else {\n")
		if leafN > 0 {
			fmt.Fprintf(b, "size += %d\n", leafN)
		}
		b.WriteString(leafCode)
		b.WriteString("}\n")
		return 0, b.String()
	}
	// json:",string" wraps the value in two quote bytes the inner Kind
	// budget doesn't account for. Add them here so every numeric width
	// gets the right upper bound regardless of which Kind branch below
	// runs. KindBool is excluded: jsonv2 emits bare bool even with
	// `,string`, and ggen follows.
	if f.String {
		switch f.Kind {
		case KindInt, KindInt8, KindInt16, KindInt32, KindInt64,
			KindUint, KindUint8, KindUint16, KindUint32, KindUint64,
			KindFloat32, KindFloat64:
			n, code := sizeContribKind(f, ref)
			return n + 2, code
		}
	}
	return sizeContribKind(f, ref)
}

func sizeContribKind(f FieldInfo, ref string) (int, string) {
	switch f.Kind {
	case KindString:
		return sizeStrPad, fmt.Sprintf("size += len(%s)*%d\n", ref, strMult(f.HTMLEscape))
	case KindBool:
		return sizeBool, ""
	case KindInt, KindInt8, KindInt16, KindInt32, KindInt64:
		return sizeInt, ""
	case KindUint, KindUint8, KindUint16, KindUint32, KindUint64:
		return sizeUint, ""
	case KindFloat32, KindFloat64:
		return sizeFloat, ""
	case KindStruct:
		if isGenerated(f.GoType) || f.Iface.JSONSize {
			return 0, fmt.Sprintf("size += %s.JSONSize()\n", ref)
		}
		return 128, ""
	case KindSlice, KindArray:
		return sizeSliceContrib(f, ref, 0)
	case KindMap:
		return sizeMapContrib(f, ref)
	case KindBytes:
		// The 4-byte const covers the brackets/quotes AND the nil-as-null
		// case (nil []byte marshals as `null`).
		switch f.Format {
		case "array":
			// JSON array of numbers: each byte → up to 3 digits + comma,
			// minus 1 for missing trailing comma. Upper-bound with *4.
			return 4, fmt.Sprintf("size += len(%s)*4\n", ref)
		case "base16", "hex":
			// Exactly 2× input.
			return 4, fmt.Sprintf("size += len(%s)*2\n", ref)
		case "base32", "base32hex":
			// 8/5 of input rounded up to a block of 8. ((n+4)/5)*8.
			return 4, fmt.Sprintf("size += ((len(%s)+4)/5)*8\n", ref)
		}
		// base64 (default) / base64url: ((n+2)/3)*4.
		return 4, fmt.Sprintf("size += ((len(%s)+2)/3)*4\n", ref)
	case KindTime:
		return timeFormatSize(f.Format), ""
	case KindDuration:
		return durationFormatSize(f.Format), ""
	case KindNetIP:
		// net.IP is []byte, but ParseIP returns 16 bytes even for IPv4,
		// so a raw `len(ip)==4` check is dead code. Use To4() — returns
		// non-nil only when the address actually fits in 4 octets.
		return 2, fmt.Sprintf("if %s.To4() != nil { size += 15 } else if len(%s) != 0 { size += 39 } else { size += 2 }\n", ref, ref)
	case KindNetipAddr:
		// netip.Addr: Is4() splits v4 vs v6 budget.
		return 2, fmt.Sprintf("if %s.Is4() { size += 15 } else { size += 39 }\n", ref)
	case KindNetipPrefix:
		// netip.Prefix is Addr + /N: +4 for "/128" worst case.
		return 2, fmt.Sprintf("if %s.Addr().Is4() { size += 19 } else { size += 43 }\n", ref)
	case KindRawJSON:
		return 0, fmt.Sprintf("if n := len(%s); n > 0 { size += n } else { size += 4 }\n", ref)
	case KindURL:
		// Sum the components instead of reserving a flat 256. The +8
		// const covers `"` + `://` + `?` + `#` + closing `"`. Path and
		// Fragment are stored decoded; String() re-percent-encodes
		// non-ASCII bytes (3 chars per byte worst case) so we multiply
		// by 3. Host and RawQuery emit as-is. User info reads
		// Username/Password directly (no alloc) and multiplies by 3
		// for percent-escape worst case.
		return 8, fmt.Sprintf("size += len(%s.Scheme) + len(%s.Host)*3 + len(%s.Path)*3 + len(%s.RawQuery) + len(%s.Fragment)*3 + len(%s.Opaque)\nif %s.User != nil { pw, _ := %s.User.Password(); size += (len(%s.User.Username()) + len(pw))*3 + 2 }\n",
			ref, ref, ref, ref, ref, ref, ref, ref, ref)
	case KindBigInt:
		// log10(2^bits) ≈ bits * 0.302. Add sign + safety. BitLen is cheap.
		return 4, fmt.Sprintf("size += %s.BitLen()/3\n", ref)
	case KindBigFloat:
		// Mantissa + exponent representation + surrounding quotes;
		// precision-derived bound.
		return 66, ""
	case KindBigRat:
		// Two big.Ints + slash + quotes. Approximate by num+denom bit lengths.
		return 8, fmt.Sprintf("size += (%s.Num().BitLen() + %s.Denom().BitLen())/3\n", ref, ref)
	case KindSQLNull:
		spec, ok := SQLNullSpec(f.GoType)
		if !ok {
			return 0, ""
		}
		innerField := FieldInfo{Kind: spec.Inner, GoType: spec.Type, Format: f.Format}
		innerN, code := sizeContrib(innerField, ref+"."+spec.Field)
		// !Valid emits the literal "null" (4 bytes). Inner kinds whose
		// empty/zero-value budget is <4 (notably KindString = 2 for the
		// surrounding quotes) under-reserve unless we widen here.
		return max(innerN, 4), code
	case KindAny:
		// Conservative — no introspection at codegen time. 256 covers most
		// scalar/object payloads; deeply nested any[] with many keys can
		// overshoot, but JSONSize is upper-bound by design.
		return 256, ""
	}
	return 0, ""
}

// sizeSliceContrib emits the size contribution for a slice/array field.
// The 2-byte brackets are returned as a constant for the caller to fold;
// per-element accounting goes into the runtime code. Nested slices recurse
// with a depth-suffixed loop variable to avoid name collisions.
func sizeSliceContrib(f FieldInfo, ref string, depth int) (int, string) {
	ivar := fmt.Sprintf("i%d", depth)
	b := getSmall()
	defer putSmall(b)
	fmt.Fprintf(b, "if n := len(%s); n > 0 { size += n - 1 }\n", ref)
	switch {
	case f.ElemPointer:
		// Pointer element (any depth): nil at any level budgets `null`
		// (4 bytes); a full chain budgets the deref'd leaf. sizeContrib's
		// Pointer ladder emits both.
		leafN, leafCode := sizeContrib(elemPtrField(f, f.JSONName+"[]"), fmt.Sprintf("%s[%s]", ref, ivar))
		fmt.Fprintf(b, "for %s := range %s {\n", ivar, ref)
		if leafN > 0 {
			fmt.Fprintf(b, "size += %d\n", leafN)
		}
		b.WriteString(leafCode)
		b.WriteString("}\n")
	case f.ElemKind == KindString:
		fmt.Fprintf(b, "for %s := range %s { size += len(%s[%s])*%d + %d }\n",
			ivar, ref, ref, ivar, strMult(f.HTMLEscape), sizeStrPad)
	case f.ElemKind == KindBool:
		fmt.Fprintf(b, "size += len(%s) * %d\n", ref, sizeBool)
	case f.ElemKind == KindInt, f.ElemKind == KindInt64, f.ElemKind == KindInt8, f.ElemKind == KindInt16, f.ElemKind == KindInt32:
		fmt.Fprintf(b, "size += len(%s) * %d\n", ref, sizeInt)
	case f.ElemKind == KindUint, f.ElemKind == KindUint64, f.ElemKind == KindUint8, f.ElemKind == KindUint16, f.ElemKind == KindUint32:
		fmt.Fprintf(b, "size += len(%s) * %d\n", ref, sizeUint)
	case f.ElemKind == KindFloat32, f.ElemKind == KindFloat64:
		fmt.Fprintf(b, "size += len(%s) * %d\n", ref, sizeFloat)
	case f.ElemKind == KindStruct:
		if isGenerated(f.ElemType) || f.ElemIface.JSONSize {
			fmt.Fprintf(b, "for %s := range %s { size += %s[%s].JSONSize() }\n",
				ivar, ref, ref, ivar)
		} else {
			fmt.Fprintf(b, "size += len(%s) * 128\n", ref)
		}
	case f.ElemKind == KindSlice, f.ElemKind == KindArray:
		fmt.Fprintf(b, "for %s := range %s {\n", ivar, ref)
		innerN, innerCode := sizeSliceContrib(peelSliceField(f), fmt.Sprintf("%s[%s]", ref, ivar), depth+1)
		if innerN > 0 {
			fmt.Fprintf(b, "size += %d\n", innerN)
		}
		b.WriteString(innerCode)
		b.WriteString("}\n")
	}
	// Slices can be nil → emitted as "null" (4 bytes) instead of `[]`
	// (2 bytes); the budget reserves the wider of the two so the !nil
	// path and the nil-as-null path both fit. Arrays can't be nil so
	// they keep the bracket-only 2-byte budget.
	if f.Kind == KindArray {
		return 2, b.String()
	}
	return 4, b.String()
}

// sizeMapContrib emits the size contribution for a `map[string]V` field.
// Per-entry overhead is `"k":v,` = 4 fixed bytes (one extra comma overcounted
// on the last entry — kept for simplicity, still upper bound), plus 2*len(k)
// for the key (escape worst case), plus a kind-derived value budget. The
// 2-byte braces are returned as a constant for the caller to fold.
func sizeMapContrib(f FieldInfo, ref string) (int, string) {
	b := getSmall()
	defer putSmall(b)
	const perEntryFixed = 4

	mult := strMult(f.HTMLEscape)
	// Try to lift the value contribution out of the loop when it's a
	// constant per-entry size — saves one map iteration over keys-only.
	_, eDepth := elemPtrType(f)
	if v, ok := constSizePerEntry(f.ElemKind, f.Format); ok && eDepth == 0 {
		fmt.Fprintf(b, "size += len(%s) * %d\n", ref, perEntryFixed+v)
		fmt.Fprintf(b, "for k := range %s { size += len(k) * %d }\n", ref, mult)
		// nil-map → "null" (4) is wider than `{}` (2); reserve max.
		return 4, b.String()
	}

	if eDepth > 0 {
		// Pointer value (any depth): sizeContrib's Pointer ladder budgets
		// `null` per nil level and the deref'd leaf otherwise.
		leafN, leafCode := sizeContrib(elemPtrField(f, f.JSONName+".value"), "v")
		fmt.Fprintf(b, "size += len(%s) * %d\n", ref, perEntryFixed)
		fmt.Fprintf(b, "for k, v := range %s {\n", ref)
		fmt.Fprintf(b, "size += len(k) * %d\n", mult)
		if leafN > 0 {
			fmt.Fprintf(b, "size += %d\n", leafN)
		}
		b.WriteString(leafCode)
		b.WriteString("}\n")
		return 4, b.String()
	}

	// Unknown / composite value kinds (nested slice/map, KindBytes,
	// non-generated structs, …) never read `v` in their flat fallback —
	// emit a keys-only loop so the generated code compiles (`v` would be
	// declared and unused).
	usesV := false
	switch f.ElemKind {
	case KindString, KindBigInt, KindBigRat,
		KindNetIP, KindNetipAddr, KindNetipPrefix, KindURL:
		usesV = true
	case KindStruct:
		usesV = isGenerated(f.ElemType) || f.ElemIface.JSONSize
	}
	if !usesV {
		fmt.Fprintf(b, "size += len(%s) * %d\n", ref, perEntryFixed+128)
		fmt.Fprintf(b, "for k := range %s { size += len(k) * %d }\n", ref, mult)
		return 4, b.String()
	}

	// Variable per-entry: one combined loop over k,v.
	fmt.Fprintf(b, "size += len(%s) * %d\n", ref, perEntryFixed)
	fmt.Fprintf(b, "for k, v := range %s {\n", ref)
	fmt.Fprintf(b, "size += len(k) * %d\n", mult)
	switch f.ElemKind {
	case KindString:
		fmt.Fprintf(b, "size += len(v)*%d + %d\n", mult, sizeStrPad)
	case KindStruct:
		if isGenerated(f.ElemType) || f.ElemIface.JSONSize {
			b.WriteString("size += v.JSONSize()\n")
		} else {
			b.WriteString("size += 128\n")
		}
	case KindBigInt:
		b.WriteString("size += v.BitLen()/3 + 4\n")
	case KindBigRat:
		b.WriteString("size += (v.Num().BitLen() + v.Denom().BitLen())/3 + 8\n")
	case KindNetIP:
		b.WriteString("if v.To4() != nil { size += 17 } else if len(v) != 0 { size += 41 } else { size += 4 }\n")
	case KindNetipAddr:
		b.WriteString("if v.Is4() { size += 17 } else { size += 41 }\n")
	case KindNetipPrefix:
		b.WriteString("if v.Addr().Is4() { size += 21 } else { size += 45 }\n")
	case KindURL:
		b.WriteString("size += len(v.Scheme) + len(v.Host)*3 + len(v.Path)*3 + len(v.RawQuery) + len(v.Fragment)*3 + len(v.Opaque) + 8\n")
		b.WriteString("if v.User != nil { pw, _ := v.User.Password(); size += (len(v.User.Username()) + len(pw))*3 + 2 }\n")
	default:
		// Anything else (nested slice/map, KindAny, …) falls back to the
		// legacy flat estimate. Refining further is doable but rarely worth
		// it — these compositions are uncommon as direct map values.
		b.WriteString("size += 128\n")
	}
	b.WriteString("}\n")
	// nil-map → "null" (4); same reservation as the constSize-per-entry arm.
	return 4, b.String()
}

// constSizePerEntry reports whether a value of the given kind has a
// known fixed upper-bound size, and returns that size. Used to lift the
// value contribution out of the per-entry loop in renderSizeMap.
// `format` is honored for KindTime / KindDuration so e.g. a
// `map[string]time.Time` with `format:Kitchen` reserves ~9 bytes per
// entry instead of the RFC3339Nano-sized 37.
func constSizePerEntry(kind TypeKind, format string) (int, bool) {
	switch kind {
	case KindBool:
		return sizeBool, true
	case KindInt, KindInt8, KindInt16, KindInt32, KindInt64:
		return sizeInt, true
	case KindUint, KindUint8, KindUint16, KindUint32, KindUint64:
		return sizeUint, true
	case KindFloat32, KindFloat64:
		return sizeFloat, true
	case KindTime:
		return timeFormatSize(format), true
	case KindDuration:
		return durationFormatSize(format), true
	case KindBigFloat:
		return 66, true // +2 for surrounding quotes
	case KindAny:
		return 64, true
	}
	return 0, false
}

func renderAppendSlice(b *bytes.Buffer, f FieldInfo, ref string) {
	emitAppendSlice(b, f, ref, 0)
}

// emitAppendSlice is the recursive marshal counterpart to emitByteSliceRead.
// Nested slices peel one [] off per level; loop vars carry a depth suffix
// (i0, v0 at the outermost, i1, v1 one level in, …) to avoid collisions.
//
// nil-slice handling: a nil slice serializes as JSON `null` to match stdlib
// `encoding/json` v1/v2. Empty non-nil slice still serializes as `[]`.
// Fixed-length arrays can't be nil so they skip the check.
func emitAppendSlice(b *bytes.Buffer, f FieldInfo, ref string, depth int) {
	vvar := fmt.Sprintf("v%d", depth)
	if f.Kind == KindSlice {
		fmt.Fprintf(b, "if %s == nil {\ndst = append(dst, \"null\"...)\n} else {\n", ref)
	}
	fmt.Fprintf(b, "dst = append(dst, '[')\nif len(%s) > 0 {\n", ref)
	// First element: no leading comma. Refer to it directly as `ref[0]`
	// to keep the emit primitive — saves declaring the loop var twice.
	emitSliceElement(b, f, fmt.Sprintf("%s[0]", ref), depth)
	// Rest: comma first, then element. Iterating over `ref[1:]` lifts the
	// `if i > 0` branch out of every iteration.
	fmt.Fprintf(b, "for _, %s := range %s[1:] {\ndst = append(dst, ',')\n", vvar, ref)
	emitSliceElement(b, f, vvar, depth)
	b.WriteString("}\n}\ndst = append(dst, ']')\n")
	if f.Kind == KindSlice {
		b.WriteString("}\n")
	}
}

// emitSliceElement emits the marshal code for one slice element at the
// given source expression. Shared between the first-element and loop-body
// emits in emitAppendSlice so the per-iteration `if i > 0` check is gone.
func emitSliceElement(b *bytes.Buffer, f FieldInfo, vref string, depth int) {
	if f.ElemPointer {
		// nil at any pointer level → null; only a fully-allocated chain
		// reaches the leaf. One flat `else if` ladder, one rung per level
		// (depth-1 `[]*T` degenerates to the plain nil-check), then recurse
		// on the fully-deref'd leaf with the pointer levels cleared.
		_, ptrDepth := elemPtrType(f)
		for k := 0; k < ptrDepth; k++ {
			kw := "if"
			if k > 0 {
				kw = "} else if"
			}
			fmt.Fprintf(b, "%s %s == nil {\ndst = append(dst, \"null\"...)\n", kw, derefStr(vref, k))
		}
		b.WriteString("} else {\n")
		nf := f
		nf.ElemPointer = false
		_, nf.ElemType = pointerDepth(f.ElemType)
		nf.ElemKind = resolveKind(nf.ElemType)
		if nf.ElemKind == KindArray {
			nf.ElemArrayLen = arrayLenFromType(nf.ElemType)
		}
		emitSliceElement(b, nf, derefStr(vref, ptrDepth), depth)
		b.WriteString("}\n")
		return
	}
	switch f.ElemKind {
	case KindString:
		// Split into two lines so the coalescer pass can fold the `'"'`
		// with whatever const append precedes (e.g. the slice's leading
		// `,` becomes `","...`).
		fmt.Fprintf(b, "dst = append(dst, '\"')\ndst = %s(dst, %s)\n", appendStrFn(f.HTMLEscape), vref)
	case KindBool:
		fmt.Fprintf(b, "dst = strconv.AppendBool(dst, %s)\n", vref)
	case KindInt, KindInt8, KindInt16, KindInt32:
		fmt.Fprintf(b, "dst = strconv.AppendInt(dst, int64(%s), 10)\n", vref)
	case KindInt64:
		fmt.Fprintf(b, "dst = strconv.AppendInt(dst, %s, 10)\n", vref)
	case KindUint, KindUint8, KindUint16, KindUint32:
		fmt.Fprintf(b, "dst = strconv.AppendUint(dst, uint64(%s), 10)\n", vref)
	case KindUint64:
		fmt.Fprintf(b, "dst = strconv.AppendUint(dst, %s, 10)\n", vref)
	case KindFloat32:
		fmt.Fprintf(b, "if dst, err = encode.AppendFloat(dst, float64(%s), 32); err != nil { return dst, err }\n", vref)
	case KindFloat64:
		fmt.Fprintf(b, "if dst, err = encode.AppendFloat(dst, %s, 64); err != nil { return dst, err }\n", vref)
	case KindStruct:
		if isGenerated(f.ElemType) {
			fmt.Fprintf(b, "if dst, err = %s.AppendJSON(dst); err != nil { return dst, err }\n", vref)
		} else {
			fmt.Fprintf(b, `{
	bs, err := json.Marshal(%s)
	if err != nil { return dst, err }
	dst = append(dst, bs...)
}
`, vref)
		}
	case KindSlice, KindArray:
		emitAppendSlice(b, peelSliceField(f), vref, depth+1)
	}
}

// renderAppendMap emits marshal code for a map[string]V field. Iteration
// order is Go's randomized map order — deterministic roundtrip via
// unmarshal, but wire output is not stable.
//
// nil map → null (matches stdlib). Empty non-nil → {}. No block scope:
// the first-entry flag is suffixed with the field name so adjacent maps
// in the same function don't collide.
func renderAppendMap(b *bytes.Buffer, f FieldInfo, ref string) {
	appendStr := appendStrFn(f.HTMLEscape)
	first := "first" + strings.ReplaceAll(f.GoName, ".", "")
	fmt.Fprintf(b, `if %[1]s == nil {
dst = append(dst, "null"...)
} else {
dst = append(dst, '{')
%[3]s := true
for k, v := range %[1]s {
if %[3]s { %[3]s = false
dst =append(dst, '"') } else { dst = append(dst, ",\""...) }
dst = %[2]s(dst, k)
dst = append(dst, ':')
`, ref, appendStr, first)
	if _, eDepth := elemPtrType(f); eDepth > 0 {
		// Pointer value (any depth): nil at any level → null, full chain →
		// leaf emit. renderAppendValue's Pointer ladder handles both.
		renderAppendValue(b, elemPtrField(f, f.JSONName+".value"), "v")
		b.WriteString("}\ndst = append(dst, '}')\n}\n")
		return
	}
	switch f.ElemKind {
	case KindString:
		// Two separate append lines so coalesce sees the `'"'` and merges
		// it with the preceding `':'` into `":\""...`.
		fmt.Fprintf(b, "dst = append(dst, '\"')\ndst = %s(dst, v)\n", appendStr)
	case KindBool:
		b.WriteString("dst = strconv.AppendBool(dst, v)\n")
	case KindInt:
		b.WriteString("dst = strconv.AppendInt(dst, int64(v), 10)\n")
	case KindInt64:
		b.WriteString("dst = strconv.AppendInt(dst, v, 10)\n")
	case KindUint64:
		b.WriteString("dst = strconv.AppendUint(dst, v, 10)\n")
	case KindFloat64:
		b.WriteString("if dst, err = encode.AppendFloat(dst, v, 64); err != nil { return dst, err }\n")
	case KindStruct:
		if isGenerated(f.ElemType) {
			b.WriteString("if dst, err = v.AppendJSON(dst); err != nil { return dst, err }\n")
		} else {
			// Loop-scoped — no wrapper needed (unlike the slice elem
			// fallback, which is duplicated at outer scope by the
			// first-element-then-rest pattern).
			b.WriteString(`bs, err := json.Marshal(v)
if err != nil { return dst, err }
dst = append(dst, bs...)
`)
		}
	case KindAny:
		fmt.Fprintf(b, "if dst, err = %s(dst, v); err != nil { return dst, err }\n", appendAnyFn(f.HTMLEscape))
	}
	b.WriteString("}\ndst = append(dst, '}')\n}\n")
}

// defaultPreallocCap is the small constant cap applied to slices /
// maps when no explicit sizing hint is present. Sized to absorb most
// real-world short collections without triggering the 1→2→4→...
// growth chain that leaves orphan backings inflating retained heap.
const defaultPreallocCap = 4

// userPreallocHint extracts an explicit user-provided sizing hint
// from the hintlen / len / minlen ladder. Returns -1 when no hint
// is set, so callers can distinguish "user said 0" (opt-out via
// hintlen=0) from "user said nothing" (fall through to caller's
// kind-based default).
//
// Precedence:
//  1. `hintlen=N`:
//     N >  0 → that many entries
//     N == 0 → user opt-out, force zero (overrides len/minlen)
//     N <  0 → sentinel "unset" — fall through
//  2. `len=N`    — exact count, no waste
//  3. `minlen=N` — floor; growth still works above
//
// `maxlen` is intentionally NOT used — see "tried and rejected"
// in CLAUDE.md. Pre-sizing to the worst-case bound retains
// over-allocated capacity per held value (~100 KB/item on Mega).
func userPreallocHint(f FieldInfo) int {
	if f.HintLen >= 0 {
		return f.HintLen
	}
	if v, ok := f.HasRule("len"); ok {
		if n, err := strconv.Atoi(v); err == nil && n > 0 {
			return n
		}
	}
	if v, ok := f.HasRule("minlen"); ok {
		if n, err := strconv.Atoi(v); err == nil && n > 0 {
			return n
		}
	}
	return -1
}

// mapPreallocCap returns the cap for `make(map[K]V, cap)` from the
// user's sizing hints. Returns 0 when no hint is set — maps don't
// get a kind-based default because Go's `makemap` lazy-allocates
// for hints < 8 (so small defaults are wasted) and the per-bucket
// over-allocation cost is too high to justify a higher default for
// the typical "small or empty map" case. Users with predictable
// sizes can opt in via `ggen:"hintlen=N"`.
func mapPreallocCap(f FieldInfo) int {
	if n := userPreallocHint(f); n >= 0 {
		return n
	}
	return 0
}

// preallocCap returns the initial capacities for a slice field's
// two backing allocations:
//   - slice: cap for `make([]E, 0, slice)` — the field's own slice.
//     Returns 0 to mean "do not emit a make() prealloc". The empty-
//     array branch always emits `[]E{}` regardless (stdlib parity).
//   - slab: cap for `make([]T, 0, slab)` when `f.ElemPointer` is
//     set — the contiguous backing storage for `[]*T` element
//     pointers. Caller ignores when ElemPointer is false.
//
// Precedence — explicit hints win and apply to both caps equally:
//  1. `hintlen=N` (N >= 0)
//  2. `len=N`
//  3. `minlen=N`
//
// With no explicit hint, the kind drives the default:
//   - pointer-element (`[]*T`): both default to defaultPreallocCap.
//     Slice slot waste is 8 B/slot (trivial); slab default avoids
//     the orphan-trail growth chain (0→1→2→4→8 leaves prior backings
//     alive via held `*T` pointers).
//   - heavy non-pointer (struct/slice/map/array): both 0. Over-cap
//     × element-size would explode retained heap.
//   - primitive: slice = defaultPreallocCap (clamped by maxlen if
//     smaller); slab = 0 (unused — primitives have no slab).
//
// `maxlen` is intentionally NOT used as a generous prealloc hint —
// it's an upper bound, not an expected size, and treating it as one
// was the residency villain. See "tried and rejected" in CLAUDE.md.
func preallocCap(f FieldInfo) (slice, slab int) {
	if n := userPreallocHint(f); n >= 0 {
		return n, n
	}
	switch f.ElemKind {
	case KindSlice, KindMap:
		// Element is a slice header (24 B) or map handle (8 B) — both
		// bounded slot sizes. Safe to prealloc: over-cap waste per
		// unused slot is small (cap=4 → ≤96 B waste), and starting
		// from cap=0 forces the 0→1→2→4→8 grow chain whose orphan
		// trail dwarfs the over-cap waste.
		return defaultPreallocCap, 0
	case KindStruct, KindArray:
		if f.ElemPointer {
			// `[]*T` — slice slot is 8 B, slab slot is sizeof(T).
			// Slab default avoids the orphan-trail growth chain
			// (held `*T` pointers anchor into prior backings).
			return defaultPreallocCap, defaultPreallocCap
		}
		// `[]T` value-stored — sizeof(T) could be anything. Prealloc
		// × element-size would explode retained heap on big structs.
		// Start nil, grow via append.
		return 0, 0
	}
	def := defaultPreallocCap
	if v, ok := f.HasRule("maxlen"); ok {
		if n, err := strconv.Atoi(v); err == nil && n >= 0 && n < def {
			def = n
		}
	}
	return def, 0
}

// inlineSkipWS emits an inline whitespace-skipping loop that mutates posVar
// directly. Avoids the function-call overhead of scan.SkipSpace, which shows
// up heavily in profiles (>5× hits per field) once other work is tight.
// fieldLit returns the JSON name of f as a Go string literal — used as
// the `field` argument to inline scanners / renderers that embed it into
// decode.NewParseErr at every error-return site.
func fieldLit(f FieldInfo) string { return strconv.Quote(f.JSONName) }

func inlineSkipWS(b *bytes.Buffer, posVar string) {
	// `data[i] <= ' '` gates the 4-way whitespace test: on compact JSON the
	// loop never runs and the dominant non-whitespace byte exits on a single
	// compare (gc lowers `<= ' '` to one CMPB+JHI, flags reused by the `== ' '`
	// branch). Boolean-identical accept set — every whitespace char is <= ' '.
	fmt.Fprintf(b,
		"for %s < len(data) && data[%s] <= ' ' && (data[%s] == ' ' || data[%s] == '\\t' || data[%s] == '\\n' || data[%s] == '\\r') { %s++ }\n",
		posVar, posVar, posVar, posVar, posVar, posVar, posVar)
}

// inlineNullPeek emits an inline `null` literal check on posVar. On a match,
// posVar is advanced 4 bytes inside the `if` body — no `np` / `ok` locals.
// Leaves the body open; caller appends its null-branch statements then the
// `} else {` for the non-null branch (or just `}` if no else is needed).
func inlineNullPeek(b *bytes.Buffer, posVar string) {
	fmt.Fprintf(b,
		"if %s+4 <= len(data) && data[%s] == 'n' && data[%s+1] == 'u' && data[%s+2] == 'l' && data[%s+3] == 'l' {\n%s += 4\n",
		posVar, posVar, posVar, posVar, posVar, posVar)
}

// zeroLit returns a Go expression for the zero value of an elem type, used
// as the pre-grow placeholder when slice-appending before in-place decode.
// Slice/map element kinds use plain `nil` — the recursive emit overwrites
// the slot before any other code observes it, so allocating an empty
// composite literal `[][]string{}` is wasted. Primitives can't use `T{}`
// composite-literal syntax; arrays/structs need it.
func zeroLit(elemType string, kind TypeKind) string {
	switch kind {
	case KindString:
		return `""`
	case KindBool:
		return "false"
	case KindInt, KindInt8, KindInt16, KindInt32, KindInt64,
		KindUint, KindUint8, KindUint16, KindUint32, KindUint64,
		KindFloat32, KindFloat64:
		return "0"
	case KindSlice, KindMap:
		return "nil"
	default:
		return elemType + "{}"
	}
}

// inlineScanInt64 emits an inline signed-int scanner that assigns into dst
// (via castFn if non-empty, e.g. "int") and advances posVar. Avoids the
// scan.Int64 call for the hot int fields. Accumulates as uint64 with
// per-digit overflow detection so out-of-range inputs surface
// scan.ErrNumberOverflow instead of silently wrapping. field is the Go
// expression embedded as the JSON path in decode.NewParseErr — a quoted
// literal like `"name"` for field-level callers, `""` for boundaries,
// or a runtime expression like `key` / `strings.Clone(key)` / `ownKey`
// for unknown-key handlers.
func inlineScanInt64(b *bytes.Buffer, posVar, dst, castFn, field string) {
	assign := ""
	switch {
	case castFn != "":
		assign = dst + " = " + castFn + "(n)"
	case dst != "n":
		assign = dst + " = n"
	}
	inlineScanInt64Stmt(b, posVar, field, assign)
}

// inlineScanInt64Stmt emits the inline signed-int scan, then `stmt` as the
// trailing statement with the parsed value available in `n` (int64). Callers
// that want to consume `n` directly — e.g. a pointer assign cascade with no
// intermediate temp — pass the consuming statement here.
// Brace-less: `neg`/`limit`/`u`/`n` land in the caller's scope — one numeric
// scan per scope everywhere (case body, elem loop, map loop, sqlnull else).
func inlineScanInt64Stmt(b *bytes.Buffer, posVar, field, stmt string) {
	fmt.Fprintf(b, `neg := false
if %[1]s < len(data) && data[%[1]s] == '-' { neg = true; %[1]s++ }
if %[1]s >= len(data) || data[%[1]s] < '0' || data[%[1]s] > '9' { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrBadNumber) }
limit := uint64(math.MaxInt64)
if neg { limit = scan.SignedNeg }
var u uint64
de := %[1]s + 18
if de > len(data) { de = len(data) }
for %[1]s < de && data[%[1]s] >= '0' && data[%[1]s] <= '9' {
	u = u*10 + uint64(data[%[1]s]-'0')
	%[1]s++
}
for %[1]s < len(data) && data[%[1]s] >= '0' && data[%[1]s] <= '9' {
	d := uint64(data[%[1]s]-'0')
	if u > limit/10 || (u == limit/10 && d > limit%%10) {
		return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrNumberOverflow)
	}
	u = u*10 + d
	%[1]s++
}
if %[1]s < len(data) {
	c := data[%[1]s]
	if c == '.' || c == 'e' || c == 'E' { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrBadNumber) }
}
var n int64
if neg {
	if u == scan.SignedNeg { n = math.MinInt64 } else { n = -int64(u) }
} else {
	n = int64(u)
}
%[3]s
`, posVar, field, stmt)
}

// inlineScanUint64 is the unsigned counterpart of inlineScanInt64.
// Accumulates with overflow detection so digits past MaxUint64 surface
// scan.ErrNumberOverflow. See inlineScanInt64 for `field` semantics.
func inlineScanUint64(b *bytes.Buffer, posVar, dst, castFn, field string) {
	assign := ""
	switch {
	case castFn != "":
		assign = dst + " = " + castFn + "(n)"
	case dst != "n":
		assign = dst + " = n"
	}
	inlineScanUint64Stmt(b, posVar, field, assign)
}

// inlineScanUint64Stmt is the unsigned counterpart of inlineScanInt64Stmt:
// the parsed value lands in `n` (uint64) before `stmt` runs. Brace-less —
// see inlineScanInt64Stmt.
func inlineScanUint64Stmt(b *bytes.Buffer, posVar, field, stmt string) {
	fmt.Fprintf(b, `if %[1]s >= len(data) || data[%[1]s] < '0' || data[%[1]s] > '9' { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrBadNumber) }
var n uint64
de := %[1]s + 19
if de > len(data) { de = len(data) }
for %[1]s < de && data[%[1]s] >= '0' && data[%[1]s] <= '9' {
	n = n*10 + uint64(data[%[1]s]-'0')
	%[1]s++
}
for %[1]s < len(data) && data[%[1]s] >= '0' && data[%[1]s] <= '9' {
	d := uint64(data[%[1]s]-'0')
	if n > scan.Uint64Limit/10 || (n == scan.Uint64Limit/10 && d > scan.Uint64Limit%%10) {
		return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrNumberOverflow)
	}
	n = n*10 + d
	%[1]s++
}
%[3]s
`, posVar, field, stmt)
}

// inlineScanString emits a zero-copy string reader that assigns into dst and
// advances posOut past the closing quote. The hot path aliases the input via
// unsafe.String; escape sequences fall back to scan.String (allocates).
// Used for both keys and value fields — in typical payloads neither have
// escapes so the loop stays tight. See inlineScanInt64 for `field` semantics.
func inlineScanString(b *bytes.Buffer, posIn, dst, posOut, field string) {
	// Loop stops at the closing `"`, an escape `\`, OR any control byte
	// (< 0x20). RFC 8259 forbids unescaped control characters in JSON
	// strings; both stdlib v1 and v2 reject. The fast path used to scan
	// only for `"`/`\\`, silently passing raw \x01-\x1f through —
	// matches sonic's behavior but not jsonv2's. ggen targets jsonv2,
	// so reject. The slow path (scan.String) already rejects, so the
	// `data[ke] < 0x20` branch returns ErrBadString directly without
	// falling through.
	// Emitted brace-less: `ke` lands in the caller's scope. Every call site
	// owns its scope (case body, elem loop, `var s` prelude) except
	// renderMap's value scan, which renames its end var via
	// inlineScanStringVar — the key scan in the same loop body already
	// declared `ke`.
	inlineScanStringVar(b, posIn, dst, posOut, field, "ke")
}

// inlineScanStringVar is inlineScanString with a caller-chosen name for the
// closing-quote cursor local.
func inlineScanStringVar(b *bytes.Buffer, posIn, dst, posOut, field, ke string) {
	fmt.Fprintf(b, `if %[1]s >= len(data) || data[%[1]s] != '"' { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrExpectString) }
%[5]s := %[1]s + 1
for %[5]s < len(data) && data[%[5]s] != '"' && data[%[5]s] != '\\' && data[%[5]s] >= 0x20 { %[5]s++ }
if %[5]s >= len(data) { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrUnterminated) }
if data[%[5]s] < 0x20 { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrBadString) }
if data[%[5]s] == '"' {
	%[3]s = unsafe.String(unsafe.SliceData(data[%[1]s+1:]), %[5]s-%[1]s-1)
	%[4]s = %[5]s + 1
} else {
	%[3]s, %[4]s, err = scan.String(data, %[1]s)
	if err != nil { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, err) }
}
`, posIn, field, dst, posOut, ke)
}

// emitReceiverReset emits the per-container reset block at the top of
// DecodeFrom / DecodeFromStream. The decoder is decode-into-receiver:
// `result` IS the value the caller passed in. Scalars / structs merge
// naturally (recursive DecodeFrom on a nested struct passes the existing
// value as the receiver of the next call); containers MUST be reset so
// the new decoder never appends over data carried in from the receiver.
// Deliberately UNCONDITIONAL (not per-present-key): a blank payload
// yields a blank slate while keeping container capacity for reuse.
//
//   - slices, []byte (KindBytes), and the inline catch-all map all get
//     `if X != nil { X = X[:0] }` (or `clear(X)` for maps) so existing
//     backing is reused but starts at len=0.
//   - fixed-length arrays (KindArray) need no reset — strict-length
//     decode overwrites every slot or errors.
//   - pointer fields are not reset here. Single `*T` merges into a non-nil
//     receiver pointee inside the renderField pointer branch (reuse, not
//     reset); multi-level `**T` always rebuilds the chain. Either way no
//     entry-reset is needed or correct.
func emitReceiverReset(b *bytes.Buffer, s StructInfo) {
	for _, f := range s.Fields {
		// Pointer-to-container fields (`*[]T`, `*map[K]V`) are not reset:
		// the pointer-emit path discards the receiver pointer and
		// allocates a fresh pointee anyway, so resetting the receiver's
		// pointee here would also be wrong syntax (`*[]int[:0]` is not
		// a valid expression).
		if f.Pointer {
			continue
		}
		switch f.Kind {
		case KindSlice, KindBytes:
			fmt.Fprintf(b, "if result.%[1]s != nil { result.%[1]s = result.%[1]s[:0] }\n", f.GoName)
		case KindMap:
			fmt.Fprintf(b, "if result.%[1]s != nil { clear(result.%[1]s) }\n", f.GoName)
		}
	}
}

// renderDecode emits the body of DecodeFrom: a loop that reads each
// JSON key, dispatches to per-field scan code, and handles ',' / '}'.
// Zero-copy (strings alias the input) and zero-alloc on the happy path.
// Dispatch is length-first so missing keys reject with a single int compare
// instead of a string compare per case. Whitespace skipping is inlined at
// each hot-path site to avoid the ~5ns/call overhead dominating runtime.
func renderDecode(b *bytes.Buffer, s StructInfo) {
	// Named results home the values directly in the caller-allocated return
	// slot; the `result = recv` prologue seeds `result` from the receiver
	// (merge source). Every `return result, …` then compiles to register sets
	// + RET with no struct copy — vs an anonymous result, where each of the
	// ~99 RET sites copies the full receiver-sized struct. Happy path is
	// copy-neutral (the one entry copy replaces the one exit copy); error
	// paths and function text shrink. Naming `i`/`err` too drops the
	// `i := 0` + `var err error; _ = err` prelude — `i` zero-inits and an
	// unused named `err` needs no blank assignment. See perf-candidates [15].
	fmt.Fprintf(b, "func (recv %s) DecodeFrom(data []byte) (result %s, i int, err error) {\n", s.Name, s.Name)
	b.WriteString("result = recv\n")
	if s.IsAlias {
		renderAliasDecode(b, s)
		b.WriteString("}\n\n")
		return
	}
	emitReceiverReset(b, s)
	// `err` is the named result (see signature) — every sub-render reassigns
	// it with `=`; a pure-primitive struct that never touches it just leaves
	// the named result unused, no blank assignment needed.
	if s.MultiErr {
		b.WriteString("var errs validation.Errors\n")
	}

	// Per-field "seen" tracking serves two masters: required-field
	// post-loop checks (when validation is on) and duplicate-key guard
	// (when AllowDups is off). Narrow structs use per-field bools (1 byte
	// each, fit in registers); wide structs (>seenBitmaskThreshold) use
	// a packed bitmask to cut stack/cache pressure on deep recursion.
	if useSeenBitmask(s) {
		b.WriteString(seenDecl(s))
	} else {
		for _, f := range s.Fields {
			if f.Inline {
				continue
			}
			if needsSeen(f) {
				fmt.Fprintf(b, "seen%s := false\n", f.GoName)
			}
		}
	}

	inlineSkipWS(b, "i")
	b.WriteString(`if i >= len(data) || data[i] != '{' { return result, i, decode.NewParseErr("", i, scan.ErrBadObject) }
i++
`)
	inlineSkipWS(b, "i")
	b.WriteString("if i < len(data) && data[i] == '}' {\ni++\n")
	renderPostLoop(b, s)
	b.WriteString("return result, i, nil\n}\nfor {\nvar key string\n")
	inlineScanString(b, "i", "key", "i", `""`)
	inlineSkipWS(b, "i")
	b.WriteString(`if i >= len(data) || data[i] != ':' { return result, i, decode.NewParseErr("", i, scan.ErrBadObject) }
i++
`)
	inlineSkipWS(b, "i")
	renderDispatch(b, s)
	inlineSkipWS(b, "i")
	b.WriteString(`if i >= len(data) { return result, i, decode.NewParseErr("", i, scan.ErrBadObject) }
if data[i] == ',' { i++; `)
	inlineSkipWS(b, "i")
	b.WriteString("continue }\nif data[i] == '}' {\ni++\n")
	renderPostLoop(b, s)
	b.WriteString(`return result, i, nil
}
return result, i, decode.NewParseErr("", i, scan.ErrBadObject)
}`)
	b.WriteString("}\n\n")
}

// renderPostLoop emits end-of-parse bookkeeping: required-field checks
// (when validation is on) and the multierr flush (when MultiErr is on).
// Called at every success exit inside DecodeFrom / DecodeFromStream.
func renderPostLoop(b *bytes.Buffer, s StructInfo) {
	renderPostLoopShape(b, s, false)
}

// renderStreamPostLoop is the stream-path counterpart — same checks, but
// emits `return result, X` (no position arg, since Stream owns s.Pos).
func renderStreamPostLoop(b *bytes.Buffer, s StructInfo) {
	renderPostLoopShape(b, s, true)
}

func renderPostLoopShape(b *bytes.Buffer, s StructInfo, stream bool) {
	retShape := "return result, i, %s"
	errsShape := "if len(errs) > 0 { return result, i, errs }\n"
	if stream {
		retShape = "return result, %s"
		errsShape = "if len(errs) > 0 { return result, errs }\n"
	}
	if !s.NoValidate {
		for _, f := range s.Fields {
			if !f.IsRequired() || f.Inline {
				continue
			}
			errExpr := requiredErr(f.JSONName)
			notSeen := seenNotAccess(s, f)
			if s.MultiErr {
				fmt.Fprintf(b, "if %s { errs = append(errs, %s) }\n", notSeen, errExpr)
			} else {
				fmt.Fprintf(b, "if %s { "+retShape+" }\n", notSeen, errExpr)
			}
		}
	}
	if s.MultiErr {
		b.WriteString(errsShape)
	}
}

// renderDispatch emits a flat string switch on key. The compiler lowers it
// to length-grouped binary search / jump tables itself — a manual
// length-first outer switch benched equal-or-slower at every width.
func renderDispatch(b *bytes.Buffer, s StructInfo) {
	// emitField wraps the per-field parse code with seen-tracking and dup
	// handling. Three shapes share the same `if seen { … } else { set;
	// render }` skeleton — what changes is the seen-branch:
	//   - AllowDups: skip the duplicate value via scan.SkipValue
	//     (first-wins — the second occurrence's value is dropped).
	//   - MultiErr: log a DuplicateKeyError AND skip, so partial decode
	//     stays intact for the rest of the multierr accumulation.
	//   - default: error out immediately.
	// `render` writes the field's decode body into b directly so the
	// renderField call drills the same buffer instead of routing through
	// an intermediate string.
	emitField := func(b *bytes.Buffer, f FieldInfo) {
		f.AtDispatch = true
		if f.Inline || !needsSeen(f) {
			renderField(b, f, "result."+f.GoName, "i")
			return
		}
		set := seenSet(s, f)
		seen := seenAccess(s, f)
		chk := bytesErrCheck(fieldLit(f), "i")
		if s.AllowDups {
			fmt.Fprintf(b, `if %s {
	i, err = scan.SkipValue(data, i)
	%s} else {
	%s`, seen, chk, set)
			renderField(b, f, "result."+f.GoName, "i")
			b.WriteString("}\n")
			return
		}
		if s.MultiErr {
			fmt.Fprintf(b, `if %[1]s {
	errs = append(errs, &validation.DuplicateKeyError{Path: []string{%[2]q}})
	i, err = scan.SkipValue(data, i)
	%[3]s} else {
	%[4]s`, seen, f.JSONName, chk, set)
			renderField(b, f, "result."+f.GoName, "i")
			b.WriteString("}\n")
			return
		}
		fmt.Fprintf(b, `if %s { return result, i, &validation.DuplicateKeyError{Path: []string{%q}} }
%s`, seen, f.JSONName, set)
		renderField(b, f, "result."+f.GoName, "i")
	}

	b.WriteString("switch key {\n")
	for _, f := range s.Fields {
		if f.Inline {
			continue
		}
		fmt.Fprintf(b, "case %q:\n", f.JSONName)
		emitField(b, f)
	}
	b.WriteString("default:\n")
	b.WriteString(unknownKey(s, "i"))
	b.WriteString("}\n")
}

// keyValidateAndMod emits mods and validation on the map key variable
// (keyRef) into b. The rules come from the `keys:` tag bucket. Both
// renderMods and renderValidationOn are called with the 3-tuple return
// shape (posVar="i") since map readers always run mid-stream.
func keyValidateAndMod(b *bytes.Buffer, f FieldInfo, keyRef string) {
	if f.NoValidate || (len(f.KeyMods) == 0 && len(f.KeyValidation) == 0) {
		return
	}
	if len(f.KeyMods) > 0 {
		renderMods(b, f.KeyMods, keyRef, "string", KindString)
	}
	if len(f.KeyValidation) > 0 {
		renderValidationOn(b, f.KeyValidation, keyRef, f.JSONName+".key", KindString, f.MultiErr, "i")
	}
}

// keyValidateAndModStream is the stream-path counterpart of
// keyValidateAndMod. Emits 2-tuple `return result, err` shapes.
func keyValidateAndModStream(b *bytes.Buffer, f FieldInfo, keyRef string) {
	if f.NoValidate || (len(f.KeyMods) == 0 && len(f.KeyValidation) == 0) {
		return
	}
	if len(f.KeyMods) > 0 {
		renderStreamMods(b, f.KeyMods, keyRef, "string", KindString)
	}
	if len(f.KeyValidation) > 0 {
		renderValidationOn(b, f.KeyValidation, keyRef, f.JSONName+".key", KindString, f.MultiErr, "")
	}
}

// renderMap emits map[string]V decode for the byte path. Accepts `null`
// → nil out the map field; empty `{}` → non-nil empty (stdlib parity).
// Receiver merge: emitReceiverReset has already done `clear(ref)` at
// the top of DecodeFrom, so non-nil maps keep their bucket array
// (allocation only when ref is nil — `if ref == nil { ref = make(...) }`).
// err is from the DecodeFrom function-body scope; no local decl. Maps
// don't expose interior pointers (`&m[k]` is illegal), so unlike slices
// we can't decode struct elems directly into the slot. We decode into
// `mv` (or the inline scanner's `mn` for primitives) and assign at the
// end.
func renderMap(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	field := fieldLit(f)
	makeExpr := fmt.Sprintf("make(%s)", f.GoType)
	if cap := mapPreallocCap(f); cap > 0 {
		makeExpr = fmt.Sprintf("make(%s, %d)", f.GoType, cap)
	}
	// At dispatch level the null branch breaks straight to the comma
	// handling instead of nesting the whole object read in an else.
	// No wrapper block: `mk` / `mv` / `mn` all live inside the element loop.
	flat := nullBreakOK(f)
	inlineSkipWS(b, posVar)
	inlineNullPeek(b, posVar)
	fmt.Fprintf(b, "%s = nil\n", ref)
	if flat {
		b.WriteString("break\n}\n")
	} else {
		b.WriteString("} else {\n")
	}
	fmt.Fprintf(b, `if %[1]s >= len(data) || data[%[1]s] != '{' { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrBadObject) }
	%[1]s++
`, posVar, field)
	inlineSkipWS(b, posVar)
	// ref is decode-into-receiver: either nil (fresh) or already cleared
	// at the top of DecodeFrom (existing map kept for reuse). Allocate only
	// when nil; cleared maps reuse their bucket array.
	fmt.Fprintf(b, `	if %[1]s < len(data) && data[%[1]s] == '}' {
		if %[2]s == nil { %[2]s = %[3]s{} }
	} else {
		if %[2]s == nil { %[2]s = %[4]s }
	}
	for %[1]s < len(data) && data[%[1]s] != '}' {
		var mk string
`, posVar, ref, f.GoType, makeExpr)
	inlineScanString(b, posVar, "mk", posVar, field)
	keyValidateAndMod(b, f, "mk")
	inlineSkipWS(b, posVar)
	fmt.Fprintf(b, `		if %[1]s >= len(data) || data[%[1]s] != ':' { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrBadObject) }
		%[1]s++
`, posVar, field)
	inlineSkipWS(b, posVar)

	mapTarget := fmt.Sprintf("%s[mk]", ref)
	if _, eDepth := elemPtrType(f); eDepth > 0 {
		// Pointer value (any depth) — same parse-first cascade scalar
		// pointer fields use, decoded straight into the map slot. TargetNil
		// keeps the emit assignment-only (null → `m[mk] = nil`, success →
		// `m[mk] = new(…v)`), so the unaddressable index is fine and the
		// leaf temp stays fresh per entry. Elem rules ride inside the
		// cascade.
		pf := elemPtrField(f, f.JSONName+".value")
		pf.TargetNil = true
		renderField(b, pf, mapTarget, posVar)
		inlineSkipWS(b, posVar)
		fmt.Fprintf(b, `		if %[1]s < len(data) && data[%[1]s] == ',' { %[1]s++; `, posVar)
		inlineSkipWS(b, posVar)
		emitNoCloseAfterComma(b, posVar, '}')
		fmt.Fprintf(b, `			continue }
		break
	}
	if %[1]s >= len(data) || data[%[1]s] != '}' { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrBadObject) }
	%[1]s++
`, posVar, field)
		if !flat {
			b.WriteString("}\n") // close else (null-check)
		}
		return
	}
	switch f.ElemKind {
	case KindString:
		// Straight into the map slot — no `mv` temp. The end-var is `ve`
		// because the key scan above already declared `ke` in this loop body.
		inlineScanStringVar(b, posVar, mapTarget, posVar, field, "ve")
	case KindBool:
		fmt.Fprintf(b, `%[2]s, %[1]s, err = scan.Bool(data, %[1]s)
if err != nil { return result, %[1]s, decode.NewParseErr(%[3]s, %[1]s, err) }
`, posVar, mapTarget, field)
	case KindInt, KindInt8, KindInt16, KindInt32, KindInt64:
		castFn := ""
		if f.ElemType != "int64" {
			castFn = f.ElemType
		}
		inlineScanInt64(b, posVar, mapTarget, castFn, field)
	case KindUint, KindUint8, KindUint16, KindUint32, KindUint64:
		castFn := ""
		if f.ElemType != "uint64" {
			castFn = f.ElemType
		}
		inlineScanUint64(b, posVar, mapTarget, castFn, field)
	case KindFloat32, KindFloat64:
		if f.ElemKind == KindFloat64 {
			fmt.Fprintf(b, `%[2]s, %[1]s, err = scan.Float64(data, %[1]s)
if err != nil { return result, %[1]s, decode.NewParseErr(%[3]s, %[1]s, err) }
`, posVar, mapTarget, field)
		} else {
			fmt.Fprintf(b, `var fv float64
fv, %[1]s, err = scan.Float64(data, %[1]s)
if err != nil { return result, %[1]s, decode.NewParseErr(%[3]s, %[1]s, err) }
%[2]s = float32(fv)
`, posVar, mapTarget, field)
		}
	case KindStruct:
		if isGenerated(f.ElemType) {
			// `var mv` doubles as the value-receiver source and the
			// stored value. DecodeFrom takes `data[%s:]` (the new
			// signature drops the leading `i int` param); the bytes
			// consumed (`_n`) advance posVar.
			fmt.Fprintf(b, `var mv %[1]s
var _n int
mv, _n, err = mv.DecodeFrom(data[%[2]s:])
%[2]s += _n
%[4]s%[3]s = mv
`, f.ElemType, posVar, mapTarget, nestedDecodeErrCheck(fieldLit(f), f.MultiErr, true))
		} else {
			fmt.Fprintf(b, `start := %[1]s
mk2, err := scan.SkipValue(data, start)
if err != nil { return result, %[1]s, decode.NewParseErr(%[5]s, %[1]s, err) }
var mv %[2]s
if err := json.Unmarshal(data[start:mk2], &mv); err != nil { return result, %[1]s, decode.NewParseErr(%[5]s, %[1]s, err) }
%[3]s = mv
%[4]s = mk2
`, posVar, f.ElemType, mapTarget, posVar, field)
		}
	default:
		fmt.Fprintf(b, `mk2, err := scan.SkipValue(data, %[1]s)
if err != nil { return result, %[1]s, decode.NewParseErr(%[3]s, %[1]s, err) }
%[2]s = mk2
`, posVar, posVar, field)
	}
	// dive-mods on mv — only for string elem; patch ref in the mod output.
	if len(f.ElemMods) > 0 {
		renderMods(b, f.ElemMods, mapTarget, f.ElemType, f.ElemKind)
	}
	if len(f.ElemValidation) > 0 {
		renderValidationOn(b, f.ElemValidation, mapTarget, f.JSONName+".value", f.ElemKind, f.MultiErr, "i")
	}
	inlineSkipWS(b, posVar)
	fmt.Fprintf(b, `		if %[1]s < len(data) && data[%[1]s] == ',' { %[1]s++; `, posVar)
	inlineSkipWS(b, posVar)
	emitNoCloseAfterComma(b, posVar, '}')
	fmt.Fprintf(b, `			continue }
		break
	}
	if %[1]s >= len(data) || data[%[1]s] != '}' { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrBadObject) }
	%[1]s++
`, posVar, field)
	if !flat {
		b.WriteString("}\n") // close else (null-check)
	}
}

// renderBytes emits bytes decode for (base64/hex/array). JSON `null` →
// nil out the field — parity with the sibling slice/map kinds (stdlib
// v1/v2 accept null here too).
func renderBytes(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	// No wrapper block — the null peek declares no locals and
	// renderBytesValue's `var s` is single-per-scope.
	inlineNullPeek(b, posVar)
	fmt.Fprintf(b, "%s = nil\n", ref)
	if nullBreakOK(f) {
		b.WriteString("break\n}\n")
		renderBytesValue(b, f, ref, posVar)
		return
	}
	b.WriteString("} else {\n")
	renderBytesValue(b, f, ref, posVar)
	b.WriteString("}\n")
}

func renderBytesValue(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	field := fieldLit(f)
	if f.Format == "array" {
		// `u` not `v`: a pointer-leaf caller declares `var v []byte` in the
		// same scope.
		inlineSkipWS(b, posVar)
		fmt.Fprintf(b, `if %[1]s >= len(data) || data[%[1]s] != '[' { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrBadArray) }
%[1]s++
`, posVar, field)
		inlineSkipWS(b, posVar)
		fmt.Fprintf(b, `var u uint64
for %[1]s < len(data) && data[%[1]s] != ']' {
	u, %[1]s, err = scan.Uint64(data, %[1]s)
	if err != nil { return result, %[1]s, decode.NewParseErr(%[3]s, %[1]s, err) }
	%[2]s = append(%[2]s, byte(u))
`, posVar, ref, field)
		inlineSkipWS(b, posVar)
		fmt.Fprintf(b, `	if %[1]s < len(data) && data[%[1]s] == ',' { %[1]s++; `, posVar)
		inlineSkipWS(b, posVar)
		emitNoCloseAfterComma(b, posVar, ']')
		fmt.Fprintf(b, ` continue }
	break
}
if %[1]s >= len(data) || data[%[1]s] != ']' { return result, %[1]s, decode.NewParseErr(%[2]s, %[1]s, scan.ErrBadArray) }
%[1]s++
`, posVar, field)
		return
	}
	// AppendDecode form skips the `[]byte(s)` copy DecodeString does
	// internally. We pre-size dst via DecodedLen so the single
	// allocation is exact and AppendDecode never grows it.
	enc := "base64.StdEncoding"
	dlen := "base64.StdEncoding.DecodedLen"
	switch f.Format {
	case "base64url":
		enc = "base64.URLEncoding"
		dlen = "base64.URLEncoding.DecodedLen"
	case "base32":
		enc = "base32.StdEncoding"
		dlen = "base32.StdEncoding.DecodedLen"
	case "base32hex":
		enc = "base32.HexEncoding"
		dlen = "base32.HexEncoding.DecodedLen"
	case "base16", "hex":
		enc = "" // hex doesn't share the Encoding API
	}
	if enc == "" {
		// hex.AppendDecode + hex.DecodedLen. ref was pre-reset to [:0] at
		// DecodeFrom's top; only realloc when cap is insufficient.
		b.WriteString("var s string\n")
		inlineScanString(b, posVar, "s", posVar, field)
		fmt.Fprintf(b, `if cap(%[1]s) < hex.DecodedLen(len(s)) { %[1]s = make([]byte, 0, hex.DecodedLen(len(s))) }
%[1]s, err = hex.AppendDecode(%[1]s, unsafe.Slice(unsafe.StringData(s), len(s)))
if err != nil { return result, %[2]s, decode.NewParseErr(%[3]s, %[2]s, err) }
`, ref, posVar, field)
		return
	}
	b.WriteString("var s string\n")
	inlineScanString(b, posVar, "s", posVar, field)
	fmt.Fprintf(b, `if cap(%[1]s) < %[2]s(len(s)) { %[1]s = make([]byte, 0, %[2]s(len(s))) }
%[1]s, err = %[3]s.AppendDecode(%[1]s, unsafe.Slice(unsafe.StringData(s), len(s)))
if err != nil { return result, %[4]s, decode.NewParseErr(%[5]s, %[4]s, err) }
`, ref, dlen, enc, posVar, field)
}

// renderTime emits time.Time decode decode.
func renderTime(b *bytes.Buffer, f FieldInfo, ref, posVar string) {
	field := fieldLit(f)
	layout, numeric := timeLayoutExpr(f.Format)
	if numeric != "" {
		// `format:unix` reads a JSON number that may carry fractional
		// seconds (jsonv2 emits float when nanos != 0). Parse as float
		// and split into (sec, nsec) so the wire is fully round-trip
		// safe. Other unix* variants are integer-granular by unit.
		if numeric == "Unix" {
			fmt.Fprintf(b, `var f float64
f, %[1]s, err = scan.Float64(data, %[1]s)
if err != nil { return result, %[1]s, decode.NewParseErr(%[3]s, %[1]s, err) }
sec := int64(f)
nsec := int64((f - float64(sec)) * 1e9)
%[2]s = time.Unix(sec, nsec)
`, posVar, ref, field)
			return
		}
		ctor := map[string]string{
			"UnixMilli": "time.UnixMilli(n)",
			"UnixMicro": "time.UnixMicro(n)",
			"UnixNano":  "time.Unix(0, n)",
		}[numeric]
		fmt.Fprintf(b, `var n int64
n, %[1]s, err = scan.Int64(data, %[1]s)
if err != nil { return result, %[1]s, decode.NewParseErr(%[4]s, %[1]s, err) }
%[2]s = %[3]s
`, posVar, ref, ctor, field)
		return
	}
	b.WriteString("var s string\n")
	inlineScanString(b, posVar, "s", posVar, field)
	fmt.Fprintf(b, `%[1]s, err = time.Parse(%[2]s, s)
if err != nil { return result, %[3]s, decode.NewParseErr(%[4]s, %[3]s, err) }
`, ref, layout, posVar, field)
}

