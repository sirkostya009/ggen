	t.Run("FilenameConstraint_FoldedIntoBucket", func(t *testing.T) {
		t.Parallel()
		base := t.TempDir()
		writeGgenModule(t, base, "osconstraint")
		pkg := filepath.Join(base, "pkg")
		writeFixture(
			t,
			filepath.Join(pkg, "os_linux.go"),
			"//go:build !nope\n\npackage pkg\n\n//ggen:generate\ntype OnlyLinux struct {\n\tX int `json:\"x\"`\n}\n",
		)
		writeFixture(t, filepath.Join(pkg, "arch_amd64_test.go"), "package pkg\n\n//ggen:generate\ntype OnlyAMD64 struct {\n\tX int `json:\"x\"`\n}\n")
		writeFixture(t, filepath.Join(pkg, "common.go"), "package pkg\n\n//ggen:generate\ntype Common struct {\n\tY int `json:\"y\"`\n}\n")
		if out, err := runCLI(t, bin, base, "./pkg"); err != nil {
			t.Fatalf("ggen ./pkg: %v\n%s", err, out)
		}
		linux := mustReadOutput(t, filepath.Join(pkg, "pkg_nope_linux_ggen.go"))
		if !strings.Contains(linux, "//go:build !nope && linux\n") || !strings.Contains(linux, "recv OnlyLinux) DecodeFrom") {
			t.Errorf("os_linux.go bucket lacks its constraint:\n%s", linux)
		}
		amd := mustReadOutput(t, filepath.Join(pkg, "pkg_amd64_ggen_test.go"))
		if !strings.Contains(amd, "//go:build amd64\n") {
			t.Errorf("arch_amd64_test.go bucket lacks its constraint:\n%s", amd)
		}
		common := mustReadOutput(t, filepath.Join(pkg, "pkg_ggen.go"))
		if strings.Contains(common, "//go:build") || strings.Contains(common, "OnlyLinux") {
			t.Errorf("unconstrained bucket polluted:\n%s", common)
		}
		for _, goos := range []string{"linux", "windows"} {
			if out, err := runGo(t, base, []string{"GOOS=" + goos}, "vet", "./pkg"); err != nil {
				t.Errorf("GOOS=%s go vet ./pkg: %v\n%s", goos, err, out)
			}
		}

		// Single-file mode. Go treats os_linux.go as linux-only by its name,
		// but os_linux_ggen.go ends in `_ggen`, so Go no longer sees the
		// suffix. The //go:build header must carry it instead.
		if out, err := runCLI(t, bin, base, "pkg/os_linux.go"); err != nil {
			t.Fatalf("ggen pkg/os_linux.go: %v\n%s", err, out)
		}
		single := mustReadOutput(t, filepath.Join(pkg, "os_linux_ggen.go"))
		if !strings.Contains(single, "//go:build !nope && linux\n") {
			t.Errorf("single-file output lacks the filename constraint:\n%s", single)
		}
		if err := os.Remove(filepath.Join(pkg, "pkg_nope_linux_ggen.go")); err != nil {
			t.Fatal(err)
		}
		if out, err := runGo(t, base, []string{"GOOS=darwin"}, "build", "./pkg"); err != nil {
			t.Errorf("GOOS=darwin go build ./pkg: %v\n%s", err, out)
		}
	})

	t.Run("CgoFile_BucketedBehindCgo", func(t *testing.T) {
		t.Parallel()
		if out, err := runGo(t, ".", nil, "env", "CGO_ENABLED"); err != nil || strings.TrimSpace(out) != "1" {
			t.Skip("cgo is not available")
		}
		const cgSrc = "//go:build !nope\n\npackage pkg\n\n// #include <stdlib.h>\nimport \"C\"\n\n//ggen:generate\ntype CG struct {\n\tX int `json:\"x\"`\n}\n"
		base := t.TempDir()
		writeGgenModule(t, base, "cgoconstraint")
		pkg := filepath.Join(base, "pkg")
		writeFixture(t, filepath.Join(pkg, "cg.go"), cgSrc)
		writeFixture(t, filepath.Join(pkg, "plain.go"), "package pkg\n\n//ggen:generate\ntype Plain struct {\n\tX int `json:\"x\"`\n}\n")
		if out, err := runCLI(t, bin, base, "./pkg"); err != nil {
			t.Fatalf("ggen ./pkg: %v\n%s", err, out)
		}
		cg := mustReadOutput(t, filepath.Join(pkg, "pkg_nope_cgo_ggen.go"))
		if !strings.Contains(cg, "//go:build !nope && cgo\n") || !strings.Contains(cg, "recv CG) DecodeFrom") {
			t.Errorf("cg.go bucket lacks its constraint:\n%s", cg)
		}
		if common := mustReadOutput(t, filepath.Join(pkg, "pkg_ggen.go")); strings.Contains(common, "CG") {
			t.Errorf("unconstrained bucket holds CG:\n%s", common)
		}
		if out, err := runGo(t, base, []string{"CGO_ENABLED=0"}, "vet", "./pkg"); err != nil {
			t.Errorf("CGO_ENABLED=0 go vet ./pkg: %v\n%s", err, out)
		}

		if out, err := runCLI(t, bin, base, "pkg/cg.go"); err != nil {
			t.Fatalf("ggen pkg/cg.go: %v\n%s", err, out)
		}
		if single := mustReadOutput(t, filepath.Join(pkg, "cg_ggen.go")); !strings.Contains(single, "//go:build !nope && cgo\n") {
			t.Errorf("single-file output lacks the cgo constraint:\n%s", single)
		}

		// The go command caches cgo output by content, so a second copy of
		// the file is loaded with the first copy's //line paths.
		other := t.TempDir()
		writeGgenModule(t, other, "cgoconstraint")
		writeFixture(t, filepath.Join(other, "pkg", "cg.go"), cgSrc)
		if out, err := runCLI(t, bin, other, "pkg/cg.go"); err != nil {
			t.Fatalf("ggen pkg/cg.go in a second copy: %v\n%s", err, out)
		}
		mustReadOutput(t, filepath.Join(other, "pkg", "cg_ggen.go"))
	})

