var update = flag.Bool("update", false, "rewrite golden files")

const (
	api   = "github.com/sirkostya009/ggen/gen/testdata/api"
	other = "github.com/sirkostya009/ggen/gen/testdata/other"
)

var files = []string{"api/Requests.kt", "api/Responses.kt", "shared/Money.kt"}

func render(t *testing.T) (string, *gen.Output) {
	t.Helper()
	set, err := gen.Load("../testdata/api", "../testdata/other")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	header := kotlin.Header("// Code generated by ggen. DO NOT EDIT.")
	apiPkg := kotlin.New("com.example.api", header, kotlin.External("log/slog.Level", "String"))

	requests := out.File("api/Requests.kt", apiPkg)
	requests.Place(set.Type(api, "CreateUser").In(), "CreateUser")
	requests.Place(set.Type(api, "Address").In(), "AddressInput")
	requests.Place(set.Type(api, "Edges").In(), "EdgesInput")
	requests.Place(set.Type(api, "Tags").In(), "TagsInput")

	responses := out.File("api/Responses.kt", apiPkg)
	responses.Place(set.Type(api, "User").Out().StrictFields("role"), "User")
	responses.Place(set.Type(api, "Address").Out(), "Address")
	responses.Place(set.Type(api, "Role").Out(), "Role")
	responses.Place(set.Type(api, "Plan").Out(), "Plan")
	responses.Place(set.Type(api, "Edges").Out(), "Edges")
	responses.Place(set.Type(api, "Tags").Out(), "Tags")

	out.File("shared/Money.kt", kotlin.New("com.example.shared", header)).Place(set.Type(other, "Money").Out(), "User")

	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	return dir, out
}

func TestClasses(t *testing.T) {
	t.Parallel()
	dir, out := render(t)
	var issues []string
	for _, i := range out.Report().Issues {
		issues = append(issues, i.String())
	}
	want := []string{
		"api.Edges (input): kotlinx.serialization has no catch-all map; undeclared keys are dropped",
		"api.Edges (input).conv: a converter accepts several JSON shapes; rendered as JsonElement",
		"api.Plan (output): kotlinx.serialization enums are JSON strings; integer values render as Long",
		"api.User (output).status: a closed set of 2 values is not a named type here; rendered as String",
		"api.User (output).point: image.Point is external with an unknown shape; map it with kotlin.External or kotlin.ExternalFor",
		"api.Edges (output): kotlinx.serialization has no catch-all map; undeclared keys are dropped",
		"api.Edges (output).lower: a closed set of 2 values is not a named type here; rendered as String",
	}
	if !slices.Equal(issues, want) {
		t.Errorf("report:\n%s\nwant:\n%s", strings.Join(issues, "\n"), strings.Join(want, "\n"))
	}
	for _, name := range files {
		got, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		golden := filepath.Join("testdata", strings.ReplaceAll(name, "/", "_"))
		if *update {
			os.WriteFile(golden, got, 0o644)
			continue
		}
		want, err := os.ReadFile(golden)
		if err != nil {
			t.Fatalf("%v (run with -update)", err)
		}
		if !bytes.Equal(got, want) {
			t.Errorf("%s differs from %s:\n%s", name, golden, got)
		}
	}
}

// TestRuntime compiles the classes and decodes inputs with known Go verdicts.
// It needs GGEN_KOTLIN_HOME holding kotlinc/, a JRE directory starting with
// "jdk", and the kotlinx-serialization-{core,json}-jvm jars.
func TestRuntime(t *testing.T) {
	t.Parallel()
	home := os.Getenv("GGEN_KOTLIN_HOME")
	if home == "" {
		t.Skip("set GGEN_KOTLIN_HOME to a directory with kotlinc, a JRE and the kotlinx.serialization jars")
	}
	jres, _ := filepath.Glob(filepath.Join(home, "jdk*"))
	if len(jres) == 0 {
		t.Fatal("no JRE in GGEN_KOTLIN_HOME")
	}
	dir, _ := render(t)
	user := func(extra string) string {
		return `{"id":1,"role":"admin","status":"active","created":"2020-01-01T00:00:00Z","level":"INFO","point":{"X":1},` +
			`"money":{"amount":1,"currency":"USD"},"address":{"city":"x","zip":"12345"},"friends":null,"state":0` + extra + `}`
	}
	cases := []struct {
		class, input string
		ok           bool
	}{
		{"com.example.api.CreateUser", `{}`, false},
		{"com.example.api.CreateUser", `{"name":"ab","email":"a@b"}`, true},
		{"com.example.api.CreateUser", `{"name":"ab","email":"a@b","extra":1}`, false},
		{"com.example.api.CreateUser", `{"name":"ab","email":"a@b","age":null}`, true},
		{"com.example.api.CreateUser", `{"name":null,"email":"a@b"}`, false},
		{"com.example.api.CreateUser", `{"name":"ab","email":"a@b","address":{"city":"x"}}`, true},
		{"com.example.api.CreateUser", `{"name":"ab","email":"a@b","address":{}}`, false},
		{"com.example.api.EdgesInput", `{"zzz":"s","plist":null,"nz":null}`, true},
		{"com.example.api.EdgesInput", `{"quoted":"-128","max":[1,2],"dict":{"ab":1}}`, true},
		{"com.example.api.EdgesInput", `{"quoted":12}`, false},
		{"com.example.api.EdgesInput", `{"conv":"12"}`, true},
		{"com.example.api.User", user(``), true},
		{"com.example.api.User", user(`,"manager":` + user(``)), true},
		{"com.example.api.User", strings.Replace(user(``), `"role":"admin"`, `"role":"x"`, 1), false},
		{"com.example.api.User", user(`,"plan":2`), true},
		{"com.example.shared.User", `{"amount":1,"currency":""}`, true},
	}
	var main strings.Builder
	main.WriteString(`import kotlinx.serialization.KSerializer
import kotlinx.serialization.json.Json
import kotlinx.serialization.serializer

val full = Json { encodeDefaults = true }

// check decodes, then encodes both ways: the default Json leaves a
// default-valued property out, which Go reads as the zero value, and with
// encodeDefaults every key is written. Both have to decode back to the value.
fun <T> check(s: KSerializer<T>, json: String) {
    try {
        val v = Json.decodeFromString(s, json)
        val lean = Json.encodeToString(s, v)
        val fat = full.encodeToString(s, v)
        val ok = Json.decodeFromString(s, lean) == v && Json.decodeFromString(s, fat) == v
        println(if (ok) "ok" else "err round trip $lean $fat")
    } catch (e: Exception) {
        println("err " + e.message?.lineSequence()?.first())
    }
}

fun main() {
`)
	for _, c := range cases {
		fmt.Fprintf(&main, "    check(serializer<%s>(), %q)\n", c.class, c.input)
	}
	main.WriteString("}\n")
	mainFile := filepath.Join(dir, "Main.kt")
	os.WriteFile(mainFile, []byte(strings.ReplaceAll(main.String(), `$`, `\$`)), 0o644)

	env := append(os.Environ(), "JAVA_HOME="+jres[0], "PATH="+filepath.Join(jres[0], "bin")+string(os.PathListSeparator)+os.Getenv("PATH"))
	cp := filepath.Join(home, "kotlinx-serialization-core-jvm.jar") + ":" + filepath.Join(home, "kotlinx-serialization-json-jvm.jar")
	args := []string{
		"-Xplugin=" + filepath.Join(home, "kotlinc", "lib", "kotlinx-serialization-compiler-plugin.jar"),
		"-cp",
		cp,
		"-d",
		filepath.Join(dir, "classes"),
		mainFile,
	}
	for _, f := range files {
		args = append(args, filepath.Join(dir, f))
	}
	compile := exec.CommandContext(t.Context(), filepath.Join(home, "kotlinc", "bin", "kotlinc"), args...)
	compile.Env = env
	if b, err := compile.CombinedOutput(); err != nil {
		t.Fatalf("kotlinc: %v\n%s", err, b)
	}
	run := exec.CommandContext(
		t.Context(),
		filepath.Join(jres[0], "bin", "java"),
		"-Dstdout.encoding=UTF-8",
		"-cp",
		filepath.Join(dir, "classes")+":"+cp+":"+filepath.Join(home, "kotlinc", "lib", "kotlin-stdlib.jar"),
		"MainKt",
	)
	run.Env = env
	raw, err := run.Output()
	if err != nil {
		t.Fatalf("java: %v", err)
	}
	lines := strings.Split(strings.TrimSpace(string(raw)), "\n")
	for i, c := range cases {
		if ok := lines[i] == "ok"; ok != c.ok {
			t.Errorf("%s %s: ok=%v, want %v (%s)", c.class, c.input, ok, c.ok, lines[i])
		}
	}
}

// TestFor decides headers and external types per output file and placed type.
func TestFor(t *testing.T) {
	t.Parallel()
	set, err := gen.Load("../testdata/api", "../testdata/other")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	e := kotlin.New("com.example.api",
		kotlin.HeaderFor(func(f *gen.File) string { return "// " + f.Path }),
		kotlin.ExternalFor(func(_ *gen.File, p gen.Placed, t *gen.Type) (string, []string, bool) {
			return "Point", []string{"com.example.geometry.Point"}, t.Name == "Point" && p.Name == "User"
		}),
		kotlin.External("log/slog.Level", "String"),
	)
	f := out.File("User.kt", e)
	for _, name := range []string{"User", "Address", "Role", "Plan"} {
		f.Place(set.Type(api, name).Out(), name)
	}
	f.Place(set.Type(other, "Money").Out(), "Money")
	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(dir, "User.kt"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"// User.kt\n", "import com.example.geometry.Point\n", "    val point: Point,\n"} {
		if !strings.Contains(string(b), want) {
			t.Errorf("missing %q in:\n%s", want, b)
		}
	}
}

// TestAwkwardNames pins the backticks a Kotlin property needs, the report for
// two fields that spell one property, and that the result compiles.
func TestAwkwardNames(t *testing.T) {
	t.Parallel()
	set, err := gen.Load("../testdata/api", "../testdata/other")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	pkg := kotlin.New("com.example.api")
	out.File("Types.kt", pkg).Place(set.Type(api, "Awkward").Out(), "Awkward")
	out.File("Collides.kt", pkg).Place(set.Type(api, "Collides").Out(), "Collides")
	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(dir, "Types.kt"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"val `class`: String", "val func: String", "val `val`: String", "val `in`: String",
		"@SerialName(\"a b\")", "val spaced: String",
	} {
		if !strings.Contains(string(b), want) {
			t.Errorf("missing %q in:\n%s", want, b)
		}
	}
	var issues []string
	for _, i := range out.Report().Issues {
		issues = append(issues, i.Msg)
	}
	if want := "fields id and ID both spell the property id; rename one"; !slices.Contains(issues, want) {
		t.Errorf("report = %q, want %q", issues, want)
	}

	home := os.Getenv("GGEN_KOTLIN_HOME")
	jres, _ := filepath.Glob(filepath.Join(home, "jdk*"))
	if home == "" || len(jres) == 0 {
		t.Skip("set GGEN_KOTLIN_HOME to a directory with kotlinc, a JRE and the kotlinx.serialization jars")
	}
	env := append(os.Environ(), "JAVA_HOME="+jres[0], "PATH="+filepath.Join(jres[0], "bin")+string(os.PathListSeparator)+os.Getenv("PATH"))
	cp := filepath.Join(home, "kotlinx-serialization-core-jvm.jar") + ":" + filepath.Join(home, "kotlinx-serialization-json-jvm.jar")
	compile := exec.CommandContext(t.Context(), filepath.Join(home, "kotlinc", "bin", "kotlinc"),
		"-Xplugin="+filepath.Join(home, "kotlinc", "lib", "kotlinx-serialization-compiler-plugin.jar"),
		"-cp", cp, "-d", filepath.Join(dir, "classes"), filepath.Join(dir, "Types.kt"))
	compile.Env = env
	if b, err := compile.CombinedOutput(); err != nil {
		t.Fatalf("kotlinc: %v\n%s", err, b)
	}
}
