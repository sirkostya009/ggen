var update = flag.Bool("update", false, "rewrite golden files")

const (
	api   = "github.com/sirkostya009/ggen/gen/testdata/api"
	other = "github.com/sirkostya009/ggen/gen/testdata/other"
)

var files = []string{"API/Requests.swift", "API/Responses.swift", "API/JSON.swift", "Shared/Money.swift"}

func render(t *testing.T) (string, *gen.Output) {
	t.Helper()
	set, err := gen.Load("../testdata/api", "../testdata/other")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	header := swift.Header("// Code generated by ggen. DO NOT EDIT.")
	runtime := out.File("API/JSON.swift", swift.NewRuntime("API", header))
	apiModule := swift.New("API", header, swift.Runtime(runtime), swift.External("log/slog.Level", "String"))

	requests := out.File("API/Requests.swift", apiModule)
	requests.Place(set.Type(api, "CreateUser").In(), "CreateUser")
	requests.Place(set.Type(api, "Address").In(), "AddressInput")
	requests.Place(set.Type(api, "Edges").In(), "EdgesInput")
	requests.Place(set.Type(api, "Tags").In(), "TagsInput")

	responses := out.File("API/Responses.swift", apiModule)
	responses.Place(set.Type(api, "User").Out().StrictFields("role"), "User")
	responses.Place(set.Type(api, "Address").Out(), "Address")
	responses.Place(set.Type(api, "Role").Out(), "Role")
	responses.Place(set.Type(api, "Plan").Out(), "Plan")
	responses.Place(set.Type(api, "Edges").Out(), "Edges")
	responses.Place(set.Type(api, "Tags").Out(), "Tags")

	out.File("Shared/Money.swift", swift.New("Shared", header, swift.Public())).Place(set.Type(other, "Money").Out(), "User")

	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	return dir, out
}

func TestTypes(t *testing.T) {
	t.Parallel()
	dir, out := render(t)
	var issues []string
	for _, i := range out.Report().Issues {
		issues = append(issues, i.String())
	}
	want := []string{
		"api.Edges (input): JSONDecoder has no catch-all map; undeclared keys are dropped",
		"api.Edges (input).conv: a converter accepts several JSON shapes; rendered as JSONValue",
		"api.User (output).status: a closed set of 2 values is not a named type here; rendered as String",
		"api.User (output).point: image.Point is external with an unknown shape; map it with swift.External or swift.ExternalFor",
		"api.Edges (output): JSONDecoder has no catch-all map; undeclared keys are dropped",
		"api.Edges (output).lower: a closed set of 2 values is not a named type here; rendered as String",
	}
	if !slices.Equal(issues, want) {
		t.Errorf("report:\n%s\nwant:\n%s", strings.Join(issues, "\n"), strings.Join(want, "\n"))
	}
	for _, name := range files {
		got, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		golden := filepath.Join("testdata", strings.ReplaceAll(name, "/", "_"))
		if *update {
			os.WriteFile(golden, got, 0o644)
			continue
		}
		want, err := os.ReadFile(golden)
		if err != nil {
			t.Fatalf("%v (run with -update)", err)
		}
		if !bytes.Equal(got, want) {
			t.Errorf("%s differs from %s:\n%s", name, golden, got)
		}
	}
}

// TestRuntime compiles the types with swiftc, decodes inputs and round-trips
// them through JSONEncoder. It needs GGEN_SWIFTC, the path to swiftc.
func TestRuntime(t *testing.T) {
	t.Parallel()
	swiftc := os.Getenv("GGEN_SWIFTC")
	if swiftc == "" {
		t.Skip("set GGEN_SWIFTC to a swiftc binary")
	}
	dir, _ := render(t)
	user := func(extra string) string {
		return `{"id":1,"role":"admin","status":"active","created":"2020-01-01T00:00:00Z","level":"INFO","point":{"X":1},` +
			`"money":{"amount":1,"currency":"USD"},"address":{"city":"x","zip":"12345"},"friends":null,"state":0` + extra + `}`
	}
	cases := []struct {
		typ, input string
		ok         bool
	}{
		{"CreateUser", `{}`, false},
		{"CreateUser", `{"name":"ab","email":"a@b"}`, true},
		{"CreateUser", `{"name":"ab","email":"a@b","extra":1}`, true}, // JSONDecoder ignores unknown keys
		{"CreateUser", `{"name":"ab","email":"a@b","age":null}`, true},
		{"CreateUser", `{"name":null,"email":"a@b"}`, false},
		{"CreateUser", `{"name":"ab","email":"a@b","address":{"city":"x"}}`, true},
		{"CreateUser", `{"name":"ab","email":"a@b","address":{}}`, false},
		{"EdgesInput", `{"zzz":"s","plist":null,"nz":null}`, true},
		{"EdgesInput", `{"quoted":"-128","max":[1,2],"dict":{"ab":1},"fixed":"AQIDBA=="}`, true},
		{"EdgesInput", `{"quoted":12}`, false},
		{"EdgesInput", `{"fixed":"AQI"}`, false},
		{"EdgesInput", `{"conv":"12","raw":{"a":[1,null]}}`, true},
		{"EdgesInput", `{"raw":null}`, true},
		{"User", user(``), true},
		{"User", user(`,"manager":` + user(``)), true},
		{"User", strings.Replace(user(``), `"role":"admin"`, `"role":"x"`, 1), false},
		{"User", user(`,"plan":2`), true},
		{"User", user(`,"plan":3`), false},
		{"User", strings.Replace(user(``), `"id":1`, `"id":9223372036854775807`, 1), true},
		{
			"Edges",
			`{"list":null,"max":null,"plist":null,"dict":null,"quoted":"1","unix":1,"date":"2020-01-01","dur":"1s","hex":"","fixed":"AAAAAA==","ip":"","addr":"","ns":null,"raw":null,"lower":"x","nz":0,"conv":0,"tags":null}`,
			true,
		},
		{"Shared.User", `{"amount":1,"currency":""}`, true},
	}
	var main strings.Builder
	main.WriteString("import Foundation\nimport Shared\n\n")
	main.WriteString("func check<T: Codable & Equatable>(_ type: T.Type, _ input: String) {\n")
	main.WriteString("    do {\n        let v = try JSONDecoder().decode(type, from: Data(input.utf8))\n")
	main.WriteString("        let encoded = try JSONEncoder().encode(v)\n")
	main.WriteString("        guard try JSONDecoder().decode(type, from: encoded) == v else { print(\"err round trip\"); return }\n")
	main.WriteString("        print(\"ok\", String(decoding: encoded, as: UTF8.self))\n")
	main.WriteString("    } catch {\n        print(\"err\", String(describing: error).prefix(200))\n    }\n}\n\n")
	for _, c := range cases {
		fmt.Fprintf(&main, "check(%s.self, %q)\n", c.typ, c.input)
	}
	mainFile := filepath.Join(dir, "main.swift")
	os.WriteFile(mainFile, []byte(main.String()), 0o644)

	run := func(args ...string) {
		t.Helper()
		cmd := exec.CommandContext(t.Context(), swiftc, append([]string{"-swift-version", "6", "-module-cache-path", filepath.Join(dir, "cache")}, args...)...)
		if b, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("swiftc %s: %v\n%s", strings.Join(args, " "), err, b)
		}
	}
	lib := filepath.Join(dir, "lib")
	run("-parse-as-library", "-emit-library", "-static", "-emit-module", "-module-name", "Shared",
		"-emit-module-path", filepath.Join(lib, "Shared.swiftmodule"), "-o", filepath.Join(lib, "libShared.a"),
		filepath.Join(dir, "Shared/Money.swift"))
	args := []string{"-module-name", "API", "-I", lib, "-L", lib, "-lShared", "-o", filepath.Join(dir, "app"), mainFile}
	for _, f := range files[:3] {
		args = append(args, filepath.Join(dir, f))
	}
	run(args...)
	raw, err := exec.CommandContext(t.Context(), filepath.Join(dir, "app")).Output()
	if err != nil {
		t.Fatalf("app: %v", err)
	}
	lines := strings.Split(strings.TrimSpace(string(raw)), "\n")
	if strings.Contains(lines[13], "manager") {
		t.Errorf("a nil boxed field is encoded: %s", lines[13])
	}
	for i, c := range cases {
		if ok := strings.HasPrefix(lines[i], "ok "); ok != c.ok {
			t.Errorf("%s %s: ok=%v, want %v (%s)", c.typ, c.input, ok, c.ok, lines[i])
		}
	}
}

// TestManual renders a recursive type as a final class and drops the
// synthesized protocols, for callers who handle both themselves.
func TestManual(t *testing.T) {
	t.Parallel()
	set, err := gen.Load("../testdata/api", "../testdata/other")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	f := out.File("Types.swift", swift.New("API", swift.Indirect(""), swift.Protocols(),
		swift.Runtime(out.File("JSON.swift", swift.NewRuntime("API"))), swift.External("log/slog.Level", "String")))
	f.Place(set.Type(api, "User").Out(), "User")
	f.Place(set.Type(api, "Address").Out(), "Address")
	f.Place(set.Type(api, "Role").Out(), "Role")
	f.Place(set.Type(other, "Money").Out(), "Money")
	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(dir, "Types.swift"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"final class User: Codable {", "    var manager: User?\n", "    init(id: Int64,", "struct Address: Codable {", "enum Role: String, Codable {"} {
		if !strings.Contains(string(b), want) {
			t.Errorf("missing %q in:\n%s", want, b)
		}
	}

	swiftc := os.Getenv("GGEN_SWIFTC")
	if swiftc == "" {
		t.Skip("set GGEN_SWIFTC to a swiftc binary to compile the classes")
	}
	// A class holds itself directly, so the nesting the struct rendering has
	// to box goes through untouched.
	user := `{"id":1,"role":"admin","status":"active","created":"2020-01-01T00:00:00Z","level":"INFO",` +
		`"point":null,"money":{"amount":1,"currency":"USD"},"address":{"city":"x","zip":"12345"},"friends":null,"state":0`
	main := `import Foundation

func run() {
    do {
        let v = try JSONDecoder().decode(User.self, from: Data(` + fmt.Sprintf("%q", user+`,"manager":`+user+"}}") + `.utf8))
        print(v.manager!.id, try String(decoding: JSONEncoder().encode(v), as: UTF8.self).count > 0)
    } catch {
        print("err", error)
    }
}

run()
`
	os.WriteFile(filepath.Join(dir, "main.swift"), []byte(main), 0o644)
	compileSwift(t, swiftc, dir, "API", filepath.Join(dir, "app"), nil,
		filepath.Join(dir, "Types.swift"), filepath.Join(dir, "JSON.swift"), filepath.Join(dir, "main.swift"))
	printed, err := exec.CommandContext(t.Context(), filepath.Join(dir, "app")).Output()
	if err != nil {
		t.Fatalf("app: %v", err)
	}
	if got := strings.TrimSpace(string(printed)); got != "1 true" {
		t.Errorf("class round trip: %s", got)
	}
}

// compileSwift builds the files into an executable in Swift 6 language mode,
// which is what a caller on a current toolchain gets.
func compileSwift(t *testing.T, swiftc, dir, module, exe string, extra []string, files ...string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(exe), 0o755); err != nil {
		t.Fatal(err)
	}
	args := append([]string{
		"-swift-version", "6", "-module-cache-path", filepath.Join(dir, "cache"),
		"-module-name", module, "-o", exe,
	}, extra...)
	if b, err := exec.CommandContext(t.Context(), swiftc, append(args, files...)...).CombinedOutput(); err != nil {
		t.Fatalf("swiftc: %v\n%s", err, b)
	}
}

// TestFor decides protocols, access, recursion, headers and external types
// per package, type, directive and output file.
func TestFor(t *testing.T) {
	t.Parallel()
	set, err := gen.Load("../testdata/api", "../testdata/other")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	e := swift.New("API",
		swift.HeaderFor(func(f *gen.File) string { return "// " + f.Path }),
		swift.ProtocolsFor(func(_ *gen.File, p gen.Placed) []string {
			switch {
			case p.Shape.Decl.Pkg.Name == "other":
				return []string{"Equatable"}
			case p.Name == "Address":
				return nil
			case slices.Contains(p.Shape.Decl.Directives, "schema:out"):
				return []string{"Hashable", "Sendable"}
			}
			return []string{"Hashable"}
		}),
		swift.PublicFor(func(f *gen.File, _ gen.Placed) bool { return strings.HasPrefix(f.Path, "Public/") }),
		swift.IndirectFor(func(_ *gen.File, p gen.Placed) string {
			if p.Name == "User" {
				return ""
			}
			return "Indirect"
		}),
		swift.ExternalFor(func(f *gen.File, _ gen.Placed, t *gen.Type) (string, []string, bool) {
			return "Point", []string{"Geometry"}, t.Name == "Point" && f.Path == "Internal/User.swift"
		}),
		swift.External("log/slog.Level", "String"),
	)
	user := out.File("Internal/User.swift", e)
	user.Place(set.Type(api, "User").Out(), "User")
	user.Place(set.Type(api, "Address").Out(), "Address")
	user.Place(set.Type(api, "Role").Out(), "Role")
	out.File("Public/Money.swift", e).Place(set.Type(other, "Money").Out(), "Money")
	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	for file, wants := range map[string][]string{
		"Internal/User.swift": {"// Internal/User.swift\n", "import Geometry\n", "final class User: Codable {", "    var manager: User?\n", "    var point: Point\n", "struct Address: Codable {", "enum Role: String, Codable, Hashable {"},
		"Public/Money.swift":  {"// Public/Money.swift\n", "public struct Money: Codable, Equatable {", "    public init(amount: Int64, currency: String) {"},
	} {
		b, err := os.ReadFile(filepath.Join(dir, file))
		if err != nil {
			t.Fatal(err)
		}
		for _, want := range wants {
			if !strings.Contains(string(b), want) {
				t.Errorf("%s: missing %q in:\n%s", file, want, b)
			}
		}
	}
}

// compiles the same per-type rendering, with a stand-in for the module the
// external type comes from.
func TestForCompiles(t *testing.T) {
	t.Parallel()
	swiftc := os.Getenv("GGEN_SWIFTC")
	if swiftc == "" {
		t.Skip("set GGEN_SWIFTC to a swiftc binary")
	}
	set, err := gen.Load("../testdata/api", "../testdata/other")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	e := swift.New("API",
		swift.PublicFor(func(f *gen.File, _ gen.Placed) bool { return strings.HasPrefix(f.Path, "Public/") }),
		swift.IndirectFor(func(_ *gen.File, p gen.Placed) string {
			if p.Name == "User" {
				return "" // a class, which holds itself directly
			}
			return "Indirect"
		}),
		swift.ExternalFor(func(_ *gen.File, _ gen.Placed, t *gen.Type) (string, []string, bool) {
			return "Point", []string{"Geometry"}, t.Name == "Point"
		}),
		swift.External("log/slog.Level", "String"),
	)
	user := out.File("Internal/User.swift", e)
	user.Place(set.Type(api, "User").Out(), "User")
	user.Place(set.Type(api, "Address").Out(), "Address")
	user.Place(set.Type(api, "Role").Out(), "Role")
	out.File("Public/Money.swift", e).Place(set.Type(other, "Money").Out(), "Money")
	if err := out.Write(); err != nil {
		t.Fatal(err)
	}

	lib := filepath.Join(dir, "lib")
	os.WriteFile(filepath.Join(dir, "Geometry.swift"), []byte(
		"public struct Point: Codable, Hashable {\n    public var X: Int\n    public var Y: Int\n}\n"), 0o644)
	compileSwift(t, swiftc, dir, "Geometry", filepath.Join(lib, "libGeometry.a"),
		[]string{
			"-parse-as-library", "-emit-library", "-static", "-emit-module",
			"-emit-module-path", filepath.Join(lib, "Geometry.swiftmodule"),
		},
		filepath.Join(dir, "Geometry.swift"))
	compileSwift(t, swiftc, dir, "API", filepath.Join(lib, "libAPI.a"),
		[]string{
			"-parse-as-library", "-emit-library", "-static", "-emit-module",
			"-emit-module-path", filepath.Join(lib, "API.swiftmodule"), "-I", lib,
		},
		filepath.Join(dir, "Internal/User.swift"), filepath.Join(dir, "Public/Money.swift"))
}

// TestAwkwardNames pins the escaping a Swift property needs, the report for
// two fields that spell one property, and that the result compiles.
func TestAwkwardNames(t *testing.T) {
	t.Parallel()
	set, err := gen.Load("../testdata/api", "../testdata/other")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	out.File("Types.swift", swift.New("API")).Place(set.Type(api, "Awkward").Out(), "Awkward")
	out.File("Collides.swift", swift.New("API")).Place(set.Type(api, "Collides").Out(), "Collides")
	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(dir, "Types.swift"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"var `class`: String\n", "var `func`: String\n", "var `in`: String\n", "var val: String\n",
		"var spaced: String\n", "case spaced = \"a b\"\n", "case `class`\n",
	} {
		if !strings.Contains(string(b), want) {
			t.Errorf("missing %q in:\n%s", want, b)
		}
	}
	var issues []string
	for _, i := range out.Report().Issues {
		issues = append(issues, i.Msg)
	}
	if want := "fields id and ID both spell the property id; rename one"; !slices.Contains(issues, want) {
		t.Errorf("report = %q, want %q", issues, want)
	}
	swiftc := os.Getenv("GGEN_SWIFTC")
	if swiftc == "" {
		t.Skip("set GGEN_SWIFTC to a swiftc binary")
	}
	compileSwift(t, swiftc, dir, "API", filepath.Join(dir, "lib", "libAPI.a"),
		[]string{"-parse-as-library", "-emit-library", "-static"}, filepath.Join(dir, "Types.swift"))
}
