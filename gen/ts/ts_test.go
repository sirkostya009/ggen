// TestRuntime pins the shared helpers file zod and valibot import from.
func TestRuntime(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	out.File("shared/ggen.ts", ts.Runtime("// Code generated by ggen. DO NOT EDIT."))
	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(filepath.Join(dir, "shared/ggen.ts"))
	if err != nil {
		t.Fatal(err)
	}
	golden := filepath.Join("testdata", "shared", "ggen.ts")
	if *update {
		os.MkdirAll(filepath.Dir(golden), 0o755)
		os.WriteFile(golden, got, 0o644)
		return
	}
	if want, err := os.ReadFile(golden); err != nil || !bytes.Equal(got, want) {
		t.Errorf("ggen.ts differs from %s (run with -update):\n%s", golden, got)
	}
}

// TestFor decides headers, declaration style and external types per output
// file and placed type.
func TestFor(t *testing.T) {
	t.Parallel()
	set, err := gen.Load("../testdata/api", "../testdata/other")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	e := ts.New(
		ts.HeaderFor(func(f *gen.File) string { return "// " + f.Path }),
		ts.TypeAliasesFor(func(_ *gen.File, p gen.Placed) bool { return p.Shape.Decl.Pkg.Name == "other" }),
		ts.ExternalFor(func(f *gen.File, _ gen.Placed, t *gen.Type) (string, bool) {
			return "{ X: number; Y: number }", t.Name == "Point" && f.Path == "web.ts"
		}),
		ts.External("log/slog.Level", "string"),
	)
	web := out.File("web.ts", e)
	for _, name := range []string{"User", "Address", "Role", "Plan"} {
		web.Place(set.Type(api, name).Out(), name)
	}
	out.File("money.ts", e).Place(set.Type(other, "Money").Out(), "Money")
	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	if issues := out.Report().Issues; len(issues) != 0 {
		t.Errorf("report: %v", issues)
	}
	for file, wants := range map[string][]string{
		"web.ts":   {"// web.ts\n", "export interface User {", "  point: { X: number; Y: number };", "export interface Address {"},
		"money.ts": {"// money.ts\n", "export type Money = {"},
	} {
		b, err := os.ReadFile(filepath.Join(dir, file))
		if err != nil {
			t.Fatal(err)
		}
		for _, want := range wants {
			if !strings.Contains(string(b), want) {
				t.Errorf("%s: missing %q in:\n%s", file, want, b)
			}
		}
	}
}

// tscPath is the tsc the tests type-check with: the one GGEN_NODE_MODULES
// pins, else whatever is on PATH. It returns "" when there is neither, and
// every caller skips loudly rather than passing quietly.
func tscPath(t *testing.T) string {
	t.Helper()
	if modules := os.Getenv("GGEN_NODE_MODULES"); modules != "" {
		if path := filepath.Join(modules, ".bin", "tsc"); fileExists(path) {
			return path
		}
	}
	path, err := exec.LookPath("tsc")
	if err != nil {
		return ""
	}
	return path
}

func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}
