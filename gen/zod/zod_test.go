var update = flag.Bool("update", false, "rewrite golden files")

const (
	api   = "github.com/sirkostya009/ggen/gen/testdata/api"
	other = "github.com/sirkostya009/ggen/gen/testdata/other"
)

func render(t *testing.T) (string, *gen.Output) {
	t.Helper()
	set, err := gen.Load("../testdata/api", "../testdata/other")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	runtime := out.File("shared/ggen.ts", ts.Runtime("// Code generated by ggen. DO NOT EDIT."))
	e := zod.New(
		zod.Runtime(runtime),
		zod.Header("// Code generated by ggen. DO NOT EDIT."),
		zod.ImportExt(".ts"),
		zod.Func("IsAdult", `.refine((x) => x >= 18, "must be an adult")`),
		zod.External("log/slog.Level", "z.string()"),
	)
	requests := out.File("web/requests.ts", e)
	requests.Place(set.Type(api, "CreateUser").In(), "CreateUser")
	requests.Place(set.Type(api, "Address").In(), "AddressInput")
	requests.Place(set.Type(api, "Edges").In(), "EdgesInput")
	requests.Place(set.Type(api, "Tags").In(), "TagsInput")

	responses := out.File("web/responses.ts", e)
	responses.Place(set.Type(api, "User").Out().StrictFields("role"), "User")
	responses.Place(set.Type(api, "Address").Out(), "Address")
	responses.Place(set.Type(api, "Role").Out(), "Role")
	responses.Place(set.Type(api, "Edges").Out(), "Edges")
	responses.Place(set.Type(api, "Tags").Out(), "Tags")

	out.File("shared/money.ts", e).Place(set.Type(other, "Money").Out(), "User")

	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	return dir, out
}

func TestSchemas(t *testing.T) {
	dir, out := render(t)
	var issues []string
	for _, i := range out.Report().Issues {
		issues = append(issues, i.String())
	}
	if want := []string{"api.User.point: image.Point is external with an unknown shape; map it with zod.External or zod.ExternalFor"}; !slices.Equal(issues, want) {
		t.Errorf("report = %q, want %q", issues, want)
	}
	for _, name := range []string{"web/requests.ts", "web/responses.ts", "shared/money.ts"} {
		got, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		golden := filepath.Join("testdata", name)
		if *update {
			os.MkdirAll(filepath.Dir(golden), 0o755)
			os.WriteFile(golden, got, 0o644)
			continue
		}
		want, err := os.ReadFile(golden)
		if err != nil {
			t.Fatalf("%v (run with -update)", err)
		}
		if string(got) != string(want) {
			t.Errorf("%s differs from %s:\n%s", name, golden, got)
		}
	}
}

// TestRuntime type-checks the schemas and runs inputs through them. It needs
// GGEN_NODE_MODULES: a node_modules directory with zod and typescript.
func TestRuntime(t *testing.T) {
	modules := os.Getenv("GGEN_NODE_MODULES")
	node, err := exec.LookPath("node")
	if modules == "" || err != nil {
		t.Skip("set GGEN_NODE_MODULES to a node_modules with zod and typescript, and put node on PATH")
	}
	dir, _ := render(t)
	if err := os.Symlink(modules, filepath.Join(dir, "node_modules")); err != nil {
		t.Fatal(err)
	}
	cfg := `{"compilerOptions":{"strict":true,"noEmit":true,"target":"ES2022","lib":["ES2022","DOM"],"module":"ESNext","moduleResolution":"Bundler","allowImportingTsExtensions":true,"skipLibCheck":true},"include":["web/*.ts","shared/*.ts"]}`
	os.WriteFile(filepath.Join(dir, "tsconfig.json"), []byte(cfg), 0o644)
	if b, err := exec.Command(filepath.Join(modules, ".bin", "tsc"), "-p", dir).CombinedOutput(); err != nil {
		t.Fatalf("tsc: %v\n%s", err, b)
	}

	user := func(extra string) string {
		return `{"id":1,"role":"admin","status":"active","created":"2020-01-01T00:00:00Z","level":"INFO","point":{"X":1},` +
			`"money":{"amount":1,"currency":"USD"},"address":{"city":"x","zip":"12345"},"friends":null,"state":0` + extra + `}`
	}
	cases := []struct {
		file, schema, input string
		ok                  bool
	}{
		{"web/requests.ts", "CreateUser", `{"name":"  a  ","email":"A@B"}`, true},
		{"web/requests.ts", "CreateUser", `{}`, false},
		{"web/requests.ts", "CreateUser", `{"name":"   ","email":"a@b"}`, false},
		{"web/requests.ts", "CreateUser", `{"name":"ab","email":"ab"}`, false},
		{"web/requests.ts", "CreateUser", `{"name":"ab","email":"a@b","age":null}`, true},
		{"web/requests.ts", "CreateUser", `{"name":"ab","email":"a@b","age":17}`, false},
		{"web/requests.ts", "CreateUser", `{"name":"ab","email":"a@b","extra":1}`, false},
		{"web/requests.ts", "CreateUser", `{"name":"ab","email":"a@b","address":{"city":"x"}}`, true},
		{"web/requests.ts", "CreateUser", `{"name":"ab","email":"a@b","address":{}}`, false},
		{"web/requests.ts", "EdgesInput", `{"list":null}`, false},
		{"web/requests.ts", "EdgesInput", `{"list":[""]}`, false},
		{"web/requests.ts", "EdgesInput", `{"list":["a"],"plist":null}`, true},
		{"web/requests.ts", "EdgesInput", `{"dict":{"a":1}}`, false},
		{"web/requests.ts", "EdgesInput", `{"dict":{"ab":0}}`, false},
		{"web/requests.ts", "EdgesInput", `{"quoted":"-128"}`, true},
		{"web/requests.ts", "EdgesInput", `{"quoted":"128"}`, false},
		{"web/requests.ts", "EdgesInput", `{"unix":1.5}`, false},
		{"web/requests.ts", "EdgesInput", `{"fixed":"AQIDBA=="}`, true},
		{"web/requests.ts", "EdgesInput", `{"fixed":"AQID"}`, false},
		{"web/requests.ts", "EdgesInput", `{"ip":"","addr":"fe80::1%eth0"}`, true},
		{"web/requests.ts", "EdgesInput", `{"ip":"fe80::1%eth0"}`, false},
		{"web/requests.ts", "EdgesInput", `{"lower":"X"}`, true},
		{"web/requests.ts", "EdgesInput", `{"lower":"Z"}`, false},
		{"web/requests.ts", "EdgesInput", `{"conv":"12","nz":null}`, true},
		{"web/requests.ts", "EdgesInput", `{"zzz":"s"}`, true},
		{"web/requests.ts", "EdgesInput", `{"zzz":1}`, false},
		{"web/responses.ts", "User", user(``), true},
		{"web/responses.ts", "User", user(`,"manager":` + user(``)), true},
		{"web/responses.ts", "User", strings.Replace(user(``), `"role":"admin"`, `"role":""`, 1), false},
		{"web/responses.ts", "User", strings.Replace(user(``), `"status":"active"`, `"status":""`, 1), true},
		{"web/responses.ts", "User", user(`,"plan":0`), false},
		{"shared/money.ts", "User", `{"amount":1,"currency":""}`, true},
	}
	type jsCase struct{ File, Schema, Input string }
	var in []jsCase
	for _, c := range cases {
		in = append(in, jsCase{filepath.Join(dir, c.file), c.schema, c.input})
	}
	payload, _ := json.Marshal(in)
	script := `
const cases = JSON.parse(await new Promise((r) => { let s = ""; process.stdin.on("data", (d) => (s += d)); process.stdin.on("end", () => r(s)); }));
const out = [];
for (const c of cases) {
  const mod = await import("file://" + c.File);
  const r = mod[c.Schema].safeParse(JSON.parse(c.Input));
  out.push(r.success ? "" : r.error.message);
}
console.log(JSON.stringify(out));
`
	os.WriteFile(filepath.Join(dir, "run.mjs"), []byte(script), 0o644)
	cmd := exec.Command(node, filepath.Join(dir, "run.mjs"))
	cmd.Stdin = strings.NewReader(string(payload))
	raw, err := cmd.Output()
	if err != nil {
		t.Fatalf("node: %v", err)
	}
	var got []string
	if err := json.Unmarshal(raw, &got); err != nil {
		t.Fatalf("%v: %s", err, raw)
	}
	for i, c := range cases {
		if ok := got[i] == ""; ok != c.ok {
			t.Errorf("%s %s: ok=%v, want %v (%s)", c.schema, c.input, ok, c.ok, strings.Join(strings.Fields(got[i]), " "))
		}
	}
}

// TestFor decides headers, schema names, @Func twins and external types per
// output file and placed type.
func TestFor(t *testing.T) {
	set, err := gen.Load("../testdata/api", "../testdata/other")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	e := zod.New(
		zod.ImportExt(".ts"),
		zod.HeaderFor(func(f *gen.File) string { return "// " + f.Path }),
		zod.SchemaName(func(f *gen.File, p gen.Placed) string {
			if strings.HasPrefix(f.Path, "shared/") {
				return p.Shape.Decl.Pkg.Name + p.Name + "Schema"
			}
			return p.Name + "Schema"
		}),
		zod.Func(api+".IsAdult", `.refine((x) => x === null || x >= 18)`),
		zod.FuncFor(func(f *gen.File, p gen.Placed, r gen.Rule) (string, bool) {
			return `.refine((x) => x === null || x >= 21)`, f.Path == "strict/users.ts" && r.Func == "IsAdult"
		}),
		zod.ExternalFor(func(_ *gen.File, p gen.Placed, t *gen.Type) (string, bool) {
			return "z.object({ X: z.int(), Y: z.int() })", t.Name == "Point" && p.Name == "User"
		}),
		zod.External("log/slog.Level", "z.string()"),
	)
	web := out.File("web/users.ts", e)
	web.Place(set.Type(api, "CreateUser").In(), "CreateUser")
	web.Place(set.Type(api, "Address").In(), "AddressInput")
	web.Place(set.Type(api, "User").Out(), "User")
	web.Place(set.Type(api, "Address").Out(), "Address")
	web.Place(set.Type(api, "Role").Out(), "Role")
	web.Place(set.Type(api, "Plan").Out(), "Plan")
	out.File("shared/money.ts", e).Place(set.Type(other, "Money").Out(), "Money")
	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	if issues := out.Report().Issues; len(issues) != 0 {
		t.Errorf("report: %v", issues)
	}
	strict := gen.NewOutput(dir)
	strict.File("strict/users.ts", e).Place(set.Type(api, "CreateUser").In(), "CreateUser").Place(set.Type(api, "Address").In(), "AddressInput")
	if err := strict.Write(); err != nil {
		t.Fatal(err)
	}
	for file, wants := range map[string][]string{
		"web/users.ts":    {"// web/users.ts\n", "export const CreateUserSchema = ", "x >= 18)", "point: z.object({ X: z.int(), Y: z.int() })", `import { otherMoneySchema } from "../shared/money.ts";`, "money: otherMoneySchema,"},
		"shared/money.ts": {"// shared/money.ts\n", "export const otherMoneySchema = "},
		"strict/users.ts": {"x >= 21)"},
	} {
		b, err := os.ReadFile(filepath.Join(dir, file))
		if err != nil {
			t.Fatal(err)
		}
		for _, want := range wants {
			if !strings.Contains(string(b), want) {
				t.Errorf("%s: missing %q in:\n%s", file, want, b)
			}
		}
	}
}
