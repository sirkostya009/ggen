// TestFor pins the ...For options that decide headers, schema names, @Func
// actions and external types per output file and placed type.
func TestFor(t *testing.T) {
	t.Parallel()
	set, err := gen.Load("../testdata/api", "../testdata/other")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	e := zod.New(
		zod.ImportExt(".ts"),
		zod.HeaderFor(func(f *gen.File) string { return "// " + f.Path }),
		zod.SchemaName(func(f *gen.File, p gen.Placed) string {
			if strings.HasPrefix(f.Path, "shared/") {
				return p.Shape.Decl.Pkg.Name + p.Name + "Schema"
			}
			return p.Name + "Schema"
		}),
		zod.Func(api+".IsAdult", `.refine((x) => x === null || x >= 18)`),
		zod.FuncFor(func(f *gen.File, p gen.Placed, r gen.Rule) (string, bool) {
			return `.refine((x) => x === null || x >= 21)`, f.Path == "strict/users.ts" && r.Func == "IsAdult"
		}),
		zod.ExternalFor(func(_ *gen.File, p gen.Placed, t *gen.Type) (string, bool) {
			return "z.object({ X: z.int(), Y: z.int() })", t.Name == "Point" && p.Name == "User"
		}),
		zod.External("log/slog.Level", "z.string()"),
	)
	web := out.File("web/users.ts", e)
	web.Place(set.Type(api, "CreateUser").In(), "CreateUser")
	web.Place(set.Type(api, "Address").In(), "AddressInput")
	web.Place(set.Type(api, "User").Out(), "User")
	web.Place(set.Type(api, "Address").Out(), "Address")
	web.Place(set.Type(api, "Role").Out(), "Role")
	web.Place(set.Type(api, "Plan").Out(), "Plan")
	out.File("shared/money.ts", e).Place(set.Type(other, "Money").Out(), "Money")
	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	if issues := out.Report().Issues; len(issues) != 0 {
		t.Errorf("report: %v", issues)
	}
	strict := gen.NewOutput(dir)
	strict.File("strict/users.ts", e).Place(set.Type(api, "CreateUser").In(), "CreateUser").Place(set.Type(api, "Address").In(), "AddressInput")
	if err := strict.Write(); err != nil {
		t.Fatal(err)
	}
	for file, wants := range map[string][]string{
		"web/users.ts":    {"// web/users.ts\n", "export const CreateUserSchema = ", "x >= 18)", "point: z.object({ X: z.int(), Y: z.int() })", `import { otherMoneySchema, type Money } from "../shared/money.ts";`, "money: otherMoneySchema,"},
		"shared/money.ts": {"// shared/money.ts\n", "export const otherMoneySchema = "},
		"strict/users.ts": {"x >= 21)"},
	} {
		b, err := os.ReadFile(filepath.Join(dir, file))
		if err != nil {
			t.Fatal(err)
		}
		for _, want := range wants {
			if !strings.Contains(string(b), want) {
				t.Errorf("%s: missing %q in:\n%s", file, want, b)
			}
		}
	}
}

// TestRecursiveAlias pins that an alias or a catch-all reaching itself is
// annotated with its type and defers the reference through z.lazy.
func TestRecursiveAlias(t *testing.T) {
	t.Parallel()
	const rec = "github.com/sirkostya009/ggen/gen/testdata/shapes"
	set, err := gen.Load("../testdata/shapes")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	out := gen.NewOutput(dir)
	f := out.File("rec.ts", zod.New())
	for _, n := range []string{"Tree", "Obj", "Bag"} {
		f.Place(set.Type(rec, n).In(), n)
	}
	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(dir, "rec.ts"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"export const Tree: z.ZodType<Tree> = z.array(z.lazy(() => Tree)).nullable();",
		"export const Obj: z.ZodType<Obj> = z.record(z.string(), z.lazy(() => Obj)).nullable();",
		".catchall(z.lazy(() => Bag));",
	} {
		if !strings.Contains(string(b), want) {
			t.Errorf("missing %q in\n%s", want, b)
		}
	}
}

// TestPrototypeFields pins the report for fields Object.prototype shadows.
func TestPrototypeFields(t *testing.T) {
	t.Parallel()
	set, err := gen.Load("../testdata/shapes")
	if err != nil {
		t.Fatal(err)
	}
	out := gen.NewOutput(t.TempDir())
	out.File("proto.ts", zod.New()).Place(set.Type("github.com/sirkostya009/ggen/gen/testdata/shapes", "Proto").In(), "Proto")
	if err := out.Write(); err != nil {
		t.Fatal(err)
	}
	var issues []string
	for _, i := range out.Report().Issues {
		issues = append(issues, i.String())
	}
	if want := []string{
		"shapes.Proto.__proto__: zod never checks a field named __proto__ and drops it from the parsed value",
		"shapes.Proto.constructor: Object.prototype defines constructor, and zod tests key presence with `in`, so the field can never be absent",
	}; !slices.Equal(issues, want) {
		t.Errorf("report = %q, want %q", issues, want)
	}
}
